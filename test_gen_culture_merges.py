def unwrap(value):
    while isinstance(value, (list, tuple)) and len(value) == 2 and value[0] in ("=", "?="):
        value = value[1]
    return value


def parse(path):
    parser = ParadoxFileParser()
    parser.parse_file(str(path))
    return {key: unwrap(value) for key, value in parser.data.items()}


def deep(value):
    """``value`` with every `=` wrapper removed, at every depth."""
    value = unwrap(value)
    return {k: deep(v) for k, v in value.items()} if isinstance(value, dict) else value


def field(body, name):
    return unwrap(body.get(name))


_VANILLA = None


def vanilla():
    """Vanilla cultures (plus "__traits__") and the parsed snapshot, loaded once."""
    global _VANILLA
    if _VANILLA is None:
        data = vanilla_parsed.load(str(ROOT / "vanilla_parsed")).data
        cultures = dict(data["Cultures"])
        cultures["__traits__"] = dict(data["Discrimination Traits"])
        _VANILLA = cultures
    return _VANILLA


def _vanilla_fields(body):
    fields = unwrap(body)
    return fields if isinstance(fields, dict) else ()


def core_heritages(merge):
    """The heritage traits of the merge's core parts."""
    return {cfg.culture_traits(part.cultures[0], vanilla(), cfg.MERGES)[0] for part in merge.core}


def start_tier(merge):
    return max(cfg.derive_tier(merge, part.cultures[0], vanilla()) for part in merge.core)


