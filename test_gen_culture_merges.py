class CultureTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cultures = parse(CULTURES)
        cls.traits = parse(TRAITS)
        cls.vanilla = vanilla()

    def vanilla_names(self, culture, name_list):
        return unwrap(unwrap(self.vanilla[culture]).get(name_list)) or []

    def test_one_culture_per_new_result_in_config_order(self):
        results = [m.result for m in cfg.MERGES if m.new is not None]
        self.assertEqual(list(self.cultures), results)
        self.assertTrue(all(c.startswith("cm_") for c in self.cultures))

    def test_german_culture(self):
        german = self.cultures["cm_german"]
        self.assertEqual(field(german, "heritage"), "heritage_germanic")
        self.assertEqual(field(german, "language"), "language_germanophone")
        names = field(german, "male_common_first_names")
        for name in self.vanilla_names("north_german", "male_common_first_names"):
            self.assertIn(name, names)

    def test_color_comes_from_the_config(self):
        self.assertEqual(field(self.cultures["cm_german"], "color"), "rgb{ 118 120 128 }")
        for merge in cfg.MERGES:
            if merge.new is not None:
                r, g, b = merge.new.color
                self.assertEqual(field(self.cultures[merge.result], "color"), f"rgb{{ {r} {g} {b} }}", merge.key)

    def test_a_result_takes_the_first_core_part(self):
        # Anglophone's first core part is British; Latin's is French.
        british = unwrap(self.vanilla["british"])
        anglophone = self.cultures["cm_anglophone"]
        for name in ("religion", "heritage", "language", "graphics"):
            self.assertEqual(field(anglophone, name), field(british, name), name)
        self.assertEqual(field(anglophone, "ethnicities"), field(british, "ethnicities"))
        french = unwrap(self.vanilla["french"])
        latin = self.cultures["cm_latin"]
        self.assertEqual(field(latin, "religion"), field(french, "religion"))
        self.assertEqual(field(latin, "graphics"), field(french, "graphics"))

    def test_obsessions_come_from_the_first_core_part(self):
        self.assertEqual(
            field(self.cultures["cm_german"], "obsessions"),
            unwrap(unwrap(self.vanilla["north_german"]).get("obsessions")),
        )

    def test_a_result_built_on_a_result_takes_that_results_first_part(self):
        # Pan-Slavic's first core part is cm_east_slavic, whose first is Russian.
        russian = unwrap(self.vanilla["russian"])
        slavic = self.cultures["cm_pan_slavic"]
        self.assertEqual(field(slavic, "religion"), field(russian, "religion"))
        self.assertEqual(field(slavic, "graphics"), field(russian, "graphics"))

    def test_names_merge_every_part_in_config_order_without_duplicates(self):
        merge = cfg.merge_by_key("german")
        merged = field(self.cultures["cm_german"], "male_common_first_names")
        self.assertEqual(len(merged), len(set(merged)))
        expected = []
        for part in merge.core + merge.optional:
            for name in self.vanilla_names(part.cultures[0], "male_common_first_names"):
                if name not in expected:
                    expected.append(name)
        self.assertEqual(merged, expected)

    def test_names_of_a_result_part_are_those_of_its_parts(self):
        # Latin lists cm_italian, itself built from North and South Italian.
        merged = field(self.cultures["cm_latin"], "common_last_names")
        for culture in ("french", "north_italian", "south_italian", "spanish", "portuguese", "romanian"):
            for name in self.vanilla_names(culture, "common_last_names"):
                self.assertIn(name, merged, culture)

    def test_gendered_surnames_only_where_a_part_has_them(self):
        # Only the East Slavic cultures (and what is built on them) have gendered surnames.
        with_female = {c for c, body in self.cultures.items() if field(body, "female_common_last_names")}
        self.assertEqual(with_female, {"cm_east_slavic", "cm_pan_slavic"})
        # Pan-Slavic's women draw on the Czech, Slovak, Serb ... surnames too (those
        # cultures name their women from the plain list), and on Russian women's own.
        female = field(self.cultures["cm_pan_slavic"], "female_common_last_names")
        for culture in ("czech", "slovak", "serb"):
            for name in self.vanilla_names(culture, "common_last_names"):
                self.assertIn(name, female, culture)
        for name in self.vanilla_names("russian", "female_common_last_names"):
            self.assertIn(name, female)

    def test_name_format_and_seal_follow_the_first_core_part(self):
        # Dravidian's first core part, Tamil, writes surnames first; German's North German does not.
        self.assertEqual(field(unwrap(self.vanilla["tamil"]), "name_format"), "last_first")
        self.assertEqual(field(self.cultures["cm_dravidian"], "name_format"), "last_first")
        self.assertNotIn("name_format", self.cultures["cm_german"])
        # Latin's first core part is French, which has its own treaty seal.
        seal = field(unwrap(self.vanilla["french"]), "seal_and_signature_texture")
        self.assertEqual(field(self.cultures["cm_latin"], "seal_and_signature_texture"), seal)
        for result, body in self.cultures.items():
            first = cfg.merge_by_key(result.removeprefix("cm_")).core[0].cultures[0]
            first_body = unwrap(self.vanilla[first]) if first in self.vanilla else self.cultures[first]
            self.assertEqual("name_format" in body, "name_format" in first_body, result)
            self.assertEqual("seal_and_signature_texture" in body, "seal_and_signature_texture" in first_body, result)

    def test_every_field_a_vanilla_culture_has_is_carried(self):
        used = {name for key, body in self.vanilla.items() if key != cfg.TRAITS_KEY for name in _vanilla_fields(body)}
        self.assertEqual(used - gen.CARRIED_FIELDS, set(), "a vanilla patch added a culture field gen_culture_merges does not know")

    def test_every_result_has_the_required_name_lists(self):
        for result, body in self.cultures.items():
            for name in ("male_common_first_names", "female_common_first_names", "common_last_names"):
                self.assertTrue(field(body, name), f"{result} has no {name}")


class TraitTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cultures = parse(CULTURES)
        cls.traits = parse(TRAITS)

    def test_latin_traits(self):
        language = self.traits["language_cm_latin"]
        self.assertEqual(field(language, "type"), "language")
        self.assertEqual(field(language, "trait_group"), "language_group_romance")
        heritage = self.traits["heritage_cm_latin"]
        self.assertEqual(field(heritage, "type"), "heritage")
        self.assertEqual(field(heritage, "trait_group"), "heritage_group_european")

    def test_a_language_trait_goes_to_every_merge_that_starts_at_tier_3(self):
        starts = [m for m in cfg.MERGES if m.new is not None and start_tier(m) == 3]
        self.assertEqual(
            sorted(m.key for m in starts),
            ["east_african", "latin", "pan_malay", "pan_slavic", "pan_turkic"],
        )
        languages = {key for key in self.traits if key.startswith("language_")}
        self.assertEqual(languages, {f"language_cm_{m.key}" for m in starts})

    def test_unshared_heritage_gets_a_minted_trait(self):
        # R16, the branch that mints: Latin's core heritages are gallic, italic and iberian.
        for key in ("latin", "pan_slavic", "pan_turkic"):
            merge = cfg.merge_by_key(key)
            self.assertGreater(len(core_heritages(merge)), 1, key)
            self.assertIn(f"heritage_cm_{key}", self.traits, key)
            self.assertEqual(field(self.cultures[merge.result], "heritage"), f"heritage_cm_{key}", key)

    def test_a_shared_heritage_is_reused_not_minted(self):
        # R16, the branch that reuses: East African's core parts all have heritage_eastern_bantu.
        for key, heritage in (("east_african", "heritage_eastern_bantu"), ("pan_malay", "heritage_insulindian")):
            merge = cfg.merge_by_key(key)
            self.assertEqual(core_heritages(merge), {heritage}, key)
            self.assertNotIn(f"heritage_cm_{key}", self.traits, key)
            self.assertEqual(field(self.cultures[merge.result], "heritage"), heritage, key)
            # ... while the language trait is still minted
            self.assertEqual(field(self.cultures[merge.result], "language"), f"language_cm_{key}", key)

    def test_the_traits_are_exactly_the_minted_ones(self):
        expected = set()
        for merge in cfg.MERGES:
            if merge.new is not None and start_tier(merge) == 3:
                expected.add(f"language_cm_{merge.key}")
                if len(core_heritages(merge)) > 1:
                    expected.add(f"heritage_cm_{merge.key}")
        self.assertEqual(set(self.traits), expected)
        self.assertEqual(len(expected), 8)

    def test_a_culture_below_tier_3_uses_no_minted_trait(self):
        for merge in cfg.MERGES:
            if merge.new is not None and start_tier(merge) < 3:
                body = self.cultures[merge.result]
                self.assertNotIn("_cm_", field(body, "language"), merge.key)
                self.assertNotIn("_cm_", field(body, "heritage"), merge.key)

    def test_east_african_has_a_trait_without_components(self):
        merge = cfg.merge_by_key("east_african")
        self.assertEqual(merge.components, ())
        self.assertEqual(field(self.traits["language_cm_east_african"], "trait_group"), "language_group_bantu")

    def test_heritage_group_falls_back_to_the_first_core_part_when_none_is_shared(self):
        # Pan-Turkic's parts span middle eastern, central Asian and European heritage groups.
        self.assertEqual(
            field(self.traits["heritage_cm_pan_turkic"], "trait_group"), "heritage_group_middle_eastern"
        )
        self.assertEqual(field(self.traits["language_cm_pan_turkic"], "trait_group"), "language_group_turkic")

    def test_every_trait_group_is_a_vanilla_group(self):
        vanilla_traits = vanilla()["__traits__"]
        groups = {
            "language": {field(unwrap(t), "trait_group") for k, t in vanilla_traits.items() if k.startswith("language_")},
            "heritage": {field(unwrap(t), "trait_group") for k, t in vanilla_traits.items() if k.startswith("heritage_")},
        }
        for key, body in self.traits.items():
            kind = field(body, "type")
            self.assertIn(field(body, "trait_group"), groups[kind], key)

    def test_the_new_traits_do_not_clash_with_vanilla(self):
        self.assertFalse(set(self.traits) & set(vanilla()["__traits__"]))


class StaticModifierTest(unittest.TestCase):
    """The engine expects six static modifiers of every culture and logs `Missing expected culture static modifier` at
    load for each one a culture lacks (126 lines for the 21 results, 2026-11-08)."""

    @classmethod
    def setUpClass(cls):
        cls.mods = parse(STATIC_MODIFIERS)
        cls.vanilla_mods = vanilla_parsed.load(str(ROOT / "vanilla_parsed")).data["Modifiers"]

    def test_vanilla_gives_every_culture_the_six(self):
        # The family the generator writes is the one vanilla gives each of its cultures.
        for culture in vanilla_parsed.load(str(ROOT / "vanilla_parsed")).data["Cultures"]:
            for key in gen.culture_static_modifier_keys(culture):
                self.assertIn(key, self.vanilla_mods, key)

    def test_every_new_result_has_the_six_in_vanillas_shape(self):
        news = [merge.result for merge in cfg.MERGES if merge.new is not None]
        self.assertEqual(len(news), 21)
        expected = {key for culture in news for key in gen.culture_static_modifier_keys(culture)}
        self.assertEqual(set(self.mods), expected)
        for culture in news:
            for vanilla_key, key in zip(gen.culture_static_modifier_keys("scottish"), gen.culture_static_modifier_keys(culture)):
                vanilla_body = {k: unwrap(v) for k, v in unwrap(self.vanilla_mods[vanilla_key]).items()}
                body = {k: unwrap(v) for k, v in self.mods[key].items()}
                self.assertEqual({k.replace("scottish", culture): v for k, v in vanilla_body.items()}, body, key)

    def test_the_file_has_one_bom(self):
        data = STATIC_MODIFIERS.read_bytes()
        self.assertTrue(data.startswith(BOM))
        self.assertFalse(data[3:].startswith(BOM))


class ModifierTypeTest(unittest.TestCase):
    """The engine creates no modifier type for a culture: vanilla registers three for each of its own, and a static
    modifier naming an unregistered one logs `Unknown modifier type` at load and loads empty (126 lines, the first
    launch after the static modifiers, 2026-11-08)."""

    @classmethod
    def setUpClass(cls):
        cls.types = parse(MODIFIER_TYPES)
        snapshot = vanilla_parsed.load(str(ROOT / "vanilla_parsed")).data
        cls.vanilla_types = snapshot["Modifier Types"]
        cls.vanilla_cultures = snapshot["Cultures"]

    def test_vanilla_registers_the_three_for_every_culture(self):
        for culture in self.vanilla_cultures:
            for name in gen.culture_modifier_types(culture):
                self.assertIn(name, self.vanilla_types, name)

    def test_every_new_result_has_the_three_in_vanillas_shape(self):
        news = [merge.result for merge in cfg.MERGES if merge.new is not None]
        self.assertEqual(set(self.types), {name for culture in news for name in gen.culture_modifier_types(culture)})
        for culture in news:
            for vanilla_name, name in zip(gen.culture_modifier_types("scottish"), gen.culture_modifier_types(culture)):
                self.assertEqual(deep(self.vanilla_types[vanilla_name]), deep(self.types[name]), name)

    def test_every_static_modifier_field_is_a_generated_type(self):
        for key, body in parse(STATIC_MODIFIERS).items():
            for name in body:
                if name != "icon":
                    self.assertIn(name, self.types, key)

    def test_no_type_clashes_with_vanilla(self):
        self.assertFalse(set(self.types) & set(self.vanilla_types))


