class TraditionsTest(unittest.TestCase):
    """A result keeps the traditions every core part has."""

    GERMAN = (cfg.merge_by_key("german"),)
    SCANDINAVIAN = (cfg.merge_by_key("scandinavian"),)

    def plan(self, merges, traditions):
        cultures = dict(vanilla())
        for culture, names in traditions.items():
            body = dict(unwrap(cultures[culture]))
            body["traditions"] = ("=", list(names))
            cultures[culture] = ("=", body)
        return {entry.merge.result: entry for entry in gen.build_plan(cultures, merges)}

    def test_a_tradition_every_core_part_has_is_kept(self):
        plan = self.plan(self.GERMAN, {"north_german": ["tradition_y", "tradition_x"], "south_german": ["tradition_x"]})
        self.assertEqual(plan["cm_german"].fields["traditions"], ["tradition_x"])
        self.assertIn("\ttraditions = { tradition_x }\n", gen.render_culture(plan["cm_german"]))

    def test_the_order_is_the_first_core_parts(self):
        both = ["tradition_a", "tradition_b"]
        plan = self.plan(self.GERMAN, {"north_german": both, "south_german": list(reversed(both))})
        self.assertEqual(plan["cm_german"].fields["traditions"], both)

    def test_a_tradition_one_core_part_lacks_is_dropped(self):
        plan = self.plan(self.GERMAN, {"north_german": ["tradition_x"]})
        self.assertEqual(plan["cm_german"].fields["traditions"], [])
        self.assertIn("\ttraditions = { }\n", gen.render_culture(plan["cm_german"]))
        plan = self.plan(self.GERMAN, {"south_german": ["tradition_x"]})
        self.assertEqual(plan["cm_german"].fields["traditions"], [])

    def test_every_core_part_counts(self):
        three = {"swedish": ["tradition_x"], "danish": ["tradition_x"], "norwegian": ["tradition_x"]}
        self.assertEqual(self.plan(self.SCANDINAVIAN, three)["cm_scandinavian"].fields["traditions"], ["tradition_x"])
        del three["norwegian"]
        self.assertEqual(self.plan(self.SCANDINAVIAN, three)["cm_scandinavian"].fields["traditions"], [])

    def test_an_optional_part_does_not_count(self):
        # Alemannic and East German are optional German parts: their traditions add nothing,
        # and a tradition they lack takes nothing away.
        plan = self.plan(self.GERMAN, {"north_german": ["tradition_x"], "south_german": ["tradition_x"]})
        self.assertEqual(unwrap(unwrap(vanilla()["alemannic"]).get("traditions")), ["tradition_helvetic"])
        self.assertEqual(plan["cm_german"].fields["traditions"], ["tradition_x"])

    def test_the_committed_cultures_carry_only_shared_traditions(self):
        cultures = parse(CULTURES)
        for merge in cfg.MERGES:
            if merge.new is None:
                continue
            core = [unwrap(vanilla()[p.cultures[0]]) if p.cultures[0] in vanilla() else None for p in merge.core]
            if None in core:
                continue  # a core part that is itself a result: covered by the build
            shared = set.intersection(*(set(unwrap(c.get("traditions")) or []) for c in core))
            written = unwrap(cultures[merge.result].get("traditions")) or []
            self.assertEqual(set(written if isinstance(written, list) else []), shared, merge.key)


class MechanicsTest(unittest.TestCase):
    def test_merged_names_skip_a_part_without_the_list(self):
        cultures = {
            "a": ["=", {"noble_last_names": ["=", ["Ash", "Birch"]]}],
            "b": ["=", {}],
            "c": ["=", {"noble_last_names": ["=", ["Birch", "Cedar"]]}],
        }
        self.assertEqual(gen.merged_names(["a", "b", "c"], "noble_last_names", cultures), ["Ash", "Birch", "Cedar"])
        self.assertEqual(gen.merged_names(["b"], "noble_last_names", cultures), [])

    def test_a_part_without_a_gendered_surname_list_lends_its_plain_one(self):
        cultures = {
            "a": ["=", {"common_last_names": ["=", ["Aov"]], "female_common_last_names": ["=", ["Aova"]]}],
            "b": ["=", {"common_last_names": ["=", ["Bov", "Aov"]]}],
            "c": ["=", {}],
        }
        self.assertEqual(gen.merged_names(["a", "b", "c"], "female_common_last_names", cultures), ["Aova", "Bov", "Aov"])
        self.assertEqual(gen.merged_names(["a", "b", "c"], "common_last_names", cultures), ["Aov", "Bov"])

    def test_a_list_a_vanilla_file_wrote_twice_is_read_once(self):
        # Vanilla's Marathi repeats three name lists, which the parser nests.
        cultures = {"m": ["=", {"noble_last_names": ["=", ["=", ["Ali", "Sultan"]]]}]}
        self.assertEqual(gen.merged_names(["m"], "noble_last_names", cultures), ["Ali", "Sultan"])

    def test_names_are_wrapped_in_tabbed_lines(self):
        text = gen.render_name_list("male_common_first_names", [f"Name{n}" for n in range(60)])
        lines = text.splitlines()
        self.assertEqual(lines[0], "\tmale_common_first_names = {")
        self.assertEqual(lines[-1], "\t}")
        self.assertTrue(all(line.startswith("\t\t") and len(line) < 110 for line in lines[1:-1]))
        self.assertEqual(" ".join(line.strip() for line in lines[1:-1]).split(), [f"Name{n}" for n in range(60)])

    def test_a_name_that_is_not_a_bare_token_is_quoted(self):
        text = gen.render_name_list("noble_last_names", ["von Moltke", "Plain"])
        self.assertIn('"von Moltke"', text)
        self.assertNotIn('"Plain"', text)

    def test_a_name_with_a_quote_mark_is_refused(self):
        with self.assertRaises(ValueError):
            gen.render_name_list("noble_last_names", ['O"Neil'])

    def test_regenerate_writes_on_change_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            os.symlink(ROOT / "vanilla_parsed", root / "vanilla_parsed")
            first = gen.regenerate(root=root)
            self.assertTrue(first["changed"])
            self.assertEqual(sorted(first["changed_files"]), sorted(str(p) for p in gen.plan_outputs(root)))
            for relative in gen.plan_outputs(root):
                self.assertTrue((root / relative).read_bytes().startswith(BOM))
            self.assertFalse(gen.regenerate(root=root)["changed"])
            victim = root / sorted(gen.plan_outputs(root))[0]
            victim.write_bytes(victim.read_bytes() + b"# edited\n")
            self.assertTrue(gen.regenerate(root=root, dry_run=True)["changed"])
            self.assertTrue(victim.read_bytes().endswith(b"# edited\n"))  # a dry run writes nothing
            self.assertTrue(gen.regenerate(root=root)["changed"])
            self.assertFalse(gen.regenerate(root=root)["changed"])

    def test_the_outputs_match_the_committed_ones(self):
        for relative, text in gen.plan_outputs().items():
            self.assertEqual((ROOT / relative).read_bytes(), text.encode("utf-8-sig"), relative)

    def test_a_bad_roster_stops_the_generator(self):
        broken = (
            cfg.Merge("x", "cm_x", cfg.NewCulture("X", (1, 2, 3)), core=(cfg.Part(("not_a_culture",)),)),
        )
        with self.assertRaises(ValueError):
            gen.build_plan(vanilla(), broken)


