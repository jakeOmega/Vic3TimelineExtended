"""The construction list's figure column for National Parks and Public Housing
(gui/00_te_build_list_columns.gui, generated by
scripts/generators/gen_build_list_columns.py; a Workshop request, 2026-11-15).

What the engine would never report:

- A redefined vanilla type that differs from vanilla outside its marked
  blocks: a vanilla patch merged into the fixture but not regenerated, or a
  hand edit.
- A building with a column of its own that still shows productivity too, in
  the cell or in either header row, or that has no cell or header: both
  would draw in the same slot, or the slot would be empty.
- A cell that reads something its datacontext doesn't have, a tooltip key no
  loc file defines, or a script value that doesn't exist: the cell or the
  tooltip renders blank or as a raw key, with no log line.
- A column for a military building: vanilla draws the cell only for a
  non-military one, so it would never show.

No game install needed; the fixture check skips without one.
"""
import json
import os
import re
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from gui_test_helpers import load_loc  # noqa: E402
from scripts.generators import gen_build_list_columns as gen  # noqa: E402

VANILLA_LOC = ROOT / "vanilla_parsed" / "localization_english.json"
VANILLA_GROUPS = ROOT / "vanilla_parsed" / "common" / "building_groups.json"


def _read(path):
    return Path(path).read_text(encoding="utf-8-sig")


def _ours():
    return _read(gen.OUT)


def _type_lines(text, name):
    lines = text.splitlines()
    start, end = gen.type_span(lines, name)
    return lines[start:end + 1]


def _mod_blocks(lines):
    """[(start, end)] of each `### MOD: Build list columns` block, inclusive."""
    spans, start = [], None
    for i, line in enumerate(lines):
        if line.strip().startswith(gen.MOD_OPEN):
            if start is not None:
                raise AssertionError(f"a MOD block opens inside another at line {i + 1}")
            start = i
        elif line.strip() == gen.MOD_CLOSE:
            if start is None:
                raise AssertionError(f"a MOD block closes at line {i + 1} with none open")
            spans.append((start, i))
            start = None
    if start is not None:
        raise AssertionError("a MOD block never closes")
    return spans


def _as_vanilla(lines):
    """The stripped, non-blank lines with each MOD block replaced by the
    vanilla lines it records."""
    spans = _mod_blocks(lines)
    out, i = [], 0
    for start, end in spans:
        out += lines[i:start]
        out += [line.strip()[len(gen.VANILLA_LINE):] for line in lines[start + 1:end]
                if line.strip().startswith(gen.VANILLA_LINE)]
        i = end + 1
    out += lines[i:]
    return [line.strip() for line in out if line.strip()]


def _visibles(lines):
    return [line.strip()[len('visible = "['):-2] for line in lines if line.strip().startswith('visible = "[')]


def _all_loc():
    keys = json.loads(VANILLA_LOC.read_text(encoding="utf-8"))
    keys.update(load_loc())
    return keys


class FileTest(unittest.TestCase):
    def test_one_bom(self):
        head = gen.OUT.read_bytes()[:6]
        self.assertTrue(head.startswith(b"\xef\xbb\xbf"))
        self.assertFalse(head.startswith(b"\xef\xbb\xbf\xef\xbb\xbf"))

    def test_it_is_up_to_date(self):
        self.assertEqual(gen.written(), gen.OUT.read_bytes(),
                         "stale: run python3 scripts/generators/gen_build_list_columns.py")

    def test_it_loads_before_vanillas_file(self):
        # The first definition of a type's name read wins (gotcha #30).
        self.assertTrue(gen.OUT.name.startswith("00_"))
        self.assertLess(gen.OUT.name, "map_list_panel.gui")

    def test_it_holds_the_three_types_and_nothing_else(self):
        text = _ours()
        self.assertEqual(sorted(re.findall(r"^\ttype (\w+) = ", text, re.M)),
                         sorted((gen.CELL_TYPE, *gen.HEADER_TYPES)))
        self.assertEqual(re.findall(r"^(\w+)", text, re.M), ["types"])

    def test_no_other_mod_file_defines_them(self):
        names = (gen.CELL_TYPE, *gen.HEADER_TYPES)
        for path in sorted((ROOT / "gui").rglob("*.gui")):
            if path == gen.OUT:
                continue
            text = _read(path)
            for name in names:
                with self.subTest(file=path.name, type=name):
                    self.assertNotRegex(text, rf"(?m)^\s*type\s+{name}\s*=")


class VanillaTest(unittest.TestCase):
    def test_each_type_is_vanillas_outside_its_blocks(self):
        vanilla = _read(gen.VANILLA)
        for name in (gen.CELL_TYPE, *gen.HEADER_TYPES):
            with self.subTest(type=name):
                theirs = [line.strip() for line in _type_lines(vanilla, name) if line.strip()]
                self.assertEqual(theirs, _as_vanilla(_type_lines(_ours(), name)))

    def test_each_type_has_its_two_blocks(self):
        for name in (gen.CELL_TYPE, *gen.HEADER_TYPES):
            with self.subTest(type=name):
                self.assertEqual(2, len(_mod_blocks(_type_lines(_ours(), name))))

    def test_vanillas_productivity_test_is_kept_inside_ours(self):
        for name, subject in ((gen.CELL_TYPE, gen.CELL_BUILDING),
                              *((header, gen.HEADER_BUILDING) for header in gen.HEADER_TYPES)):
            with self.subTest(type=name):
                visibles = _visibles(_type_lines(_ours(), name))
                ours = f"And({gen.vanilla_productivity_test(subject)}, {gen.none_of(subject)})"
                self.assertEqual(1, visibles.count(ours))
                self.assertNotIn(gen.vanilla_productivity_test(subject), visibles)

    def test_the_fixture_is_the_installed_file(self):
        base = os.environ.get("VIC3_BASE_GAME")
        if base is None:
            try:
                import path_constants
                base = path_constants.base_game_path
            except Exception:
                base = None
        game = Path(base) / "game" / "gui" / "map_list_panel.gui" if base else None
        if game is None or not game.is_file():
            self.skipTest("no Victoria 3 install")
        self.assertEqual(gen.VANILLA.read_bytes(), game.read_bytes(),
                         "vanilla changed: replace the fixture and run scripts/generators/gen_build_list_columns.py")


class ColumnTest(unittest.TestCase):
    def test_one_cell_and_one_header_each_and_no_productivity(self):
        for name, subject in ((gen.CELL_TYPE, gen.CELL_BUILDING),
                              *((header, gen.HEADER_BUILDING) for header in gen.HEADER_TYPES)):
            visibles = _visibles(_type_lines(_ours(), name))
            productivity = [v for v in visibles if gen.vanilla_productivity_test(subject) in v]
            self.assertEqual(1, len(productivity), name)
            for column in gen.COLUMNS:
                with self.subTest(type=name, building=column.building):
                    own = gen.is_building(subject, column.building)
                    self.assertEqual(1, visibles.count(own))
                    self.assertIn(own, productivity[0])
                    self.assertIn(f"Not(Or({gen.is_building(subject, gen.COLUMNS[0].building)}", productivity[0])

    def test_the_cell_tests_the_building_and_the_headers_the_panel(self):
        # The cell has the listed Building in its datacontext; the headers have
        # only the panel's building type (vanilla's own tests, each site).
        cell = "\n".join(_type_lines(_ours(), gen.CELL_TYPE))
        self.assertNotIn("MapListBuildingPanel", cell)
        for name in gen.HEADER_TYPES:
            with self.subTest(type=name):
                self.assertEqual([], re.findall(r"(?<![\w.])Building\.GetBuildingType", "\n".join(_type_lines(_ours(), name))))

    def test_the_cell_reads_only_its_datacontext(self):
        for column in gen.COLUMNS:
            with self.subTest(building=column.building):
                objects = set(re.findall(r"\[(\w+)\.", column.cell_text))
                self.assertLessEqual(objects, {"State", "Building"})

    def test_headers_have_no_sort(self):
        # MapListPanel.Sort takes a key the engine knows; a mod column has none.
        for name in gen.HEADER_TYPES:
            lines = _type_lines(_ours(), name)
            for start, end in _mod_blocks(lines):
                with self.subTest(type=name, line=start):
                    self.assertFalse(any("onclick" in line for line in lines[start:end + 1]))

    def test_the_header_slot_is_vanillas_width(self):
        # Each column's header is as wide as the productivity header it stands in for.
        for name in gen.HEADER_TYPES:
            lines = _type_lines(_ours(), name)
            (narrowed, _), (start, end) = _mod_blocks(lines)
            opener = narrowed - 1
            self.assertEqual("sort_button = {", lines[opener].strip())
            productivity = [line.strip() for line in lines[opener:gen.close(lines, opener) + 1]
                            if line.strip().startswith("size = {") and "20 }" in line]
            ours = [line.strip() for line in lines[start:end + 1] if line.strip().startswith("size = {") and "20 }" in line]
            with self.subTest(type=name):
                self.assertEqual(1, len(productivity))
                self.assertEqual([productivity[0]] * len(gen.COLUMNS), ours)

    def test_loc_keys_exist(self):
        loc = _all_loc()
        for column in gen.COLUMNS:
            for key in (column.cell_tooltip, column.header_tooltip):
                with self.subTest(building=column.building, key=key):
                    self.assertIn(key, loc)
                    for spliced in re.findall(r"\$(\w+)\$", loc[key]):
                        self.assertIn(spliced, loc)

    def test_script_values_exist(self):
        defined = set()
        for path in (ROOT / "common" / "script_values").glob("*.txt"):
            defined |= set(re.findall(r"(?m)^(\w+)\s*=", _read(path)))
        texts = [column.cell_text for column in gen.COLUMNS]
        loc = _all_loc()
        texts += [loc[column.cell_tooltip] for column in gen.COLUMNS if column.cell_tooltip in loc]
        for text in texts:
            for name in re.findall(r"ScriptValue\('(\w+)'\)", text):
                with self.subTest(script_value=name):
                    self.assertIn(name, defined)

    def test_buildings_exist_and_are_not_military(self):
        buildings = "\n".join(_read(path) for path in sorted((ROOT / "common" / "buildings").glob("*.txt")))
        groups_text = "\n".join(_read(path) for path in sorted((ROOT / "common" / "building_groups").glob("*.txt")))
        vanilla_groups = json.loads(VANILLA_GROUPS.read_text(encoding="utf-8"))
        for column in gen.COLUMNS:
            with self.subTest(building=column.building):
                m = re.search(rf"(?m)^{column.building} = \{{(.*?)^\}}", buildings, re.S)
                self.assertIsNotNone(m, f"no {column.building} in common/buildings")
                group = re.search(r"(?m)^\tbuilding_group = (\w+)", m.group(1)).group(1)
                mod_group = re.search(rf"(?m)^(?:REPLACE_OR_CREATE:|REPLACE:)?{group} = \{{(.*?)^\}}", groups_text, re.S)
                if mod_group:
                    body = mod_group.group(1)
                else:
                    self.assertIn(group, vanilla_groups)
                    body = json.dumps(vanilla_groups[group])
                # vanilla draws the cell only for a non-military building; a group with a
                # parent would need its chain read, which this doesn't do
                self.assertNotRegex(body, r"is_military")
                self.assertNotRegex(body, r"parent_group")


class GeneratorTest(unittest.TestCase):
    def test_raises_when_vanilla_moves_a_hook(self):
        vanilla = _read(gen.VANILLA)
        moved = {
            "the productivity test": vanilla.replace(
                "Not(ObjectsEqual(Building.GetBuildingType, GetBuildingType('building_trade_center').Self)))]",
                "Not(ObjectsEqual(Building.GetBuildingType, GetBuildingType('building_trade_centre').Self)))]"),
            "the trade capacity header": vanilla.replace("Sort('trade_capacity_balance')", "Sort('trade_capacity')"),
            "the cell type": vanilla.replace("type productivity_or_other_information = ", "type productivity_info = "),
        }
        for what, text in moved.items():
            with self.subTest(moved=what):
                self.assertNotEqual(text, vanilla)
                with self.assertRaises(ValueError):
                    gen.generated(text)

    def test_none_of_nests_two_arguments(self):
        one = gen.COLUMNS[:1]
        self.assertEqual(f"Not({gen.is_building('S', one[0].building)})", gen.none_of("S", one))
        self.assertEqual(len(gen.COLUMNS) - 1, gen.none_of("S").count("Or("))


if __name__ == "__main__":
    unittest.main()
