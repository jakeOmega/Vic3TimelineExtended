"""The Map Room's class maps, generated from one table (scripts/generators/gen_journal_map_classes.py, #1975).

test_journal_map_modes.py (ClassMapsTest) holds what the family paints, hovers and walks. This holds the generator: its
output is fresh, each file starts with one BOM and its header, its table checks itself, the paint and hover go between
their markers in the hand-written host and nowhere else, and every key it writes is in the generated loc file alone.
"""
import copy
import importlib.util
import os
import re
import subprocess
import sys
import unittest

REPO = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(REPO, "scripts", "generators", "gen_journal_map_classes.py")


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load("gen_journal_map_classes", SCRIPT)
classes = gen.classes


class FreshTest(unittest.TestCase):
    def test_the_generated_files_are_fresh(self):
        result = subprocess.run([sys.executable, SCRIPT, "--check"], capture_output=True, text=True, cwd=REPO)
        self.assertEqual(result.returncode, 0,
                         f"run python3 scripts/generators/gen_journal_map_classes.py\n{result.stdout}{result.stderr}")

    def test_each_file_starts_with_one_bom_and_its_header(self):
        for path, body in gen.outputs().items():
            with self.subTest(file=str(path)):
                self.assertTrue(body.startswith(b"\xef\xbb\xbf"))
                self.assertFalse(body[3:].startswith(b"\xef\xbb\xbf"))
                if path.name == gen.HOST_FILE.name:
                    # the host is hand-written: only its marked lines are the generator's
                    self.assertNotIn(b"do not edit manually", body)
                elif path.suffix == ".yml":
                    self.assertIn(b"# AUTO-GENERATED by scripts/generators/gen_journal_map_classes.py", body)
                else:
                    self.assertTrue(body[3:].startswith(b"# AUTO-GENERATED by scripts/generators/gen_journal_map_classes.py"))


class TableTest(unittest.TestCase):
    def setUp(self):
        self.rows = copy.deepcopy(classes.CLASSES)

    def tearDown(self):
        classes.CLASSES[:] = self.rows

    def test_the_table_validates(self):
        classes.validate()

    def test_a_selector_used_twice_fails(self):
        classes.CLASSES[1]["share_sel"] = classes.CLASSES[0]["count_sel"]
        with self.assertRaisesRegex(ValueError, "twice"):
            classes.validate()

    def test_a_count_range_off_a_power_of_two_fails(self):
        classes.CLASSES[0]["count"] = (250, 30000)
        with self.assertRaisesRegex(ValueError, "doublings"):
            classes.validate()

    def test_the_rows_hold_every_class_once(self):
        self.assertEqual(sorted(p for row in classes.ROWS for p in row), sorted(c["pop"] for c in classes.CLASSES))

    def test_the_tooltips_name_no_curve_or_color(self):
        # what draws a class is said in the pick's first line, which holds whatever the scale and the colors
        # (test_journal_map_modes.py, PickTooltipTest, holds the words)
        for c in classes.CLASSES:
            self.assertNotRegex(c["about"], r"\$|\[|#", c["pop"])


class HostTest(unittest.TestCase):
    def setUp(self):
        with open(os.path.join(REPO, gen.HOST_FILE), encoding="utf-8-sig") as f:
            self.host = f.read()

    def test_each_part_has_one_pair_of_markers_inside_its_block(self):
        for part in gen.PARTS:
            begin, end = self.host.index(f"# BEGIN {gen.MARK} {part}"), self.host.index(f"# END {gen.MARK} {part}")
            self.assertEqual(self.host.count(f"# BEGIN {gen.MARK} {part}"), 1)
            # inside its own block: the last block opened before the marker is the part
            opened = [m for m in re.finditer(r"^\t(map_color|map_color_second|map_tooltip)\s*=\s*\{", self.host, re.M)
                      if m.start() < begin]
            self.assertEqual(opened[-1].group(1), part)
            self.assertLess(begin, end)

    def test_a_missing_marker_fails(self):
        with self.assertRaisesRegex(ValueError, "marker"):
            gen.splice(self.host.replace(f"# END {gen.MARK} map_color", ""), "map_color", ["x"])

    def test_the_splice_keeps_everything_outside_the_markers(self):
        out = gen.render_host(self.host)
        strip = lambda text, part: re.sub(rf"# BEGIN {re.escape(gen.MARK)} {part}\n.*?# END", "#", text, flags=re.S)
        self.assertEqual(strip(strip(out, "map_color"), "map_tooltip"),
                         strip(strip(self.host, "map_color"), "map_tooltip"))


class LocTest(unittest.TestCase):
    def test_every_key_is_the_generator_s_and_files_with_it(self):
        sys.path.insert(0, REPO)
        import organize_loc
        keys = gen.loc_entries()
        for key in keys:
            self.assertEqual(organize_loc.categorize_key(key, set()), gen.LOC_CATEGORY, key)
        with open(os.path.join(REPO, gen.LOC_FILE), encoding="utf-8-sig") as f:
            written = set(re.findall(r"^ ([\w.]+):", f.read(), re.M))
        self.assertEqual(written, set(keys))
        # and no hand-written file holds one
        loc = os.path.join(REPO, "localization", "english")
        for name in os.listdir(loc):
            if name.endswith(".yml") and name != gen.LOC_FILE.name:
                with open(os.path.join(loc, name), encoding="utf-8-sig") as f:
                    text = f.read()
                with self.subTest(file=name):
                    self.assertNotRegex(text, r"(?m)^ te_jmap_(pick|tt)_class_")


if __name__ == "__main__":
    unittest.main()
