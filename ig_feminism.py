HEADER = """# AUTO-GENERATED by ig_feminism.py - Do not edit manually
#
# Each field restates vanilla's lines, then adds the mod's branches. An
# injected script value replaces vanilla's whole field, so leaving vanilla's
# lines out would drop them. The zz_ prefix sorts this file after the vanilla
# files it injects into.
"""


def _code(line):
    """`line` with comments cut and quoted text blanked, so braces count right."""
    out = []
    in_string = False
    for char in line:
        if in_string:
            if char == '"':
                in_string = False
            out.append(" ")
        elif char == '"':
            in_string = True
            out.append(" ")
        elif char == "#":
            break
        else:
            out.append(char)
    return "".join(out)


def _masked(text):
    """`text` with comments and quoted text blanked, keeping every offset."""
    return "\n".join(_code(line).ljust(len(line)) for line in text.split("\n"))


def interest_group_key(text):
    """The interest group a vanilla file defines (its first top-level key)."""
    match = re.search(r"^(ig_\w+)\s*=\s*\{", _masked(text), flags=re.MULTILINE)
    if not match:
        raise ValueError("no interest group defined")
    return match.group(1)


def field_lines(text, field):
    """The stripped, non-blank lines inside `field = { ... }` in `text`."""
    masked = _masked(text)
    match = re.search(rf"\b{field}\s*=\s*\{{", masked)
    if not match:
        raise ValueError(f"{field} not found")
    depth = 1
    for end in range(match.end(), len(masked)):
        depth += {"{": 1, "}": -1}.get(masked[end], 0)
        if depth == 0:
            inner = text[match.end():end]
            return [line.strip() for line in inner.split("\n") if line.strip()]
    raise ValueError(f"{field} is not closed")


def _indent(lines, depth):
    """Indent stripped lines with tabs by brace depth, as format_paradox_tabs does."""
    out = []
    for line in lines:
        code = _code(line).strip()
        closers = len(code) - len(code.lstrip("}"))
        out.append("\t" * max(depth - closers, 0) + line)
        depth += code.count("{") - code.count("}")
    return out


def branch_lines(condition, details):
    """The mod's branch for one law or technology, unindented."""
    if details["type"] == "technology":
        trigger = f"has_technology_researched = {condition}"
    else:
        trigger = f"{details['type']} = {condition}"
    return [
        "if = {",
        "limit = {",
        "owner = {",
        trigger,
        "}",
        "}",
        f"add = {{ value = {details['increase']} }}",
        "}",
    ]


def build_inject(vanilla_text, roles):
    """One INJECT block restating each field of `roles` and adding its profile."""
    lines = [f"INJECT:{interest_group_key(vanilla_text)} = {{"]
    for role, profile in roles.items():
        body = field_lines(vanilla_text, role)
        for condition, details in profile.items():
            body += branch_lines(condition, details)
        lines += _indent([f"{role} = {{", *body, "}"], 1)
    lines.append("}")
    return "\n".join(lines)


def build_file(input_dir, modifications):
    """The whole generated file, from the vanilla interest-group files in `input_dir`."""
    blocks = []
    for filename, roles in modifications.items():
        with open(os.path.join(input_dir, filename), encoding="utf-8-sig") as file:
            blocks.append(build_inject(file.read(), roles))
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def write_file(input_dir, output_path, modifications):
    text = build_file(input_dir, modifications)
    # `utf-8-sig` writes the leading BOM so the engine doesn't emit a
    # "should be in utf8-bom encoding" warning for the regenerated file.
    with open(output_path, "w", encoding="utf-8-sig", newline="\n") as file:
        file.write(text)


def normalize_values(modifications, desired_total):
    new_modifications = copy.deepcopy(modifications)
    total_increase = sum(
        details["increase"]
        for item, details in modifications.items()
        if item != "law_type:law_comprehensive_rights"
    )
    scale_factor = desired_total / total_increase
    for item, details in modifications.items():
        normalized_increase = details["increase"] * scale_factor
        new_modifications[item]["increase"] = round(normalized_increase, 3)
    return new_modifications


