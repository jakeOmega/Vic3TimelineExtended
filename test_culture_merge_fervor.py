# The entries the fervor copy replaced waits for (R37), and the movements it also serves.
FERVOR_ENTRIES = {
    "je_german_unification_idea": ("north_german", "south_german"),
    "je_the_balkan_league": ("serb", "bulgarian"),
}
FERVOR_MOVEMENTS = {
    "movement_german_national": ("north_german", "south_german"),
    "movement_italian_national": ("north_italian", "south_italian"),
    "movement_yugoslav_national": ("serb", "croat", "bosniak", "slovene"),
}


def copy_calls():
    """The cultures te_cmg_copy_fervor_all copies, in order, each with the guard its call sits behind."""
    body = squash(block(text_of(GEN_EFFECTS), "te_cmg_copy_fervor_all"))
    return re.findall(r"if = \{ limit = \{ has_global_variable = te_cm_switched_(\w+) \} te_cm_copy_fervor = \{ CULTURE = (\w+) \} \}", body)


class VanillaReadsTest(unittest.TestCase):
    """Why the copy exists: vanilla reads these parts' fervor, and none of them waits any more."""

    def test_the_entries_and_movements_read_the_parts_fervor(self):
        data = snapshot_data()
        for group, table in (("Journal Entries", FERVOR_ENTRIES), ("Political Movements", FERVOR_MOVEMENTS)):
            for name, cultures in table.items():
                text = json.dumps(data[group][name])
                self.assertIn("culture_current_fervor", text, name)
                for culture in cultures:
                    self.assertIn("cu:" + culture, text, (name, culture))

    def test_no_merge_waits_on_those_entries(self):
        waits = {e for m in cfg.MERGES for p in m.core + m.optional for e in p.wait_for}
        for entry in FERVOR_ENTRIES:
            self.assertNotIn(entry, waits, entry)

    def test_every_culture_those_reads_name_can_switch(self):
        switchable = set(gen.switchable_cultures(cfg.MERGES))
        for table in (FERVOR_ENTRIES, FERVOR_MOVEMENTS):
            for cultures in table.values():
                for culture in cultures:
                    self.assertIn(culture, switchable, culture)


class CopyTest(unittest.TestCase):
    def test_the_generated_files_are_current(self):
        self.assertFalse(gen.regenerate(dry_run=True)["changed"], "run python3 scripts/generators/gen_culture_merges.py")

    def test_every_switchable_culture_but_the_excluded_is_copied_once_behind_its_own_switch(self):
        calls = copy_calls()
        self.assertTrue(all(guard == culture for guard, culture in calls), calls[:3])
        cultures = [c for _, c in calls]
        expected = [c for c in gen.switchable_cultures(cfg.MERGES) if c not in cfg.NO_FERVOR_COPY]
        self.assertEqual(sorted(cultures), sorted(expected))
        self.assertEqual(len(cultures), len(set(cultures)))

    def test_ukrainian_and_byelorussian_are_left_out_because_vanilla_reads_their_fervor_as_a_separate_identity(self):
        # Their renaissances open on their own fervor (15, 20), and the Russian Civil War releases a homeland culture's
        # states on fervor 10 (Russian excepted); copied from East Slavic, both would revive what the merge ended.
        self.assertEqual(cfg.NO_FERVOR_COPY, ("ukrainian", "byelorussian"))
        switchable = set(gen.switchable_cultures(cfg.MERGES))
        data = snapshot_data()
        for culture, entry in (("ukrainian", "je_ukraine_cultural_renaissance"), ("byelorussian", "je_belarus_cultural_renaissance")):
            self.assertIn(culture, switchable)
            text = json.dumps(data["Journal Entries"][entry])
            self.assertIn("cu:" + culture, text)
            self.assertIn("culture_current_fervor", text)
        self.assertNotIn("russian", cfg.NO_FERVOR_COPY)

    def test_a_result_is_copied_before_the_cultures_that_switch_into_it(self):
        # North Italian copies cm_italian's fervor, which copies cm_latin's: one pass settles the chain.
        order = [c for _, c in copy_calls()]
        pos = {c: i for i, c in enumerate(order)}
        pairs = [(result, part) for result, parts in gen.switched_into(cfg.MERGES).items() if result in pos for part in parts if part in pos]
        self.assertTrue(pairs)
        for result, part in pairs:
            self.assertLess(pos[result], pos[part], (result, part))
        self.assertLess(pos["cm_italian"], pos["north_italian"])
        self.assertLess(pos["french"], pos["occitan"])

    def test_the_order_rejects_a_roster_that_nests_a_culture_in_itself(self):
        a = cfg.Merge("a", "cm_a", cfg.MERGES[0].new, core=(cfg.Part(("x",)), cfg.Part(("cm_b",))))
        b = cfg.Merge("b", "cm_b", cfg.MERGES[0].new, core=(cfg.Part(("y",)), cfg.Part(("cm_a",))))
        with self.assertRaises(ValueError):
            gen.fervor_copy_order((a, b))

    def test_the_copy_sets_the_switched_culture_to_its_successors_fervor(self):
        body = squash(block(text_of(EFFECTS), "te_cm_copy_fervor"))
        save = "global_var:te_cm_switched_$CULTURE$ = { save_temporary_scope_as = te_cm_fervor_source }"
        setter = "cu:$CULTURE$ = { te_cmg_set_fervor_from_source = yes }"
        self.assertIn(save, body)
        self.assertEqual(body.count(setter), 1)
        self.assertLess(body.index(save), body.index(setter))
        # The self-check zeroes and re-sets the culture before the copy, never after it.
        self.assertLess(body.index("te_cm_chk_fervor = { CULTURE = $CULTURE$ }"), body.index(setter))

    def test_the_value_reads_the_saved_source_in_vanillas_dotted_form(self):
        body = squash(block(text_of(VALUES), "te_cm_fervor_of_source"))
        self.assertEqual(body, "value = scope:te_cm_fervor_source.culture_current_fervor")

    def test_the_global_monthly_pulse_runs_the_copy_outside_the_rule_gate(self):
        text = text_of(ON_ACTIONS)
        self.assertEqual(squash(block(text, "on_monthly_pulse")), "on_actions = { te_cm_fervor_on_action }")
        # The self-check reads last month's copy before this month's overwrites it. No rule gate. The same pulse carries
        # the tradition carry-over and its two self-checks (2026-11-09; test_culture_merge_primary_reads.py).
        self.assertEqual(
            squash(block(text, "te_cm_fervor_on_action")),
            "effect = { te_cm_chk_fervor_monthly = yes te_cmg_copy_fervor_all = yes te_cmg_carry_traditions = yes "
            "te_cm_chk_dead_primary_monthly = yes te_cm_chk_definition_inject = yes }",
        )
        # Once a month for the world, so no lock: the country pulse keeps only the rule's upkeep.
        self.assertEqual(
            squash(block(text, "te_cm_monthly_on_action")),
            "effect = { if = { limit = { te_cm_system_enabled = yes any_scope_state = { always = yes } } te_cmg_monthly_country = yes } }",
        )
        self.assertNotIn("te_cm_fervor_lock", text)

    def test_no_set_fervor_takes_a_named_value(self):
        # set_fervor is documented with a literal; an effect that read a named value as 0 would zero the culture.
        for path in (EFFECTS, GEN_EFFECTS, ROOT / "common/scripted_effects/te_culture_merge_selfcheck_effects.txt"):
            for value in re.findall(r"set_fervor = (\S+)", text_of(path)):
                self.assertRegex(value, r"^\d+(\.\d+)?$", "%s: set_fervor = %s" % (path.name, value))

    def test_the_switch_hands_the_result_the_parts_fervor_where_its_own_is_lower(self):
        body = squash(block(text_of(EFFECTS), "te_cm_switch_part"))
        raise_ = (
            "cu:$CULTURE$ = { save_temporary_scope_as = te_cm_fervor_source } if = { limit = { cu:$RESULT$ = "
            "{ culture_current_fervor < te_cm_fervor_of_source } } cu:$RESULT$ = { te_cmg_set_fervor_from_source = yes } }"
        )
        self.assertEqual(body.count(raise_), 1)
        # Inside the switch's own guard, read before any pop of the part converts.
        self.assertLess(body.index("global_var:te_cm_dom_$MERGE$_$CULTURE$ >= te_cm_switch_share"), body.index(raise_))
        self.assertLess(body.index(raise_), body.index("change_pop_culture"))


@functools.lru_cache(maxsize=1)
def ladder_nodes():
    return parse_text(block(text_of(GEN_EFFECTS), "te_cmg_set_fervor_from_source"), "ladder")[0]


def run_ladder(source):
    """What te_cmg_set_fervor_from_source sets for a source fervor, run from the generated text (every test in it is
    `culture_current_fervor >= N` on scope:te_cm_fervor_source; the parser keeps no operator)."""
    nodes = ladder_nodes()
    sets = []

    def holds(limit):
        (scope,) = limit.children
        assert scope.key == "scope:te_cm_fervor_source", scope.key
        (test,) = scope.children
        assert test.key == "culture_current_fervor", test.key
        return source >= float(test.value)

    def run(children):
        taken = False
        for node in children:
            if node.key == "if":
                taken = False
            if node.key in ("if", "else_if", "else"):
                if taken:
                    continue
                limit = next((c for c in node.children if c.key == "limit"), None)
                if limit is None or holds(limit):
                    taken = True
                    run([c for c in node.children if c.key != "limit"])
            elif node.key == "set_fervor":
                sets.append(float(node.value))
            else:
                raise AssertionError("unexpected %s in the ladder" % node.key)

    run(nodes)
    return sets


class LadderTest(unittest.TestCase):
    def test_the_ladder_rounds_down_to_the_half_point_and_never_overshoots(self):
        for tenths in range(0, 1001):
            source = tenths / 10
            sets = run_ladder(source)
            self.assertEqual(len(sets), 1, source)
            self.assertEqual(sets[0], min(100.0, int(source * 2) / 2), source)
            self.assertLessEqual(sets[0], source)
            self.assertLess(source - sets[0], 0.5)

    def test_every_vanilla_threshold_reads_the_same_on_the_copy(self):
        # German National Identity 40 and 30, the Balkan League above 75, the movements above 10.
        for threshold in (10, 30, 40, 75):
            for source in (threshold - 0.3, threshold, threshold + 0.6):
                (copied,) = run_ladder(source)
                self.assertEqual(copied >= threshold, source >= threshold, (threshold, source))

    def test_the_data_and_the_text_agree(self):
        steps = [s for _, band, rest in gen.fervor_ladder() for s in band + [rest]]
        self.assertEqual(sorted(steps, reverse=True), [v / 2 for v in range(200, -1, -1)])
        self.assertEqual(squash(block(text_of(GEN_EFFECTS), "te_cmg_set_fervor_from_source")).count("set_fervor = "), 201)


