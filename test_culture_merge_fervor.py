"""Tests for the culture merges' fervor copy (owner, 2026-11-07, in place of R37's waits).

A culture that has switched has no pops, so its fervor drifts toward 0 and vanilla's reads of it go dark:
je_german_unification_idea's completion, je_the_balkan_league's possible, and the German, Italian and Yugoslav
pan-national movements' creation_trigger. Once a month every switched culture takes the fervor of the culture it
switched into, through a ladder of literals, and a result takes a switching part's fervor where its own is lower.
Ukrainian and Byelorussian are left out: vanilla reads their fervor only for an identity apart from Russian.

Files under test:
* common/scripted_effects/te_culture_merge_effects.txt (te_cm_copy_fervor; te_cm_switch_part's raise)
* common/script_values/te_culture_merge_values.txt (te_cm_fervor_of_source)
* common/on_actions/te_culture_merge_on_actions.txt (the monthly copy on the global pulse, outside the rule gate)
* common/scripted_effects/te_culture_merges_generated_effects.txt (te_cmg_copy_fervor_all, te_cmg_set_fervor_from_source),
  generated by scripts/generators/gen_culture_merges.py (fervor_copy_order, fervor_ladder)

Run: python3 -m unittest test_culture_merge_fervor -v
"""

