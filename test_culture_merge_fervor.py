"""Tests for the culture merges' fervor copy (owner, 2026-11-07, in place of R37's waits).

A culture that has switched has no pops, so its fervor drifts toward 0 and vanilla's reads of it go dark:
je_german_unification_idea's completion, je_the_balkan_league's possible, and the German, Italian and Yugoslav
pan-national movements' creation_trigger. Once a month every switched culture takes the fervor of the culture it
switched into, and a result takes a switching part's fervor where its own is lower.

Files under test:
* common/scripted_effects/te_culture_merge_effects.txt (te_cm_copy_fervor; te_cm_switch_part's raise)
* common/script_values/te_culture_merge_values.txt (te_cm_fervor_of_source)
* common/on_actions/te_culture_merge_on_actions.txt (the monthly copy, outside the rule gate)
* common/scripted_effects/te_culture_merges_generated_effects.txt (te_cmg_copy_fervor_all), generated by
  scripts/generators/gen_culture_merges.py (fervor_copy_order)

Run: python3 -m unittest test_culture_merge_fervor -v
"""

import json
import re
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts" / "generators"))

import culture_merges_config as cfg  # noqa: E402
import gen_culture_merges as gen  # noqa: E402
from test_culture_merge_census import block, snapshot_data, squash, text_of  # noqa: E402

EFFECTS = ROOT / "common/scripted_effects/te_culture_merge_effects.txt"
VALUES = ROOT / "common/script_values/te_culture_merge_values.txt"
ON_ACTIONS = ROOT / "common/on_actions/te_culture_merge_on_actions.txt"
GEN_EFFECTS = ROOT / "common/scripted_effects/te_culture_merges_generated_effects.txt"

# The entries the fervor copy replaced waits for (R37), and the movements it also serves.
FERVOR_ENTRIES = {
    "je_german_unification_idea": ("north_german", "south_german"),
    "je_the_balkan_league": ("serb", "bulgarian"),
}
FERVOR_MOVEMENTS = {
    "movement_german_national": ("north_german", "south_german"),
    "movement_italian_national": ("north_italian", "south_italian"),
    "movement_yugoslav_national": ("serb", "croat", "bosniak", "slovene"),
}


def copy_calls():
    """The cultures te_cmg_copy_fervor_all copies, in order, each with the guard its call sits behind."""
    body = squash(block(text_of(GEN_EFFECTS), "te_cmg_copy_fervor_all"))
    return re.findall(r"if = \{ limit = \{ has_global_variable = te_cm_switched_(\w+) \} te_cm_copy_fervor = \{ CULTURE = (\w+) \} \}", body)


class VanillaReadsTest(unittest.TestCase):
    """Why the copy exists: vanilla reads these parts' fervor, and none of them waits any more."""

    def test_the_entries_and_movements_read_the_parts_fervor(self):
        data = snapshot_data()
        for group, table in (("Journal Entries", FERVOR_ENTRIES), ("Political Movements", FERVOR_MOVEMENTS)):
            for name, cultures in table.items():
                text = json.dumps(data[group][name])
                self.assertIn("culture_current_fervor", text, name)
                for culture in cultures:
                    self.assertIn("cu:" + culture, text, (name, culture))

    def test_no_merge_waits_on_those_entries(self):
        waits = {e for m in cfg.MERGES for p in m.core + m.optional for e in p.wait_for}
        for entry in FERVOR_ENTRIES:
            self.assertNotIn(entry, waits, entry)

    def test_every_culture_those_reads_name_can_switch(self):
        switchable = set(gen.switchable_cultures(cfg.MERGES))
        for table in (FERVOR_ENTRIES, FERVOR_MOVEMENTS):
            for cultures in table.values():
                for culture in cultures:
                    self.assertIn(culture, switchable, culture)


class CopyTest(unittest.TestCase):
    def test_the_generated_files_are_current(self):
        self.assertFalse(gen.regenerate(dry_run=True)["changed"], "run python3 scripts/generators/gen_culture_merges.py")

    def test_every_switchable_culture_is_copied_once_behind_its_own_switch(self):
        calls = copy_calls()
        self.assertTrue(all(guard == culture for guard, culture in calls), calls[:3])
        cultures = [c for _, c in calls]
        self.assertEqual(sorted(cultures), sorted(gen.switchable_cultures(cfg.MERGES)))
        self.assertEqual(len(cultures), len(set(cultures)))

    def test_a_result_is_copied_before_the_cultures_that_switch_into_it(self):
        # North Italian copies cm_italian's fervor, which copies cm_latin's: one pass settles the chain.
        order = [c for _, c in copy_calls()]
        pos = {c: i for i, c in enumerate(order)}
        pairs = [(result, part) for result, parts in gen.switched_into(cfg.MERGES).items() if result in pos for part in parts]
        self.assertTrue(pairs)
        for result, part in pairs:
            self.assertLess(pos[result], pos[part], (result, part))
        self.assertLess(pos["cm_italian"], pos["north_italian"])
        self.assertLess(pos["french"], pos["occitan"])

    def test_the_order_rejects_a_roster_that_nests_a_culture_in_itself(self):
        a = cfg.Merge("a", "cm_a", cfg.MERGES[0].new, core=(cfg.Part(("x",)), cfg.Part(("cm_b",))))
        b = cfg.Merge("b", "cm_b", cfg.MERGES[0].new, core=(cfg.Part(("y",)), cfg.Part(("cm_a",))))
        with self.assertRaises(ValueError):
            gen.fervor_copy_order((a, b))

    def test_the_copy_sets_the_switched_culture_to_its_successors_fervor(self):
        body = squash(block(text_of(EFFECTS), "te_cm_copy_fervor"))
        save = "global_var:te_cm_switched_$CULTURE$ = { save_temporary_scope_as = te_cm_fervor_source }"
        setter = "cu:$CULTURE$ = { set_fervor = te_cm_fervor_of_source }"
        self.assertIn(save, body)
        self.assertEqual(body.count(setter), 1)
        self.assertLess(body.index(save), body.index(setter))
        # The self-check zeroes and re-sets the culture before the copy, never after it.
        self.assertLess(body.index("te_cm_chk_fervor = { CULTURE = $CULTURE$ }"), body.index(setter))

    def test_the_value_reads_the_saved_source_in_vanillas_dotted_form(self):
        body = squash(block(text_of(VALUES), "te_cm_fervor_of_source"))
        self.assertEqual(body, "value = scope:te_cm_fervor_source.culture_current_fervor")

    def test_the_month_runs_the_copy_once_outside_the_rule_gate(self):
        body = squash(block(text_of(ON_ACTIONS), "te_cm_monthly_on_action"))
        gate = "if = { limit = { te_cm_system_enabled = yes } te_cmg_monthly_country = yes }"
        self.assertIn(gate, body)
        lock = re.search(
            r"if = \{ limit = \{ NOT = \{ has_global_variable = te_cm_fervor_lock \} \} "
            r"set_global_variable = \{ name = te_cm_fervor_lock value = yes days = (\d+) \} (.*?) \}$",
            body,
        )
        self.assertIsNotNone(lock, body)
        days, inner = int(lock.group(1)), lock.group(2)
        self.assertLess(days, 28, "a month must never go without a copy")
        self.assertNotIn("te_cm_system_enabled", inner)
        self.assertEqual(inner.count("te_cmg_copy_fervor_all = yes"), 1)
        # The self-check reads last month's copy before this month's overwrites it.
        self.assertLess(inner.index("te_cm_chk_fervor_monthly = yes"), inner.index("te_cmg_copy_fervor_all = yes"))
        self.assertEqual(body.count("te_cmg_copy_fervor_all"), 1)

    def test_the_switch_hands_the_result_the_parts_fervor_where_its_own_is_lower(self):
        body = squash(block(text_of(EFFECTS), "te_cm_switch_part"))
        raise_ = (
            "cu:$CULTURE$ = { save_temporary_scope_as = te_cm_fervor_source } if = { limit = { cu:$RESULT$ = "
            "{ culture_current_fervor < te_cm_fervor_of_source } } cu:$RESULT$ = { set_fervor = te_cm_fervor_of_source } }"
        )
        self.assertEqual(body.count(raise_), 1)
        # Inside the switch's own guard, after the part is marked switched.
        self.assertLess(body.index("name = te_cm_switched_$CULTURE$"), body.index(raise_))


if __name__ == "__main__":
    unittest.main()
