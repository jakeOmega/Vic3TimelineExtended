def _absorb_result(merge, culture):
    return merge.new is None and culture == merge.result


def joinable(merge):
    return [c for c in slot_cultures(merge) if not _absorb_result(merge, c)]


def optional_cultures(merge):
    return {c for part in merge.optional for c in part.cultures}


def switchable():
    seen = {}
    for merge in cfg.MERGES:
        for culture in joinable(merge):
            seen.setdefault(culture)
    return list(seen)


def section(body, key):
    """The part of a per-merge-ordered generated block that belongs to merge `key`: from its first clause to the
    next merge's. `body` is squashed text of a block with one `if = { limit = { OR = { global_var:te_cm_state_<m> ?= 1`
    per merge, in roster order."""
    keys = [m.key for m in cfg.MERGES]
    head = "if = { limit = { OR = { global_var:te_cm_state_%s ?= 1 " % key
    start = body.index(head)
    nxt = keys.index(key) + 1
    end = len(body)
    if nxt < len(keys):
        end = body.index("if = { limit = { OR = { global_var:te_cm_state_%s ?= 1 " % keys[nxt], start + 1)
    return body[start:end]


def calls(text, helper):
    """Every `helper = { K = V ... }` call in squashed text, as dicts."""
    found = []
    for m in re.finditer(re.escape(helper) + r" = \{ ((?:\w+ = [\w:$]+ ?)+)\}", text):
        found.append(dict(re.findall(r"(\w+) = ([\w:$]+)", m.group(1))))
    return found


