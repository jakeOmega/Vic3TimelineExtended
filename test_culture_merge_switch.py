class ConversionTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.text = text_of(EFFECTS)
        cls.body = squash(block(cls.text, "te_cm_convert_part"))

    def test_conversion_uses_the_rate_value(self):
        # The yearly conversion converts a fraction by the pop's own rate; only the switch (and the monthly
        # sweep of a part that has already switched) converts whole pops.
        found = re.findall(r"change_pop_culture = \{ ([^}]*) \}", self.body)
        self.assertEqual(found, ["target = cu:$RESULT$ value = te_cm_pop_rate"])
        self.assertIn("every_scope_pop = { limit = { culture = cu:$CULTURE$ } change_pop_culture", self.body)
        switch = squash(block(self.text, "te_cm_switch_part"))
        self.assertEqual(re.findall(r"change_pop_culture = \{ ([^}]*) \}", switch), ["target = cu:$RESULT$ value = 1"])

    def test_the_rate_value_reads_the_two_saved_scopes_the_helper_saves(self):
        self.assertIn("cu:$CULTURE$ = { save_temporary_scope_as = te_cm_part }", self.body)
        self.assertIn("global_var:te_cm_starter_$MERGE$ = { save_temporary_scope_as = te_cm_starter }", self.body)
        # Both are saved before the first pop is touched.
        self.assertLess(self.body.index("te_cm_part"), self.body.index("change_pop_culture"))
        self.assertLess(self.body.index("te_cm_starter"), self.body.index("change_pop_culture"))
        values = text_of(ROOT / "common/script_values/te_culture_merge_values.txt")
        rate = block(values, "te_cm_pop_rate")
        self.assertIn("scope:te_cm_part", rate)
        self.assertIn("scope:te_cm_starter", rate)

    def test_a_country_with_no_pops_of_the_part_is_skipped(self):
        self.assertRegex(
            self.body,
            r"^cu:\$CULTURE\$ = \{ save_temporary_scope_as = te_cm_part \} "
            r"global_var:te_cm_starter_\$MERGE\$ = \{ save_temporary_scope_as = te_cm_starter \} "
            r"set_local_variable = \{ name = te_cm_cv_tier value = \$TIER\$ \} "
            r"if = \{ limit = \{ culture_percent_country = \{ target = cu:\$CULTURE\$ value > 0 \} \}",
        )
        self.assertEqual(self.body.count("culture_percent_country"), 1)

    def test_first_conversion_adds_primary(self):
        self.assertIn(
            "if = { limit = { NOT = { country_has_primary_culture = cu:$RESULT$ } } add_primary_culture = cu:$RESULT$ }",
            self.body,
        )
        # Guarded every pass rather than once: a formation that dropped the primary gets it back.
        self.assertEqual(self.body.count("add_primary_culture"), 1)

    def test_the_conversion_marks_the_country_for_the_formation_hook(self):
        self.assertIn("set_variable = { name = te_cm_converted_$MERGE$ value = 1 }", self.body)
        # Revolution inheritance: a country variable, never a modifier or a list.
        self.assertNotIn("add_modifier", self.body)

    def test_only_a_country_that_is_not_paused_converts(self):
        tail = self.body[self.body.index("set_variable = { name = te_cm_paused_$MERGE$_$CULTURE$ value = local_var:te_cm_cv_fail }"):]
        self.assertTrue(tail.startswith(
            "set_variable = { name = te_cm_paused_$MERGE$_$CULTURE$ value = local_var:te_cm_cv_fail } "
            "if = { limit = { local_var:te_cm_cv_fail = 0 }"
        ))
        self.assertIn("add_primary_culture", tail)
        self.assertIn("change_pop_culture", tail)
        self.assertNotIn("change_pop_culture", self.body[:self.body.index(tail)])

    def test_the_pause_uses_the_pair_of_the_parts_own_tier(self):
        # R29. Script tier 2 (the spec's 1b) takes the very high pair, every other tier the accepted pair; a
        # country that is paused comes back at the open value, one that is not stops at the close value.
        tier2 = self.body[self.body.index("if = { limit = { local_var:te_cm_cv_tier = 2 }"):self.body.index("} else = { if = { limit = { var:te_cm_paused")]
        self.assertIn("value < te_cm_accept_high_open", tier2)
        self.assertIn("value < te_cm_accept_high_close", tier2)
        self.assertNotRegex(tier2, r"value < te_cm_accept_(open|close)\b")
        rest = self.body[self.body.index(tier2) + len(tier2):]
        standard = rest[:rest.index("set_local_variable = { name = te_cm_cv_cnt")]
        self.assertIn("value < te_cm_accept_open", standard)
        self.assertIn("value < te_cm_accept_close", standard)
        self.assertNotIn("high", standard)
        for text, opened, closed in ((tier2, "te_cm_accept_high_open", "te_cm_accept_high_close"),
                                     (standard, "te_cm_accept_open", "te_cm_accept_close")):
            paused = text.index("limit = { var:te_cm_paused_$MERGE$_$CULTURE$ ?= 1 }")
            other = text.index("else = {", paused)
            self.assertIn(opened, text[paused:other], "a paused country is tested against the open value")
            self.assertNotIn(closed, text[paused:other])
            self.assertIn(closed, text[other:], "an unpaused country is tested against the close value")
            self.assertNotIn(opened, text[other:])

    def test_the_pause_ignores_a_country_that_holds_only_a_sliver(self):
        self.assertIn("limit = { local_var:te_cm_cv_fail = 1 }", self.body)
        self.assertIn("every_scope_state = { limit = { state_region = { is_homeland = cu:$CULTURE$ } }", self.body)
        self.assertIn(
            "value = global_var:te_cm_home_$CULTURE$ multiply = te_cm_meaningful_share",
            self.body,
        )
        # A census figure that doesn't exist yet leaves the floor at 0, so the country still counts.
        self.assertIn("limit = { has_global_variable = te_cm_home_$CULTURE$ }", self.body)
        self.assertIn(
            "if = { limit = { local_var:te_cm_cv_cnt < local_var:te_cm_cv_floor } "
            "set_local_variable = { name = te_cm_cv_fail value = 0 } }",
            self.body,
        )
        # The count only runs for a country that already fails, never for the many that pass.
        self.assertEqual(self.body.count("every_scope_state"), 1)
        failing = self.body.index("limit = { local_var:te_cm_cv_fail = 1 }")
        self.assertLess(failing, self.body.index("every_scope_state"))

    def test_the_pause_is_a_country_variable_that_keeps_its_value(self):
        # Revolution inheritance and "progress is kept": set from the test's result each pass, never removed.
        self.assertIn("set_variable = { name = te_cm_paused_$MERGE$_$CULTURE$ value = local_var:te_cm_cv_fail }", self.body)
        self.assertNotIn("remove_variable", self.body)

    def test_every_argument_the_helper_names_is_passed_and_no_other(self):
        self.assertEqual(set(re.findall(r"\$([A-Z]+)\$", self.body)), {"MERGE", "CULTURE", "RESULT", "TIER"})
        for call in calls(squash(text_of(GEN_EFFECTS)), "te_cm_convert_part"):
            self.assertEqual(set(call), {"MERGE", "CULTURE", "RESULT", "TIER"})


class JoinedPartGateTest(unittest.TestCase):
    """R29: once a part has joined, te_cm_ok_<m>_<c> tests the hold alone; acceptance is the converting
    country's own pause."""

    @classmethod
    def setUpClass(cls):
        cls.body = squash(block(text_of(EFFECTS), "te_cm_census_part"))

    def test_a_joined_parts_ok_gate_does_not_read_acceptance(self):
        scan = self.body[self.body.index("every_country = { limit = { has_variable = te_cm_tmp_cnt }"):]
        scan = scan[:scan.index("remove_variable = te_cm_tmp_cnt")]
        # Every acceptance test sits under a limit that holds only for a part that has not joined.
        self.assertIn(
            "if = { limit = { local_var:te_cm_cp_joined = 0 var:te_cm_tmp_cnt >= local_var:te_cm_cp_min_cnt }",
            scan,
        )
        self.assertEqual(self.body.count("country_average_culture_pop_acceptance"), 4)
        self.assertEqual(scan.count("country_average_culture_pop_acceptance"), 4)
        guarded = scan[scan.index("local_var:te_cm_cp_joined = 0"):]
        self.assertEqual(guarded.count("country_average_culture_pop_acceptance"), 4)
        # Nothing but that scan writes the failure counters, so for a joined part they stay at their reset 0
        # and the gate (hold open/close, which still reads them) tests the hold alone.
        writes = re.findall(r"change_local_variable = \{ name = (te_cm_cp_fail_\w+) add = 1 \}", self.body)
        self.assertEqual(len(writes), 4)
        self.assertEqual(self.body.count("change_local_variable = { name = te_cm_cp_fail"), 4)
        for name in ("te_cm_cp_fail_open", "te_cm_cp_fail_close", "te_cm_cp_fail_high_open", "te_cm_cp_fail_high_close"):
            self.assertIn("set_local_variable = { name = %s value = 0 }" % name, self.body)
            self.assertLess(self.body.index("set_local_variable = { name = %s value = 0 }" % name),
                            self.body.index("limit = { local_var:te_cm_cp_joined = 0"))

    def test_the_scan_still_clears_the_holder_variable_for_a_joined_part(self):
        # The holders are noted in the walk above whether or not the part joined, so the scan must remove
        # every one of them, joined or not.
        self.assertRegex(self.body, r"remove_variable = te_cm_tmp_cnt \} if = \{ limit = \{ local_var:te_cm_cp_tier = 2 \}")

    def test_the_gate_still_has_its_hysteresis_pairs(self):
        self.assertIn(
            "if = { limit = { var:te_cm_ok_$MERGE$_$CULTURE$ = 1 } "
            "if = { limit = { OR = { var:te_cm_held_$MERGE$_$CULTURE$ < te_cm_hold_close local_var:te_cm_cp_fail_close > 0 } } "
            "set_variable = { name = te_cm_ok_$MERGE$_$CULTURE$ value = 0 } } } "
            "else = { if = { limit = { var:te_cm_held_$MERGE$_$CULTURE$ >= te_cm_hold_open local_var:te_cm_cp_fail_open = 0 } "
            "set_variable = { name = te_cm_ok_$MERGE$_$CULTURE$ value = 1 } } }",
            self.body,
        )


class YearlyConversionTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.effects = text_of(GEN_EFFECTS)
        cls.body = squash(block(cls.effects, "te_cmg_yearly_country"))
        cls.on_actions = text_of(ON_ACTIONS)

    def test_every_merge_has_one_section_that_converts_its_joined_parts(self):
        for merge in cfg.MERGES:
            key = merge.key
            sec = section(self.body, key)
            self.assertEqual(sec.count("te_cm_state_%s ?= 1" % key), 1, key)
            self.assertEqual(sec.count("exists = global_var:te_cm_starter_%s" % key), 1, key)
            self.assertEqual(sec.count("te_cm_convert_part"), len(joinable(merge)), key)
            for culture in joinable(merge):
                self.assertEqual(
                    sec.count("te_cm_convert_part = { MERGE = %s CULTURE = %s RESULT = %s TIER = %d }"
                              % (key, culture, merge.result, tier_of(merge, culture))),
                    1, "%s/%s" % (key, culture),
                )

    def test_the_starter_is_saved_before_the_sphere_reads_it(self):
        # Ruling (d): a scope left over from the census in the same on_action may hold another country.
        for merge in cfg.MERGES:
            sec = section(self.body, merge.key)
            save = "global_var:te_cm_starter_%s = { save_temporary_scope_as = te_cm_starter }" % merge.key
            self.assertEqual(sec.count(save), 1, merge.key)
            self.assertLess(sec.index(save), sec.index("te_cm_in_sphere = yes"), merge.key)
            self.assertLess(sec.index(save), sec.index("scope:te_cm_starter = {"), merge.key)

    def test_a_country_outside_the_starters_sphere_or_a_dead_starter_converts_nothing(self):
        for merge in cfg.MERGES:
            sec = section(self.body, merge.key)
            gate = sec[sec.index("scope:te_cm_starter = { is_country_alive = yes }"):]
            self.assertLess(gate.index("te_cm_in_sphere = yes"), gate.index("te_cm_convert_part"), merge.key)

    def test_the_whole_merge_stalls_on_the_core_while_it_runs_only(self):
        # The brief and R23: core_ok and the core-only te_cm_sol_ok_<m> stall the merge. A complete merge has no
        # core part left to stall it, and te_cm_sol_ok_<m> keeps its last value once no core part has a figure.
        for merge in cfg.MERGES:
            key = merge.key
            sec = section(self.body, key)
            self.assertIn(
                "OR = { global_var:te_cm_state_%s ?= 2 scope:te_cm_starter = { te_cmg_%s_core_ok = yes var:te_cm_sol_ok_%s ?= 1 } }"
                % (key, key, key),
                sec, key,
            )

    def test_one_part_stalls_on_its_own_gates_read_on_the_starter(self):
        # R29: the hold alone for a joined part (te_cm_ok); R23: an optional part also its own SoL gate; a core part
        # does not read te_cm_sol_ok_<m>_<c> (the merge-wide gate covers it).
        for merge in cfg.MERGES:
            key = merge.key
            sec = section(self.body, key)
            for culture in joinable(merge):
                gates = "var:te_cm_ok_%s_%s ?= 1" % (key, culture)
                if culture in optional_cultures(merge):
                    gates += " var:te_cm_sol_ok_%s_%s ?= 1" % (key, culture)
                self.assertIn(
                    "if = { limit = { global_var:te_cm_joined_%s_%s ?= 1 NOT = { has_global_variable = te_cm_switched_%s } "
                    "scope:te_cm_starter = { %s } } te_cm_convert_part" % (key, culture, culture, gates),
                    sec, "%s/%s" % (key, culture),
                )

    def test_a_part_that_has_not_joined_or_has_switched_is_not_converted(self):
        for merge in cfg.MERGES:
            for culture in joinable(merge):
                sec = section(self.body, merge.key)
                head = sec[sec.index("CULTURE = %s RESULT" % culture) - 400:sec.index("CULTURE = %s RESULT" % culture)]
                self.assertIn("global_var:te_cm_joined_%s_%s ?= 1" % (merge.key, culture), head)
                self.assertIn("NOT = { has_global_variable = te_cm_switched_%s }" % culture, head)

    def test_the_tier_passed_is_the_parts_own(self):
        # Pan-Turkic mixes tiers (Kazak tier 1, Tatar tier 1b, the others tier 2): the pause pair follows the part.
        body = section(self.body, "pan_turkic")
        self.assertIn("CULTURE = kazak RESULT = cm_pan_turkic TIER = 1 }", body)
        self.assertIn("CULTURE = tatar RESULT = cm_pan_turkic TIER = 2 }", body)
        self.assertIn("CULTURE = uzbek RESULT = cm_pan_turkic TIER = 3 }", body)

    def test_the_conversion_runs_on_every_countrys_own_pulse_outside_the_census_guard(self):
        # Ruling (e): not under the calendar-year guard or the lock, which let one country a year through.
        flat = squash(block(self.on_actions, "te_cm_yearly_on_action"))
        call = "if = { limit = { te_cm_system_enabled = yes } te_cmg_yearly_country = yes }"
        self.assertEqual(flat.count("te_cmg_yearly_country = yes"), 1)
        self.assertIn(call, flat)
        census_if = flat[flat.index("effect = { ") + len("effect = { "):flat.index(call)]
        self.assertIn("te_cmg_census_all = yes", census_if)
        self.assertNotIn("te_cmg_yearly_country", census_if)
        # The census `if` is closed before the conversion starts: the call is a sibling, not nested in it.
        self.assertEqual(census_if.count("{"), census_if.count("}"))
        self.assertTrue(flat.endswith(call + " }"))

    def test_the_hook_runs_the_yearly_on_action(self):
        self.assertIn("on_actions = { te_cm_yearly_on_action }", squash(block(self.on_actions, "on_yearly_pulse_country")))


class DominanceTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.text = text_of(EFFECTS)
        cls.body = squash(block(cls.text, "te_cm_census_dominance"))
        cls.effects = text_of(GEN_EFFECTS)

    def test_dominance_value_guards_zero(self):
        # The denominator is tested before the division, and a zero one gives 0 (the part still exists
        # somewhere) or 1 (it is gone from the world).
        divide = self.body.index("divide = local_var:te_cm_dm_total")
        guard = self.body.index("limit = { local_var:te_cm_dm_total > 0 }")
        self.assertLess(guard, divide)
        self.assertEqual(self.body.count("divide"), 1)
        self.assertRegex(self.body, r"else = \{ set_global_variable = \{ name = te_cm_dom_\$MERGE\$_\$CULTURE\$ value = 0 \} \}$")
        self.assertIn(
            "NOT = { any_country = { culture_percent_country = { target = cu:$CULTURE$ value > 0 } } } } "
            "set_global_variable = { name = te_cm_dom_$MERGE$_$CULTURE$ value = 1 }",
            self.body,
        )

    def test_dominance_reads_the_census_and_walks_nothing_itself(self):
        # Ruling (a), R22: the part's remaining pops and the result's pops in its homeland states are the
        # census's globals; te_cm_home_r_<c> first exists at the census after the join, so it is read guarded.
        self.assertNotIn("every_scope_homeland_state", self.body)
        self.assertNotIn("every_scope_pop", self.body)
        self.assertNotIn("every_country", self.body)
        self.assertIn(
            "if = { limit = { has_global_variable = te_cm_home_r_$CULTURE$ } "
            "set_local_variable = { name = te_cm_dm_res value = global_var:te_cm_home_r_$CULTURE$ } }",
            self.body,
        )
        self.assertIn(
            "if = { limit = { has_global_variable = te_cm_home_$CULTURE$ } "
            "set_local_variable = { name = te_cm_dm_part value = global_var:te_cm_home_$CULTURE$ } }",
            self.body,
        )
        # The census stores the result's figure for a joined part, from the same walk.
        census = squash(block(self.text, "te_cm_census_culture_joined"))
        self.assertIn("name = te_cm_home_r_$CULTURE$ value = local_var:te_cm_cc_res", census)
