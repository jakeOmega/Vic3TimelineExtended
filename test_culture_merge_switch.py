    # ---- the rule against the real homeland scripts -------------------------------------------------------

    def make(self, *, successor_homeland=True, switched=True, removal=".1", shares=None):
        """A state: the owner's primary culture `a`, a part `north_german` that switched into `cm_german`, both
        below the disappearance threshold, both homelands unless the successor's is left out."""
        owner = obj("country", primary={"a"}, legitimacy=50, modifiers={"country_homelands_can_change_bool": True})
        cultures = [obj("culture", name=n) for n in ("a", "north_german", "cm_german")]
        state = obj("state", owner=owner, turmoil=Decimal(0),
                    shares={k: Decimal(v) for k, v in (shares or {"a": ".8", "north_german": ".05", "cm_german": ".05"}).items()},
                    cultures=cultures,
                    modifiers={"state_homeland_creation_threshold_add": Decimal(".6"),
                               "state_homeland_removal_threshold_add": Decimal(removal),
                               "state_homeland_change_speed_mult": Decimal(0)})
        homelands = {"north_german"} | ({"cm_german"} if successor_homeland else set())
        state["state_region"] = obj("region", states=[state], homelands=homelands)
        sim = Script(state)
        if switched:
            sim.globals["te_cm_switched_north_german"] = cultures[2]
        return sim

    def months(self, sim, n):
        for _ in range(n):
            sim.month()

    def test_a_switched_part_is_kept_while_its_successor_is_a_homeland_there(self):
        sim = self.make(shares={"a": ".9", "north_german": ".05", "cm_german": ".05"}, successor_homeland=True)
        # cm_german is itself a removal candidate (not primary, below the threshold); the part is exempt.
        self.months(sim, 5)
        projects = {p["variables"]["te_homeland_culture"]["name"] for p in sim.projects("removal")}
        self.assertEqual(projects, {"cm_german"})
        # An ordinary part (nothing switched) gets its project like the successor.
        plain = self.make(switched=False)
        self.months(plain, 5)
        self.assertEqual({p["variables"]["te_homeland_culture"]["name"] for p in plain.projects("removal")},
                         {"north_german", "cm_german"})

    def test_removing_the_successors_homeland_removes_the_parts_with_it(self):
        sim = self.make()
        self.months(sim, 119)
        self.assertEqual(sim.root["state_region"]["homelands"], {"north_german", "cm_german"})
        sim.month()
        # The owner's primary culture forms its own homeland in the same month (the creation track).
        self.assertEqual(sim.root["state_region"]["homelands"], {"a"})
        self.assertEqual(sim.notifications.count("homeland_removed"), 1)
        self.assertEqual(len(sim.projects("removal")), 0)

    def test_a_part_whose_successor_has_no_homeland_there_is_removed_like_any_other(self):
        sim = self.make(successor_homeland=False, shares={"a": ".9", "north_german": ".05", "cm_german": "0"})
        self.months(sim, 120)
        self.assertEqual(sim.root["state_region"]["homelands"], {"a"})

    def test_nothing_changes_for_a_culture_that_did_not_switch_into_the_removed_one(self):
        sim = self.make(switched=False)
        self.months(sim, 120)
        self.assertEqual(sim.root["state_region"]["homelands"], {"a"})
        # The tie-in reads the global: with it unset the effect removes nothing it was not asked to.
        other = self.make(switched=False, shares={"a": ".7", "north_german": ".3", "cm_german": ".05"})
        self.months(other, 120)
        self.assertEqual(other.root["state_region"]["homelands"], {"a", "north_german"})

    def test_a_removal_project_begun_before_the_switch_is_dropped_by_it(self):
        sim = self.make(switched=False)
        self.months(sim, 60)
        self.assertEqual(len(sim.projects("removal")), 2)
        sim.globals["te_cm_switched_north_german"] = sim.root["cultures"][2]
        sim.month()
        names = {p["variables"]["te_homeland_culture"]["name"] for p in sim.projects("removal")}
        self.assertEqual(names, {"cm_german"})
        self.months(sim, 59)
        self.assertEqual(sim.root["state_region"]["homelands"], {"a"})
        # ... and only because the successor's homeland went; the part was never removed on its own.
        self.assertEqual(sim.notifications.count("homeland_removed"), 1)


