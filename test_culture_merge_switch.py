            core = [c for part in merge.core for c in part.cultures if not _absorb_result(merge, c)]
            node = triggers["te_cmg_%s_core_switched" % key]

            def world(joined, switched):
                globals_ = {"te_cm_joined_%s_%s" % (key, c): 1 for c in joined}
                globals_.update({"te_cm_switched_%s" % c: "x" for c in switched})
                return World(globals=globals_)

            self.assertFalse(holds(node.children, world([], [])), key + ": nothing joined is not a completed core")
            self.assertFalse(holds(node.children, world(core, [])), key + ": nothing switched")
            self.assertTrue(holds(node.children, world(core, core)), key + ": every joined core part switched")
