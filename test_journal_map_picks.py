"""The Map Room's picks, generated from one table (scripts/generators/gen_journal_map_picks.py, #1974).

test_journal_map_modes.py holds the picks to the paint (a branch per selector, a button per pick, the groups by
theme). This holds the generator: its output is fresh, its table places every map once, and the maps other files
name (the fitted scales, the systems' and Demographics' map buttons) each have a pick.
"""
import copy
import importlib.util
import os
import re
import subprocess
import sys
import unittest

REPO = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(REPO, "scripts", "generators", "gen_journal_map_picks.py")


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load("gen_journal_map_picks", SCRIPT)


def read(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8-sig") as f:
        return f.read()


class FreshTest(unittest.TestCase):
    def test_the_generated_files_are_fresh(self):
        result = subprocess.run([sys.executable, SCRIPT, "--check"], capture_output=True, text=True, cwd=REPO)
        self.assertEqual(result.returncode, 0,
                         f"run python3 scripts/generators/gen_journal_map_picks.py\n{result.stdout}{result.stderr}")

    def test_each_file_starts_with_one_bom_and_its_header(self):
        for rel, body in gen.outputs().items():
            with self.subTest(file=str(rel)):
                self.assertTrue(body.startswith(b"\xef\xbb\xbf# AUTO-GENERATED by scripts/generators/"))
                self.assertFalse(body[3:].startswith(b"\xef\xbb\xbf"))


class TableTest(unittest.TestCase):
    def setUp(self):
        self.maps, self.groups = copy.deepcopy(gen.MAPS), copy.deepcopy(gen.GROUPS)

    def tearDown(self):
        gen.MAPS[:], gen.GROUPS[:] = self.maps, self.groups

    def test_the_table_validates(self):
        gen.validate()

    def test_a_map_left_out_of_every_group_fails(self):
        gen.GROUPS[0]["rows"][0] = gen.GROUPS[0]["rows"][0][1:]
        with self.assertRaisesRegex(ValueError, "missing"):
            gen.validate()

    def test_a_map_in_two_groups_fails(self):
        gen.GROUPS[1]["rows"][-1] = gen.GROUPS[1]["rows"][-1][:1] + [gen.GROUPS[0]["rows"][0][0]]
        with self.assertRaisesRegex(ValueError, "twice"):
            gen.validate()

    def test_a_selector_used_twice_fails(self):
        gen.MAPS[1]["sel"] = gen.MAPS[0]["sel"]
        with self.assertRaisesRegex(ValueError, "twice"):
            gen.validate()

    def test_a_row_too_wide_fails(self):
        gen.GROUPS[0]["rows"] = [sum(gen.GROUPS[0]["rows"], [])]
        with self.assertRaisesRegex(ValueError, "a row of"):
            gen.validate()

    def test_selector_2_stays_retired(self):
        # 2 was literacy: a save holding it shows "Pick a map" (te_journal_map_values.txt)
        self.assertNotIn(2, [m["sel"] for m in gen.MAPS])


class GatesTest(unittest.TestCase):
    def test_a_group_hides_only_when_every_map_in_it_is_gated(self):
        for group in gen.GROUPS:
            gates = gen.group_gates(group)
            keys = [k for row in group["rows"] for k in gen.row_maps(row)]
            with self.subTest(group=group["key"]):
                if any(gen.by_key()[k].get("gate") is None for k in keys):
                    self.assertIsNone(gates)
                else:
                    self.assertTrue(gates)

    def test_a_row_hides_with_the_gate_its_maps_share(self):
        gui = gen.render_gui()
        for group in gen.GROUPS:
            for row in group["rows"]:
                gate = gen.row_gate(row)
                first = f"te_jmap_pick_{gen.row_maps(row)[0]}_sgui"
                row_line = (f"\t\t\t\tvisible = \"[GetScriptedGui('{first}').IsShown( GuiScope.SetRoot( "
                            "GetPlayer.MakeScope ).End )]\"\n\t\t\t\tdirection = horizontal")
                with self.subTest(row=row):
                    self.assertEqual(row_line in gui, gate is not None)

    def test_a_mixed_group_s_gates_are_an_or(self):
        group = dict(key="x", name="X", note="n", rows=[["emissions", "nuclear"]])
        gen.GROUPS.append(group)
        try:
            self.assertEqual(gen.group_gates(group), ["has_game_rule = global_warming_enabled",
                                                      "has_game_rule = nuclear_weapons_enabled"])
            body = gen.render_sguis()
            block = body[body.index("te_jmap_cat_x_sgui = {"):]
            self.assertIn("\t\tOR = {\n\t\t\thas_game_rule = global_warming_enabled\n", block)
        finally:
            gen.GROUPS.remove(group)


class SlotTest(unittest.TestCase):
    """A class's two maps share a place in its row (#1975): the Count/Share switch shows one of them."""

    def test_each_class_slot_holds_its_count_then_its_share(self):
        classes = gen.classes
        self.assertEqual(set(gen.SLOTS), {classes.slot(c) for c in classes.CLASSES})
        for c in classes.CLASSES:
            count, share = gen.SLOTS[classes.slot(c)]
            maps = gen.by_key()
            self.assertEqual((maps[count]["sel"], maps[count]["mode"]), (c["count_sel"], classes.MODE_COUNT))
            self.assertEqual((maps[share]["sel"], maps[share]["mode"]), (c["share_sel"], classes.MODE_SHARE))

    def test_a_row_counts_its_slots_not_its_buttons(self):
        rows = next(g["rows"] for g in gen.GROUPS if g["key"] == "classes")
        self.assertEqual(rows, [[f"class_{p}" for p in row] for row in gen.classes.ROWS])
        self.assertTrue(all(len(row) == gen.ROW_WIDTH for row in rows))
        self.assertTrue(all(len(gen.row_maps(row)) == 2 * gen.ROW_WIDTH for row in rows))

    def test_a_class_pick_asks_the_switch(self):
        body = gen.render_sguis()
        for m in gen.MAPS:
            block = body[body.index(f"te_jmap_pick_{m['key']}_sgui = {{"):]
            block = block[:block.index("\n}\n")]
            self.assertEqual("te_jmap_class_mode = " in block, "mode" in m, m["key"])
            if "mode" in m:
                self.assertIn(f"\t\tte_jmap_class_mode = {m['mode']}\n", block)


class ReachTest(unittest.TestCase):
    def test_every_fitted_map_has_a_pick(self):
        scales = load("gen_journal_map_scales", os.path.join(REPO, "scripts", "generators", "gen_journal_map_scales.py"))
        sels = {m["sel"] for m in gen.MAPS}
        for scale in scales.SCALES:
            if scales.fitted(scale) and scales.in_room(scale):
                self.assertIn(scale["sel"], sels, scale["name"])

    def test_every_map_button_names_a_pick(self):
        # the Demographics and system tabs' buttons pick a map before they open the Map Room
        picks = {f"te_jmap_pick_{m['key']}_sgui" for m in gen.MAPS}
        named = set(re.findall(r"GetScriptedGui\('(te_jmap_pick_\w+_sgui)'\)", read("gui/te_map_widgets.gui")))
        self.assertTrue(named)
        self.assertEqual(named - picks, set())

    def test_the_hand_written_file_keeps_no_pick(self):
        self.assertNotRegex(read("common/scripted_guis/te_journal_map_sguis.txt"), r"(?m)^te_jmap_pick_\w+_sgui\s*=")
        self.assertNotIn("type te_jmap_pick_row", read("gui/te_map_widgets.gui"))

    def test_the_page_mounts_the_row(self):
        self.assertIn("te_jmap_pick_row = {}", read("gui/journal_entry_widgets/te_map_room_widget.gui"))


if __name__ == "__main__":
    unittest.main()
