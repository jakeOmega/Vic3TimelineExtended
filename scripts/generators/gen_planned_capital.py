#!/usr/bin/env python3
"""Write te_demog_capital_generated.txt: the Planned Capital decision's move.

set_capital takes a state region's key, never a scope: the engine's effects.log
documents it as `set_capital = X  Where X is a state region` with no Supported
Targets line (the effects that take a scope list one), and vanilla and every
Workshop mod on disk write a literal (`set_capital = STATE_LAZIO`). So the
decision (docs/superpowers/specs/2026-10-08-demographics-design.md §5.1;
te_demog_pc_build in common/scripted_effects/te_demog_place_effects.txt)
dispatches on its chosen site's state region: one branch for each land state
region in map_data/state_regions/ (the sea file skipped), read by
gen_region_area.land_regions.

Needs nothing but the repo. Re-run after a state region is added or renamed;
test_demographics_place.py fails CI when the committed file is stale:

    python3 scripts/generators/gen_planned_capital.py [--check]
"""
import argparse
import importlib.util
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "common", "scripted_effects", "te_demog_capital_generated.txt")

_spec = importlib.util.spec_from_file_location(
    "gen_region_area", os.path.join(REPO, "scripts", "generators", "gen_region_area.py"))
_region_area = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_region_area)


def regions():
    """Every land state region's key, sorted."""
    return sorted(_region_area.land_regions())


def render(keys=None):
    keys = regions() if keys is None else keys
    lines = [
        "# AUTO-GENERATED by scripts/generators/gen_planned_capital.py — do not edit manually.",
        "# The Planned Capital decision's move (te_demog_pc_build, te_demog_place_effects.txt). set_capital takes a",
        "# state region's key, never a scope, so this dispatches on scope:te_pc_site's state region: one branch for",
        "# each land state region in map_data/state_regions/. Re-run the generator after a state region is added or",
        "# renamed; test_demographics_place.py fails when this file is stale.",
        "",
        "# THIS = ROOT = the country; scope:te_pc_site = the state its capital moves to (its own, incorporated).",
        "te_demog_pc_set_capital = {",
    ]
    for i, key in enumerate(keys):
        kind = "if" if i == 0 else "else_if"
        lines.append(f"\t{kind} = {{ limit = {{ scope:te_pc_site = {{ state_region = s:{key} }} }} set_capital = {key} }}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale; write nothing")
    args = parser.parse_args()
    text = render()
    if args.check:
        try:
            with open(OUT, encoding="utf-8-sig") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f"{os.path.relpath(OUT, REPO)} is stale: run scripts/generators/gen_planned_capital.py")
            return 1
        print(f"{os.path.relpath(OUT, REPO)} is current")
        return 0
    with open(OUT, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print(f"wrote {len(regions())} state regions to {os.path.relpath(OUT, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
