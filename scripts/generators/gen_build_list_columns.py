"""The construction list's figure column for the mod's buildings that have a
better figure than productivity (a Workshop request, 2026-11-15).

When the player picks a building to construct, vanilla lists the states it can
go in (gui/map_list_panel.gui). One column shows each state's productivity
impact, except for Government Administration (the state's tax capacity balance)
and Trade Center (its trade capacity balance). The cell is the type
`productivity_or_other_information`; its header is a sort button inside the
types `construction_headers_condensed` and `construction_headers_full`, one
for each of the list's two layouts. This redefines those three types (gotcha
#30 in docs/guides/gui_modding_guide.md: a 00_ file's definition is read
first and wins) with a column of the mod's own for each building in COLUMNS,
so the rest of vanilla's file stays vanilla's.

Each redefined type is vanilla's, with two kinds of `### MOD: Build list
columns` block:
- the productivity textbox's and the productivity header's `visible`, ANDed
  with a test that the building is none of COLUMNS' (vanilla's expression
  kept verbatim inside the new one);
- one textbox (the cell) or sort button (the header) per column, after
  vanilla's last case (the cell's Trade Center textbox, the headers' trade
  capacity button), so it sits in the same slot.

The headers have no onclick: MapListPanel.Sort takes a key the engine knows
(`tax_capacity_balance`, `trade_capacity_balance`, ...), and nothing in the
engine's data types lists the keys or lets script add one, so a mod column
can't be sorted. Their tooltips say so.

Run after a vanilla patch, with test_fixtures/vanilla_gui/map_list_panel.gui
replaced by the new vanilla file:
    python3 scripts/generators/gen_build_list_columns.py
It writes gui/00_te_build_list_columns.gui; never hand-edit it. --check writes
nothing and exits 1 if the file is stale. It raises, naming what moved, if a
line its blocks hook onto is no longer where it was. test_build_list_columns.py
holds the output to the fixture and the fixture to the installed game.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
VANILLA = ROOT / "test_fixtures" / "vanilla_gui" / "map_list_panel.gui"
OUT = ROOT / "gui" / "00_te_build_list_columns.gui"

HEADER = "AUTO-GENERATED by scripts/generators/gen_build_list_columns.py; do not edit manually."
MOD_OPEN = "### MOD: Build list columns"
MOD_CLOSE = "### END MOD ###"
VANILLA_LINE = "# vanilla: "
GROUP = "te_build_list_columns"

CELL_TYPE = "productivity_or_other_information"
HEADER_TYPES = ("construction_headers_condensed", "construction_headers_full")

# What each redefined type tests the building through: the cell has the
# listed building in its datacontext, the headers only the panel's type.
CELL_BUILDING = "Building.GetBuildingType"
HEADER_BUILDING = "MapListBuildingPanel.GetBuildingType"


@dataclass(frozen=True)
class Column:
    building: str       # the building type's key
    what: str           # a few words for the MOD block comments
    cell_text: str      # the cell's raw_text (the cell has Building and State)
    cell_tooltip: str   # loc key
    header_icon: str    # texture of the header's icon (70 px slot: icon, no text)
    header_tooltip: str  # loc key


COLUMNS = (
    # The pollution cut is the reason to build one; vanilla's own state
    # pollution list shows the same figure with the same tooltip
    # (state_pollution_map_list_panel).
    Column(
        building="building_national_park",
        what="the state region's pollution impact",
        cell_text="[State.GetStateRegion.GetPollutionImpact|%R1]",
        cell_tooltip="STATE_POLLUTION",
        header_icon="gfx/interface/icons/state_status_icons/pollution.dds",
        header_tooltip="te_build_list_pollution_header_tt",
    ),
    # Public Housing raises the state's crowding threshold, so it pays where
    # crowding cuts migration pull: the penalty the state view's crowding
    # tile shows (gui/states_panel.gui), one script-value read per row.
    Column(
        building="building_public_housing",
        what="the migration pull the state loses to crowding",
        cell_text="[State.MakeScope.ScriptValue('migration_crowding_pull_pct')|%0-]",
        cell_tooltip="te_build_list_crowding_tt",
        header_icon="gfx/interface/icons/generic_icons/population.dds",
        header_tooltip="te_build_list_crowding_header_tt",
    ),
    # Carbon Conversion Works makes no goods on Direct Air Capture, the method
    # it unlocks with (carbon_capture_and_storage), so its productivity is zero
    # in every state; Synthetic Coal (genetic_engineering) sells coal. Both buy
    # 1,200 Electricity a staffed level, 98% and 99% of their inputs at base
    # prices, and Electricity is a local good, so the state's price ranks
    # states under either method (coal sells at one price across a market).
    # The cell can't tell which method an unbuilt level would run: the GUI has
    # no lookup of a production method by key. Its tooltip keeps productivity,
    # for the coal method.
    Column(
        building="building_synthetics_plant_coal",
        what="the state's Electricity price, nearly all of a level's running cost",
        cell_text="#v @money![State.MakeScope.ScriptValue('te_build_list_electricity_price')|1]#!",
        cell_tooltip="te_build_list_electricity_tt",
        header_icon="gfx/interface/icons/goods_icons/electricity.dds",
        header_tooltip="te_build_list_electricity_header_tt",
    ),
)


def is_building(subject, building):
    return f"ObjectsEqual({subject}, GetBuildingType('{building}').Self)"


def none_of(subject, columns=COLUMNS):
    """Not(any column's building), Or nested two arguments at a time."""
    tests = [is_building(subject, column.building) for column in columns]
    expr = tests[-1]
    for test in reversed(tests[:-1]):
        expr = f"Or({test}, {expr})"
    return f"Not({expr})"


def vanilla_productivity_test(subject):
    """Vanilla's test for the productivity cell and header: neither
    Government Administration nor Trade Center."""
    return (f"And(Not({is_building(subject, 'building_government_administration')}), "
            f"Not({is_building(subject, 'building_trade_center')}))")


def type_span(lines, name):
    """The first and last line of `type <name> = ...`."""
    starts = [i for i, line in enumerate(lines) if line.strip().startswith(f"type {name} = ")]
    if len(starts) != 1:
        raise ValueError(f"vanilla has {len(starts)} `type {name} = ` (expected one): update gen_build_list_columns.py")
    return starts[0], close(lines, starts[0])


def close(lines, start):
    """The line that closes the block opened on line `start`."""
    depth = 0
    for i in range(start, len(lines)):
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0:
            return i
    raise ValueError(f"the block at line {start + 1} never closes")


def indent_of(line):
    return line[:len(line) - len(line.lstrip("\t"))]


def mod_block(indent, why, vanilla, new):
    lines = [f"{indent}{MOD_OPEN}: {why}"]
    lines += [f"{indent}{VANILLA_LINE}{line.strip()}" for line in vanilla if line.strip()]
    return lines + new + [f"{indent}{MOD_CLOSE}"]


def narrowed(body, name, subject):
    """`body` with its one productivity `visible` ANDed with none_of()."""
    old = f'visible = "[{vanilla_productivity_test(subject)}]"'
    at = [i for i, line in enumerate(body) if line.strip() == old]
    if len(at) != 1:
        raise ValueError(f"vanilla's {name} has {len(at)} productivity tests `{old}` (expected one): "
                         "update gen_build_list_columns.py")
    i = at[0]
    indent = indent_of(body[i])
    new = f'{indent}visible = "[And({vanilla_productivity_test(subject)}, {none_of(subject)})]"'
    return body[:i] + mod_block(indent, "productivity, but not for a building with a column below",
                                [body[i]], [new]) + body[i + 1:]


def cell_widget(indent, column):
    return [
        f"{indent}textbox = {{",
        f'{indent}\tvisible = "[{is_building(CELL_BUILDING, column.building)}]"',
        f'{indent}\traw_text = "{column.cell_text}"',
        f'{indent}\ttooltip = "{column.cell_tooltip}"',
        "",
        f"{indent}\telide = right",
        f"{indent}\tfontsize_min = 12",
        "",
        f'{indent}\tblock "productivity_info_text_style" {{}}',
        f"{indent}}}",
    ]


def header_widget(indent, column):
    return [
        f"{indent}sort_button = {{",
        f'{indent}\tvisible = "[{is_building(HEADER_BUILDING, column.building)}]"',
        f"{indent}\talign = hcenter|nobaseline",
        f'{indent}\ttooltip = "{column.header_tooltip}"',
        f"{indent}\tsize = {{ 70 20 }}",
        "",
        f"{indent}\ticon = {{",
        f'{indent}\t\ttexture = "{column.header_icon}"',
        f"{indent}\t\tsize = {{ 25 25 }}",
        f"{indent}\t\tparentanchor = center",
        f"{indent}\t\talwaystransparent = yes",
        f"{indent}\t}}",
        f"{indent}}}",
    ]


def added(indent, widget):
    lines = []
    for column in COLUMNS:
        lines += [f"{indent}# {column.building}: {column.what}"] + widget(indent, column) + [""]
    return mod_block(indent, "a column of the mod's own for these buildings", [], ["", *lines[:-1]])


def redefined_cell(lines):
    start, end = type_span(lines, CELL_TYPE)
    body = narrowed(lines[start:end + 1], CELL_TYPE, CELL_BUILDING)
    # After vanilla's last case, the Trade Center textbox: the type's last widget.
    trade = [i for i, line in enumerate(body)
             if line.strip() == f'visible = "[{is_building(CELL_BUILDING, "building_trade_center")}]"']
    if len(trade) != 1:
        raise ValueError(f"vanilla's {CELL_TYPE} has {len(trade)} Trade Center textboxes (expected one): "
                         "update gen_build_list_columns.py")
    opener = trade[0] - 1
    if body[opener].strip() != "textbox = {":
        raise ValueError(f"vanilla's {CELL_TYPE} Trade Center case is no longer a textbox: update gen_build_list_columns.py")
    after = close(body, opener)
    if any(line.strip() for line in body[after + 1:-1]):
        raise ValueError(f"vanilla's {CELL_TYPE} has something after its Trade Center case: update gen_build_list_columns.py")
    indent = indent_of(body[opener])
    return body[:after + 1] + [""] + added(indent, cell_widget) + body[after + 1:]


def redefined_header(lines, name):
    start, end = type_span(lines, name)
    body = narrowed(lines[start:end + 1], name, HEADER_BUILDING)
    # After the trade capacity button, the last of the three in the slot.
    sort = [i for i, line in enumerate(body) if line.strip() == "onclick = \"[MapListPanel.Sort('trade_capacity_balance')]\""]
    if len(sort) != 1:
        raise ValueError(f"vanilla's {name} has {len(sort)} trade capacity headers (expected one): "
                         "update gen_build_list_columns.py")
    opener = next(j for j in range(sort[0], -1, -1) if body[j].strip() == "sort_button = {")
    after = close(body, opener)
    if after < sort[0]:
        raise ValueError(f"vanilla's {name} trade capacity header moved: update gen_build_list_columns.py")
    indent = indent_of(body[opener])
    return body[:after + 1] + [""] + added(indent, header_widget) + body[after + 1:]


def generated(vanilla_text=None):
    text = VANILLA.read_text(encoding="utf-8-sig") if vanilla_text is None else vanilla_text
    lines = text.splitlines()
    out = [
        f"### {HEADER}",
        "### Vanilla's construction list cell and its two header rows (gui/map_list_panel.gui:",
        f"### {CELL_TYPE}, {HEADER_TYPES[0]}, {HEADER_TYPES[1]}),",
        "### redefined from this file so National Parks show pollution, Public Housing migration",
        "### crowding and Carbon Conversion Works the price of Electricity where other buildings",
        "### show productivity (gui_modding_guide.md gotcha #30: the 00_ file is read first and",
        "### its definitions win). Copied from",
        "### test_fixtures/vanilla_gui/map_list_panel.gui; only the `### MOD: Build list columns`",
        "### blocks differ.",
        "",
        f"types {GROUP} {{",
    ]
    out += redefined_cell(lines) + [""]
    for name in HEADER_TYPES:
        out += redefined_header(lines, name) + [""]
    return "\n".join(out[:-1] + ["}"]) + "\n"


def written():
    return ("﻿" + generated()).encode("utf-8")


def main(argv=None):
    """Write the file; with --check, write nothing and exit 1 if it is stale."""
    argv = sys.argv[1:] if argv is None else argv
    data = written()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_bytes() != data:
            print(f"stale: {OUT.relative_to(ROOT).as_posix()} (run python3 scripts/generators/gen_build_list_columns.py)")
            return 1
        return 0
    OUT.write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
