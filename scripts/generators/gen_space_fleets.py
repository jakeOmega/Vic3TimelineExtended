def var(n: int | str, name: str) -> str:
    return f"sr_fl_{n}_{name}"


def _chain(cases: list[tuple[str, list[str]]], indent: int = 1, else_body: list[str] | None = None) -> list[str]:
    """An if / else_if chain: cases are (limit, body lines)."""
    tab = "\t" * indent
    out = []
    for i, (limit, body) in enumerate(cases):
        out.append(f"{tab}{'if' if i == 0 else 'else_if'} = {{")
        out.append(f"{tab}\tlimit = {{ {limit} }}")
        out += [f"{tab}\t{line}" for line in body]
        out.append(f"{tab}}}")
    if else_body:
        out.append(f"{tab}else = {{")
        out += [f"{tab}\t{line}" for line in else_body]
        out.append(f"{tab}}}")
    return out


