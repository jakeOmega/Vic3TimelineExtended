def _opt(name: str, variable: str, default: str = "0") -> list[str]:
    return [f"{name} = {{", f"\tvalue = {default}", f"\tif = {{ limit = {{ has_variable = {variable} }} value = var:{variable} }}",
            "}"]


def render_slot_values(n: int) -> list[str]:
    out = [f"# --- Slot {n} ---"]
    for r in ROLES:
        out += _opt(var(n, f"{r.key}_value"), var(n, r.key))
        out += _opt(var(n, f"{r.key}_full_value"), var(n, f"{r.key}_full"))
    out += [f"{var(n, 'strength')} = {{", "\tvalue = 0", *[f"\tadd = {var(n, r.key + '_value')}" for r in ROLES], "}",
            f"{var(n, 'strength_full')} = {{", "\tvalue = 0",
            *[f"\tadd = {var(n, r.key + '_full_value')}" for r in ROLES], "}",
            f"{var(n, 'screen_strength')} = {{", "\tvalue = 0",
            *[f"\tadd = {var(n, r.key + '_value')}" for r in ROLES if r.screen], "}",
            f"{var(n, 'tender_share')} = {{",
            "\tvalue = 0",
            "\tif = {",
            f"\t\tlimit = {{ {var(n, 'strength')} > 0 }}",
            f"\t\tvalue = {var(n, 'tender_value')}",
            f"\t\tdivide = {var(n, 'strength')}",
            "\t}",
            "}"]
    out += _opt(var(n, "drive_value"), var(n, "drive"))
    out += _opt(var(n, "dv_value"), var(n, "dv"))
    out += _opt(var(n, "supply_value"), var(n, "supply"))
    out += _opt(var(n, "marines_value"), var(n, "marines"))
    out += _opt(var(n, "loc_value"), var(n, "loc"))
    out += _opt(var(n, "posture_value"), var(n, "posture"))
    out += ["# Its pace: its drive, one ahead for rapid response hulls alone (4: antimatter's).",
            f"{var(n, 'pace')} = {{",
            f"\tvalue = {var(n, 'drive_value')}",
            f"\tif = {{ limit = {{ {var(n, 'all_rapid')} = yes }} add = 1 }}",
            "}",
            f"{var(n, 'capacity_base')} = {{",
            f"\tvalue = sr_fl_capacity_{PACE_CAPACITY[0]}"]
    for pace in (1, 2, 3):
        out.append(f"\tif = {{ limit = {{ {var(n, 'pace')} >= {pace} }} value = sr_fl_capacity_{PACE_CAPACITY[pace]} }}")
    out += ["}",
            "# Propellant capacity, km/s: the pace's x (1 + the tenders' share).",
            f"{var(n, 'dv_capacity')} = {{",
            f"\tvalue = {var(n, 'tender_share')}",
            "\tadd = 1",
            f"\tmultiply = {var(n, 'capacity_base')}",
            "}",
            "# Endurance, months: the lowest of its other roles' x (1 + 2 x the tenders'",
            "# share); tenders alone, theirs.",
            f"{var(n, 'endurance')} = {{",
            "\tvalue = sr_fl_endurance_tender"]
    for r in ROLES:
        if r.key != "tender":
            out.append(f"\tif = {{ limit = {{ {var(n, r.key + '_value')} > 0 }} max = sr_fl_endurance_{r.key} }}")
    out += ["\tif = {",
            f"\t\tlimit = {{ {var(n, 'strength')} > {var(n, 'tender_value')} }}",
            f"\t\tmultiply = {{ value = {var(n, 'tender_share')} multiply = 2 add = 1 }}",
            "\t}",
            "}",
            f"{var(n, 'marine_capacity')} = {{",
            f"\tvalue = {var(n, 'carrier_value')}",
            "\tmultiply = sr_fl_marines_per_carrier",
            "}",
            f"{var(n, 'fire_fleets')} = {{", "\tvalue = 0",
            *[f"\tadd = {{ value = {var(n, r.key + '_value')} multiply = sr_fl_fire_fleets_{r.key} }}" for r in ROLES],
            "}",
            f"{var(n, 'fire_defences')} = {{", "\tvalue = 0",
            *[f"\tadd = {{ value = {var(n, r.key + '_value')} multiply = sr_fl_fire_defences_{r.key} }}" for r in ROLES],
            "}",
            "# Repair a month while docked: 20% of the gap at Earth, 10% a Spaceport level",
            "# (the best of ours at the location); 0 elsewhere.",
            f"{var(n, 'repair_share')} = {{",
            "\tvalue = 0",
            f"\tif = {{ limit = {{ has_variable = {var(n, 'loc')} var:{var(n, 'loc')} = {EARTH} }} value = sr_fl_repair_earth }}"]
    for loc in LOCATIONS[1:]:
        out.append(f"\telse_if = {{ limit = {{ has_variable = {var(n, 'loc')} var:{var(n, 'loc')} = {loc.code} }} "
                   f"value = {{ value = sr_loc_port_level_{loc.key} multiply = sr_fl_repair_port_level max = 1 }} }}")
    out.append("}")
    # The leg home from each location, at its pace (the AI's return check).
    for b in LOCATIONS[1:]:
        out += [f"{var(n, f'return_dv_{b.key}')} = {{", f"\tvalue = sr_leg_dv_{PACE_LEGS[0]}_{b.key}_earth"]
        for pace in (1, 2, 3, 4):
            out.append(f"\tif = {{ limit = {{ {var(n, 'pace')} >= {pace} }} value = sr_leg_dv_{PACE_LEGS[pace]}_{b.key}_earth }}")
        out.append("}")
    # The legs from where it is to every location, at its pace.
    for b in LOCATIONS:
        for kind in ("months", "dv"):
            out += [f"{var(n, f'leg_{kind}_{b.key}')} = {{", "\tvalue = 0",
                    "\tif = {", f"\t\tlimit = {{ has_variable = {var(n, 'loc')} }}"]
            first = True
            for a in LOCATIONS:
                if a.key == b.key:
                    continue
                for pace, reader in PACE_LEGS.items():
                    word = "if" if first else "else_if"
                    first = False
                    out.append(f"\t\t{word} = {{ limit = {{ var:{var(n, 'loc')} = {a.code} {var(n, 'pace')} = {pace} }} "
                               f"value = sr_leg_{kind}_{reader}_{a.key}_{b.key} }}")
            out += ["\t}", "}"]
    return out


def _bound(n: int, code: int) -> str:
    """Slot n is in flight to the location of this code."""
    return f"has_variable = sr_fl_{n}_dest var:sr_fl_{n}_dest = {code} NOT = {{ has_variable = sr_fl_{n}_loc }}"


def _hostile_inbound(lc: glw.Location) -> list[str]:
    """The hostile fleets in flight to a location, for the country reading it:
    their strength, and the earliest landing month (each leg caps the value
    with max =, from a ceiling only set when some leg exists)."""
    count = [f"\t\t\tif = {{ limit = {{ {_bound(n, lc.code)} }} add = 1 }}" for n in range(1, SLOTS + 1)]
    each = [f"\t\t\tif = {{ limit = {{ {_bound(n, lc.code)} }} add = sr_fl_{n}_strength }}" for n in range(1, SLOTS + 1)]
    first = [f"\t\t\tif = {{ limit = {{ {_bound(n, lc.code)} }} max = var:sr_fl_{n}_arrive }}" for n in range(1, SLOTS + 1)]
    head = ["\t\tevery_in_global_list = {", "\t\t\tvariable = sr_fleet_powers",
            "\t\t\tlimit = { is_country_alive = yes has_war_with = prev }"]
    listed = ["\tif = {", "\t\tlimit = { has_global_variable_list = sr_fleet_powers }", *head]
    return [f"sr_loc_hostile_inbound_count_{lc.key} = {{", "\tvalue = 0", *listed, *count, "\t\t}", "\t}", "}",
            f"sr_loc_hostile_inbound_strength_{lc.key} = {{", "\tvalue = 0", *listed, *each, "\t\t}", "\t}", "}",
            f"sr_loc_hostile_inbound_first_{lc.key} = {{", "\tvalue = 0",
            "\tif = {", f"\t\tlimit = {{ sr_loc_hostile_inbound_count_{lc.key} > 0 }}", "\t\tvalue = 99999",
            *head, *first, "\t\t}", "\t}", "}"]


