"""Solar System Colonization's fleets: every per-slot and per-location block.

Design: ``docs/superpowers/archive/specs/2026-10-26-solar-colonization-fleets-design.md``
(slice 6: 6a the fleet record, Space Command and movement; 6b combat, blockade,
seizure and destruction; 6c interdiction and the AI's offence), and
``docs/superpowers/specs/2026-10-29-lunar-colonization-design.md`` § 8 (the
Moon's worlds at Earth: Close in there, their blockade, the AI's lunar
offence; no interdiction at Earth). Full Colonies only.

A country keeps up to ``SLOTS`` fleets, all country variables (a revolution's
winner inherits them): ``sr_fl_<n>_loc`` (a location's code; absent while in
transit or empty), ``_dest``, ``_depart`` and ``_arrive`` (in transit), the
strength of each role now and at full (``sr_fl_<n>_<role>``,
``sr_fl_<n>_<role>_full``), ``_dv`` (propellant, km/s), ``_supply`` (months),
``_marines`` (battalions), ``_drive`` and ``_refit_until``, and from 6b
``_posture`` (1 station, 2 stand off, 3 close in; 6c 4 interdict), ``_target``
(a world's index), ``_destroy`` and from 6c ``_icpt`` (the country it
interdicts). A fleet is at one of nine locations (``FLEET_LOCATIONS``:
Earth and the Moon, then the panel's eight; gen_launch_windows.LOCATIONS holds
the bodies their legs are measured to).

Outputs (every block that enumerates slots, roles, locations or worlds; the
arithmetic of one slot is hand-written, parameterized by ``$N$``, in
common/scripted_effects/sr_fleet_effects.txt and sr_fleet_combat_effects.txt):

- ``common/scripted_effects/sr_fleets_generated.txt``: the slot dispatchers
  (``sr_fl_each_slot``, ``sr_fl_by_op``, ``sr_fl_by_local``), the per-slot
  helpers that enumerate roles or locations, the location records, the
  combat step's per-location passes and the console's helpers.
- ``common/scripted_triggers/sr_fleets_generated.txt``: per slot (exists,
  refitting, docked, may depart for each location, the panel's checks) and per
  location (we hold a colony, a Spaceport, a propellant port there).
- ``common/script_values/sr_fleets_generated.txt``: per slot (strength, fire,
  capacity, endurance, the legs to every location) and the totals.
- ``common/script_values/sr_fleets_display_generated.txt``: the panel's.
- ``common/customizable_localization/sr_fleets_generated_custom_loc.txt``: a
  slot's location, destination, target world and drive by name.
- ``gui/journal_entry_widgets/sr_fleets_generated_rows.gui``: the Fleets and
  Locations rows (the colonies' Defenses are a view of gen_solar_sites' Colonies rows).

Run ``python3 scripts/generators/gen_space_fleets.py [--dry-run | --check]``.
A post-load regenerator (``mod_state_server.POST_LOAD_REGENERATORS``).
"""

