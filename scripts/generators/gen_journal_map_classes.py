"""Generate the Map Room's class maps from one table (owner, 2026-11-23, #1975; docs/systems/mod_systems/journal_map_modes.md,
The Class Maps).

Every pop type has two maps, its people and its share of the people, alike but for the class, so they come from one
row each in journal_map_classes.py's CLASSES. This writes:

- `common/script_values/te_journal_map_classes_generated.txt`: each class's share of a state's people
  (te_jmap_share_<pop>) and whether the pick is a class map (te_jmap_pick_class, for the Count/Share switch);
- `common/scripted_effects/te_journal_map_classes_generated.txt`: the yearly walk's counts (te_jmap_class_walk_init,
  _pop and _store, which te_journal_map_effects.txt's te_jmap_walk_* call from Demographics' walk, whatever its rule),
  and te_jmap_class_flip, which moves a class map to its other selector when the switch is flipped;
- `common/named_colors/te_journal_map_classes_generated.txt`: each class's two colors;
- `localization/english/te_journal_maps_generated_l_english.yml`: the picks' names and tooltips and the hovers
  (organize_loc.py's JOURNAL_MAPS_GENERATED, rendered as organize_loc renders it, so the two writers agree);
- the class family's branches in je_te_map_room's map_color and map_tooltip (common/journal_entries/te_journal_maps.txt),
  between the BEGIN and END marker lines this script owns; the rest of the file is hand-written.

The curves come from the same table through gen_journal_map_scales.py (class_rows) and the picks through
gen_journal_map_picks.py. Standard library and the repo only, no game install.
    python3 scripts/generators/gen_journal_map_classes.py [--check]
`--check` lists drifted files, writes nothing and exits 1 on drift (test_journal_map_classes.py runs it).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import journal_map_classes as classes  # noqa: E402
import gen_journal_map_scales as scales  # noqa: E402
from organize_loc import _render_loc_file, section_label  # noqa: E402

VALUES_FILE = Path("common/script_values/te_journal_map_classes_generated.txt")
EFFECTS_FILE = Path("common/scripted_effects/te_journal_map_classes_generated.txt")
COLORS_FILE = Path("common/named_colors/te_journal_map_classes_generated.txt")
LOC_FILE = Path("localization/english/te_journal_maps_generated_l_english.yml")
HOST_FILE = Path("common/journal_entries/te_journal_maps.txt")
LOC_CATEGORY = "JOURNAL_MAPS_GENERATED"

HEADER = "# AUTO-GENERATED by scripts/generators/gen_journal_map_classes.py — do not edit manually\n"
# The marker lines around the class family's branches in the hand-written host: `# BEGIN <MARK> <part>` and
# `# END <MARK> <part>`, each on a line of its own.
MARK = "GENERATED by scripts/generators/gen_journal_map_classes.py (the class maps; edit its table, not these lines):"
PARTS = ("map_color", "map_tooltip")


def sel_line(sel: int) -> str:
    return f"te_jmap_selector = {sel}"


def share_where(c: dict) -> list[str]:
    return [f"has_variable = {classes.count_var(c)}", "has_variable = te_dg_walk_pop", "var:te_dg_walk_pop > 0"]


def count_where(c: dict) -> list[str]:
    var = classes.count_var(c)
    return [f"has_variable = {var}", f"var:{var} > 0"]


def _branch(limit: list[str], body: list[str], first: bool = False) -> list[str]:
    return (["if = {" if first else "else_if = {", "\tlimit = {"] + [f"\t\t{ln}" for ln in limit] + ["\t}"]
            + [f"\t{ln}" for ln in body] + ["}"])


def _lerp(c: dict, factor: str) -> list[str]:
    return ["lerp = {", f"\tmin_color = \"te_jmap_class_{c['pop']}_low\"",
            f"\tmax_color = \"te_jmap_class_{c['pop']}_high\"", f"\tfactor = {factor}", "}"]


def _no_data(body: list[str]) -> list[str]:
    return _branch(["OR = {"] + [f"\t{sel_line(s)}" for s in classes.selectors()] + ["}"], body)


def paint() -> list[str]:
    """map_color's class branches: each class's count (a doubling at a time, a state with none pale) and share, then
    grey for a state the walk hasn't counted yet."""
    out = []
    for c in classes.CLASSES:
        var = classes.count_var(c)
        out += [f"# {c['count_sel']}. {c['name']}, their people: a doubling at a time; a state with none pale."]
        out += _branch([sel_line(c["count_sel"])] + count_where(c),
                       _lerp(c, f"te_jmap_{classes.count_scale(c)}_factor"))
        out += _branch([sel_line(c["count_sel"]), f"has_variable = {var}"], ['value = "te_jmap_none"'])
        out += [f"# {c['share_sel']}. {c['name']}, their share of the people."]
        out += _branch([sel_line(c["share_sel"])] + share_where(c),
                       _lerp(c, f"te_jmap_{classes.share_scale(c)}_factor"))
    out += ["# A state the yearly walk hasn't counted yet: grey."]
    out += _no_data(['value = "te_jmap_no_data"'])
    return out


def hover() -> list[str]:
    """map_tooltip's class branches, in the paint's order: the class's people and their share, both maps alike."""
    out = []
    for c in classes.CLASSES:
        tt = f"te_jmap_tt_class_{c['pop']}"
        out += _branch([sel_line(c["count_sel"])] + count_where(c), [f"custom_tooltip_no_bullet = {tt}"])
        out += _branch([sel_line(c["count_sel"]), f"has_variable = {classes.count_var(c)}"],
                       [f"custom_tooltip_no_bullet = {tt}_none"])
        out += _branch([sel_line(c["share_sel"])] + share_where(c), [f"custom_tooltip_no_bullet = {tt}"])
    out += _no_data(["custom_tooltip_no_bullet = te_jmap_tt_no_census"])
    return out


def splice(text: str, part: str, lines: list[str]) -> str:
    """text with the lines between part's BEGIN and END markers replaced, indented as the BEGIN line is."""
    begin, end = f"# BEGIN {MARK} {part}", f"# END {MARK} {part}"
    rows = text.split("\n")
    starts = [i for i, r in enumerate(rows) if r.strip() == begin]
    ends = [i for i, r in enumerate(rows) if r.strip() == end]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{HOST_FILE}: one BEGIN and one END marker for {part}, in that order")
    indent = rows[starts[0]][:len(rows[starts[0]]) - len(rows[starts[0]].lstrip("\t"))]
    body = [(indent + ln) if ln else "" for ln in lines]
    return "\n".join(rows[:starts[0] + 1] + body + rows[ends[0]:])


def render_host(current: str) -> str:
    out = splice(current, "map_color", paint())
    return splice(out, "map_tooltip", hover())


def _sv(name: str, body: list[str]) -> list[str]:
    return [f"{name} = {{"] + [f"\t{ln}" for ln in body] + ["}"]


def render_values() -> str:
    out = [HEADER.rstrip("\n"),
           "# The Map Room's class maps (journal_map_classes.py; te_journal_maps.txt). Each class's people over the state's,",
           "# 0-1, both the yearly walk's (te_dg_cls_<pop>, te_dg_walk_pop), whatever the Demographics rule: the share map's",
           "# input and the hover's second figure. State scope, as the map paints or hovers."]
    for c in classes.CLASSES:
        var = classes.count_var(c)
        out += [""] + _sv(classes.share_value(c), [
            "value = 0", "if = {", "\tlimit = {", f"\t\thas_variable = {var}", "\t\thas_variable = te_dg_walk_pop", "\t}",
            f"\tvalue = var:{var}", "\tdivide = {", "\t\tvalue = var:te_dg_walk_pop", "\t\tmin = 1", "\t}", "}",
            "min = 0", "max = 1"])
    out += ["", "# 1 while the pick is a class map, either kind: Map Options' Count/Share switch is greyed on any other",
            "# (te_jmap_classes_count_sgui, te_journal_map_sguis.txt). Any scope: the selector is a global."]
    out += _sv("te_jmap_pick_class", ["value = 0", "if = {", "\tlimit = {", "\t\tOR = {"]
               + [f"\t\t\t{sel_line(s)}" for s in classes.selectors()] + ["\t\t}", "\t}", "\tvalue = 1", "}"])
    return "\n".join(out) + "\n"


def render_effects() -> str:
    walk = sorted(classes.CLASSES, key=lambda c: c["walk"])
    out = [HEADER.rstrip("\n"),
           "# The Map Room's class maps (journal_map_classes.py): every pop type's people, counted in Demographics' yearly",
           "# walk (te_demog_walks, te_demog_effects.txt) through te_jmap_walk_init, _pop and _store",
           "# (te_journal_map_effects.txt), whatever the rule, as Armed Forces' soldiers are, and stored as te_dg_cls_<pop>.",
           "# Calls of the Map Room's own, not the census's helpers, which set nothing outside the census",
           "# (test_demographics_registry.py, TestWorkWalk); test_demographics_golden.py leaves them out of the walk it pins.",
           "", "# State scope, before the walk's pop loop."]
    out += _sv("te_jmap_class_walk_init",
               [f"set_local_variable = {{ name = te_jmap_w_{c['pop']} value = 0 }}" for c in walk])
    out += ["", "# Pop scope, in the walk's pop loop: one class each, the classes with the most pops asked first."]
    body = []
    for i, c in enumerate(walk):
        body += ["if = {" if i == 0 else "else_if = {", f"\tlimit = {{ is_pop_type = {c['pop']} }}",
                 f"\tchange_local_variable = {{ name = te_jmap_w_{c['pop']} add = total_size }}", "}"]
    out += _sv("te_jmap_class_walk_pop", body)
    out += ["", "# State scope, after the walk's pop loop."]
    body = [f"set_variable = {{ name = {classes.count_var(c)} value = local_var:te_jmap_w_{c['pop']} }}" for c in walk]
    out += _sv("te_jmap_class_walk_store", body)
    out += ["", "# Map Options' Count/Share switch, just set (te_jmap_set_class_mode, te_journal_map_effects.txt): a class map",
            "# on the page moves to the same class's other map, its people or its share. Country scope, the player's."]
    body = []
    for c in classes.CLASSES:
        for here, there, mode in ((c["count_sel"], c["share_sel"], classes.MODE_SHARE),
                                  (c["share_sel"], c["count_sel"], classes.MODE_COUNT)):
            body += ["if = {" if not body else "else_if = {",
                     f"\tlimit = {{ {sel_line(here)} te_jmap_class_mode = {mode} }}",
                     f"\tte_jmap_set_selector = {{ SEL = {there} }}", "}"]
    out += _sv("te_jmap_class_flip", body)
    return "\n".join(out) + "\n"


def render_colors() -> str:
    out = [HEADER.rstrip("\n"),
           "# The Map Room's class maps (journal_map_classes.py): each class in the hue of its pop type's own color in",
           "# vanilla's pop charts (common/pop_types), nearly white at the low end and deep at the high, on both its maps.",
           "colors = {"]
    for c in classes.CLASSES:
        h, s, v = c["high"]
        out += [f"\t# {c['name']}: {c['words'][0]} to {c['words'][1]}.",
                f"\tte_jmap_class_{c['pop']}_low = hsv360 {{ {c['hue']} {classes.LOW_SAT} {classes.LOW_VAL} }}",
                f"\tte_jmap_class_{c['pop']}_high = hsv360 {{ {h} {s} {v} }}"]
    out.append("}")
    return "\n".join(out) + "\n"


def _select(option: str, own: str, other: str) -> str:
    return (f"[SelectLocalization( EqualTo_CFixedPoint( GetPlayer.MakeScope.ScriptValue('{option}'), "
            f"'(CFixedPoint)0' ), '{own}', '{other}' )]")


def _range(scale: str, fmt: str) -> str:
    return (f"$te_jmap_scaled_lead$ $te_jmap_measured_area$: #v [GetPlayer.MakeScope.ScriptValue('te_jmap_{scale}_lo')|{fmt}]#! "
            f"to #v [GetPlayer.MakeScope.ScriptValue('te_jmap_{scale}_hi')|{fmt}]#!. $te_jmap_measured_trim$")


def loc_entries() -> dict[str, str]:
    rows = {r["name"]: r for r in scales.SCALES}
    out = {}
    for c in classes.CLASSES:
        name, low, high = c["name"], *c["words"]
        state = "[THIS.GetState.GetName]"
        for key, scale, what, fmt, curve, colors, extra in (
                (classes.count_key(c), classes.count_scale(c), ", in people", "K", "te_jmap_scale_in_force_doubling",
                 "te_jmap_color_in_force_none", " A state with none is pale."),
                (classes.share_key(c), classes.share_scale(c), " as a share of its people", "%1",
                 "te_jmap_scale_in_force", "te_jmap_color_in_force", "")):
            pick = f"te_jmap_pick_{key}"
            out[pick] = name
            switch = ("Map Options' Classes row colors them by their share of the people instead." if "in people" in what
                      else "Map Options' Classes row colors them by their people instead.")
            out[f"{pick}_desc"] = "\\n".join([
                f"Color each state by its {name}{what}. {c['about']} Counted once a year. {switch}",
                _range(scale, fmt),
                _select("te_jmap_scale", scales.curve_key(rows[scale]), curve),
                _select("te_jmap_color", f"{pick}_colors", colors)])
            out[f"{pick}_colors"] = f"$te_jmap_color_text_own$ From {low} at the low end to {high} at the high.{extra}"
        count = f"[THIS.GetState.MakeScope.Var('{classes.count_var(c)}').GetValue|K]"
        share = f"[THIS.GetState.MakeScope.ScriptValue('{classes.share_value(c)}')|%1]"
        out[f"te_jmap_tt_class_{c['pop']}"] = f"#b {state}#!\\n{name}: #v {count}#!, #v {share}#! of its people"
        out[f"te_jmap_tt_class_{c['pop']}_none"] = f"#b {state}#!\\nNo {name}."
    return out


def render_loc() -> str:
    entries = {key: f'0 "{text}"' for key, text in loc_entries().items()}
    return _render_loc_file([(section_label(LOC_CATEGORY), entries)]).decode("utf-8-sig")


def outputs(root: Path = ROOT) -> dict[Path, bytes]:
    classes.validate()
    host = (root / HOST_FILE).read_text(encoding="utf-8-sig")
    return {
        root / VALUES_FILE: render_values().encode("utf-8-sig"),
        root / EFFECTS_FILE: render_effects().encode("utf-8-sig"),
        root / COLORS_FILE: render_colors().encode("utf-8-sig"),
        root / LOC_FILE: render_loc().encode("utf-8-sig"),
        root / HOST_FILE: render_host(host).encode("utf-8-sig"),
    }


def main(argv: list[str]) -> int:
    data = outputs()
    drifted = [path for path, body in data.items() if not path.is_file() or path.read_bytes() != body]
    if "--check" in argv:
        for path in drifted:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if drifted else 0
    for path, body in data.items():
        path.write_bytes(body)
    print(f"wrote {len(data)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
