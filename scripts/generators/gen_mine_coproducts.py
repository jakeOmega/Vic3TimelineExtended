"""Generate the co-product mines' production methods (#1419).

Each of the mod's mines below works one mineral, and that mineral's real end uses
span several of the game's goods: aluminum goes into wiring as well as frames, nickel
into stainless steel as well as batteries. So each mine gets its own copy of the three
equipment groups that carry its output (mining equipment, explosives, steam
automation), cloned from the family it ran before (the iron, lead or coal mine's, or
the mod's tech metals mine family), with every positive output of the family's good
split across the goods in `MINES`, in proportion to value at base prices. A method
keeps its inputs, staffing, technologies and total output value, so its profit at base
prices, and with it the AI's choice of method, is unchanged. Only the goods move.

The family groups stay the templates. Change a pump, an explosive or an excavator
there, then rerun this script; `test_mine_coproducts.py` fails while the copies are
stale. No building runs the tech metals mine family's three groups any more: all four
of its mines have their own copies.

What a copy changes besides the outputs:

* method references inside a copy (`unlocking_production_methods`) name the copies;
* a template that burns fuel out of its own output (`pm_emissions.NETTED_FUEL`, the
  Coal Mine's pumps and steam donkey) lists that fuel as an input instead, and splits
  its gross output: a graphite mine buys the coal its pumps burn, at the same profit;
* the `state_greenhouse_gas_emissions_add` line is worked out from the copy's own fuel
  inputs, as `gen_carbon_capture_pms.py` would write it, and the cost comments come
  from `pm_costs.py`, so neither regenerator rewrites this script's file;
* the names are `$template$` references, so a copy reads like its template in every
  language.

Shared methods outside the copied groups that unlock on a template pump
(`pm_tailings_treatment`, `pm_maintenance_mechanized_mine`,
`pm_rail_transport_mine_infrastructure_4`) list the copies too: their
`unlocking_production_methods` blocks end in a generated tail, after `MARKER`.

The buildings themselves (`common/buildings/03_zz_te_mines.txt`) are hand-written and
name their copied groups; `gen_carbon_capture_pms.py` then gives each copied group its
own capture group. After running this script, run ``python3 gen_carbon_capture_pms.py``
and ``python3 organize_loc.py``.

Run ``python3 scripts/generators/gen_mine_coproducts.py [--dry-run | --check]``. No
game install or running server is needed.
"""

