def unwrap(value):
    while isinstance(value, tuple) and len(value) == 2 and value[0] == "=":
        value = value[1]
    return value


# A parsed body as a list of (key, operator, value) entries, value a string, a list of
# strings or another entry list, so repeated keys and key order survive editing.
def to_entries(body):
    entries = []
    for key, value in body.items():
        for operator, item in _pairs(value):
            entries.append([key, operator, _to_value(item)])
    return entries


def _pairs(value):
    if isinstance(value, tuple):
        if len(value) % 2:
            raise ValueError(f"Unexpected parsed value {value!r}")
        return [(value[i], value[i + 1]) for i in range(0, len(value), 2)]
    if isinstance(value, list) and all(isinstance(v, tuple) for v in value):
        return [pair for v in value for pair in _pairs(v)]
    raise ValueError(f"Unexpected parsed value {value!r}")


def _to_value(item):
    if isinstance(item, dict):
        return to_entries(item)
    if isinstance(item, list):
        if not all(isinstance(v, str) for v in item):
            raise ValueError(f"Unexpected parsed list {item!r}")
        return list(item)
    return str(item)


def find(entries, key):
    return [entry for entry in entries if entry[0] == key]


def block(entries, key, create=False, first=False):
    found = [entry for entry in entries if entry[0] == key and isinstance(entry[2], list)
             and not (entry[2] and isinstance(entry[2][0], str))]
    if len(found) > 1:
        raise ValueError(f"Repeated block {key}")
    if found:
        return found[0][2]
    if not create:
        return None
    entry = [key, "=", []]
    entries.insert(0, entry) if first else entries.append(entry)
    return entry[2]


def rename(entries, mapping):
    for entry in entries:
        value = entry[2]
        if isinstance(value, str):
            entry[2] = mapping.get(value, value)
        elif value and isinstance(value[0], str):
            entry[2] = [mapping.get(v, v) for v in value]
        else:
            rename(value, mapping)


def mentions(entries, names):
    for _, _, value in entries:
        if isinstance(value, str):
            if value in names:
                return True
        elif value and isinstance(value[0], str):
            if names.intersection(value):
                return True
        elif mentions(value, names):
            return True
    return False


def number(value: Decimal) -> str:
    text = format(value.quantize(CENT, rounding=ROUND_HALF_UP).normalize(), "f")
    return "0" if text in ("-0", "0") else text


def serialize(name, entries):
    lines = [f"{name} = {{"]
    _serialize(entries, 1, lines)
    lines.append("}")
    return "\n".join(lines)


def _serialize(entries, depth, lines):
    tabs = "\t" * depth
    for key, operator, value in entries:
        if isinstance(value, str):
            lines.append(f"{tabs}{key} {operator} {value}")
        elif value and isinstance(value[0], str):
            lines.append(f"{tabs}{key} {operator} {{")
            lines.extend(f"{tabs}\t{item}" for item in value)
            lines.append(f"{tabs}}}")
        else:
            lines.append(f"{tabs}{key} {operator} {{")
            _serialize(value, depth + 1, lines)
            lines.append(f"{tabs}}}")


def load_state(root: Path = ROOT):
    return pm_emissions.load_state(root)


def emission_factors(root: Path):
    parser = pm_emissions.ParadoxFileParser()
    parser.parse_file(str(root / pm_emissions.FACTORS))
    factors = {fuel: Decimal(unwrap(parser.data[f"gw_emission_factor_{fuel}"])) for fuel in ("coal", "oil")}
    return factors, Decimal(unwrap(parser.data["gw_emission_display_scale"]))


def group_methods(groups, name):
    if name not in groups:
        raise ValueError(f"Missing template group {name}")
    methods = unwrap(unwrap(groups[name])["production_methods"])
    return [methods] if isinstance(methods, str) else list(methods)


def output_goods(entries):
    """{good} of every goods_output line in the method's building modifiers."""
    goods = set()
    modifiers = block(entries, "building_modifiers") or []
    for scale, _, value in modifiers:
        if not isinstance(value, list) or (value and isinstance(value[0], str)):
            continue
        for key, _, _ in value:
            match = re.fullmatch(r"goods_output_(\w+)_add", key)
            if match:
                if scale != "workforce_scaled":
                    raise ValueError(f"Output outside workforce_scaled ({scale}): {key}")
                goods.add(match[1])
    return goods


def quantum(amount: Decimal) -> Decimal:
    """Tenths for one unit or more, hundredths below, as the panel shows them."""
    return Decimal("0.1") if abs(amount) >= 1 else CENT


def split(quantity: Decimal, template_good, shares, prices):
    """[(good, quantity)] with the template output's value split by `shares`.

    The first good takes the remainder, so the total value differs from the
    template's by under half a quantum of each good's price per line."""
    value = quantity * prices[template_good]
    rest = []
    for good, share in shares[1:]:
        exact = value * share / prices[good]
        rest.append((good, exact.quantize(quantum(exact), rounding=ROUND_HALF_UP)))
    first = shares[0][0]
    exact = (value - sum(amount * prices[good] for good, amount in rest)) / prices[first]
    lead = exact.quantize(quantum(exact), rounding=ROUND_HALF_UP)
    return [(good, amount) for good, amount in [(first, lead), *rest] if amount]


def clone_method(template, body, mine, template_good, mapping, prices, factors, scale):
    entries = to_entries(copy.deepcopy(unwrap(body)))
    rename(entries, mapping)
    shares = [(good, Decimal(share)) for good, share in mine.shares]
    state = block(entries, "state_modifiers")
    if state is not None:
        for _, _, scaled in state:
            if isinstance(scaled, list):
                scaled[:] = [e for e in scaled if e[0] not in (pm_emissions.STATE_MODIFIER,
                                                                    *pm_emissions.OBSOLETE_MODIFIERS)]
    modifiers = block(entries, "building_modifiers", create=True)
    workforce = block(modifiers, "workforce_scaled", create=True, first=True)
    # Fuel the template burns out of its own output: buy it instead, and split the
    # gross output, so profit and emissions match the template's.
    netted = pm_emissions.netted_fuel(template, body)
    output_key = f"goods_output_{template_good}_add"
    for fuel, burn in netted.items():
        inputs = [i for i, entry in enumerate(workforce) if entry[0].startswith("goods_input_")]
        workforce.insert(inputs[-1] + 1 if inputs else 0, [f"goods_input_{fuel}_add", "=", number(burn)])
        outputs = find(workforce, f"goods_output_{fuel}_add")
        if fuel != template_good or len(outputs) != 1:
            raise ValueError(f"{template}: netted {fuel} must come off its one {template_good} output")
        outputs[0][2] = number(Decimal(outputs[0][2]) + burn)
    rebuilt = []
    for entry in workforce:
        key, _, value = entry
        if key == output_key:
            amount = Decimal(value)
            if amount < 0:
                raise ValueError(f"{template}: negative {template_good} output is not netted fuel")
            rebuilt.extend([f"goods_output_{good}_add", "=", number(quantity)]
                           for good, quantity in split(amount, template_good, shares, prices))
        elif key.startswith("goods_output_"):
            raise ValueError(f"{template}: unexpected output {key}")
        else:
            rebuilt.append(entry)
    workforce[:] = rebuilt
    fuels = {key: ("=", value) for key, _, value in workforce if key.startswith("goods_input_")}
    amount = pm_emissions.recipe_emissions({"building_modifiers": {"workforce_scaled": fuels}}, factors, scale)
    if amount:
        state = block(entries, "state_modifiers", create=True, first=True)
        scaled = block(state, "workforce_scaled", create=True, first=True)
        scaled.insert(0, [pm_emissions.STATE_MODIFIER, "=",
                          f"{amount:.2f} # AUTO-GENERATED: industrial emissions"])
    return entries


def annotate(blocks, prices):
    """Each block with pm_costs' cost comments, as pm_costs writes them in extra_pms.txt."""
    annotated = []
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "pm.txt"
        for text in blocks:
            path.write_text(text, encoding="utf-8-sig")
            pm_costs.process_and_update_production_methods_grouped(
                str(path), prices, pm_costs.calculate_costs, pm_costs.calculate_employment)
            annotated.append(path.read_text(encoding="utf-8-sig"))
    return annotated


def own_names(root: Path):
    """Names this script's last run defined, so they don't count as collisions."""
    names = set()
    for relative in (METHODS, GROUPS):
        path = root / relative
        if path.exists():
            names.update(re.findall(r"(?m)^([\w-]+) = \{", path.read_text(encoding="utf-8-sig")))
    return names


def plan_clones(state, root: Path = ROOT):
    """Per mine: (template good, {template method: copy}, {template group: copy group})."""
    groups = state.mod_parsers["PM Groups"].data
    methods = state.mod_parsers["PMs"].data
    ours = own_names(root)
    plans = []
    for mine in MINES:
        if sum(Decimal(share) for _, share in mine.shares) != 1:
            raise ValueError(f"{mine.building}: shares must sum to 1")
        suffix = "_" + mine.family
        template_groups = {f"pmg_{g}_building_{mine.family}": f"pmg_{g}_building_{mine.token}"
                           for g in CLONED_GROUPS}
        members = [pm for group in template_groups for pm in group_methods(groups, group)]
        goods = set().union(*(output_goods(to_entries(unwrap(methods[pm]))) for pm in members))
        goods.update(fuel for pm in members for fuel in pm_emissions.NETTED_FUEL.get(pm, {}))
        if len(goods) != 1:
            raise ValueError(f"{mine.family} family outputs {sorted(goods)}, not one good")
        template_good = goods.pop()
        if template_good not in dict(mine.shares):
            raise ValueError(f"{mine.building}: shares must include the family's good {template_good}")
        cloned = {pm for pm in members
                  if output_goods(to_entries(unwrap(methods[pm]))) or pm in pm_emissions.NETTED_FUEL}
        while True:
            more = {pm for pm in members if pm not in cloned
                    and mentions(to_entries(unwrap(methods[pm])), cloned)}
            if not more:
                break
            cloned |= more
        mapping = {}
        for pm in members:
            if pm in cloned:
                if not pm.endswith(suffix):
                    raise ValueError(f"{pm} carries output but its name doesn't end in {suffix}")
                mapping[pm] = pm.removesuffix(suffix) + "_" + mine.token
        for name in [*mapping.values(), *template_groups.values()]:
            if name not in ours and (name in methods or name in groups):
                raise ValueError(f"{name} already exists outside {METHODS} and {GROUPS}")
        plans.append((mine, template_good, mapping, template_groups))
    return plans


def loc_tables(root: Path):
    mod = {}
    for path in iter_loc_files(str(root / "localization" / "english")):
        with open(path, encoding="utf-8-sig") as handle:
            for line in handle:
                parsed = parse_loc_line(line)
                if parsed:
                    mod[parsed[0]] = parsed[1]
    vanilla = json.loads((root / VANILLA_LOC).read_text(encoding="utf-8"))
    return mod, vanilla


def owned_loc_key(key, value, tokens):
    """A line this script writes: a lone `$reference$` under a copy's name."""
    return (key.startswith(("pm_", "pmg_")) and not key.startswith(("pmg_carbon_capture_", "pm_carbon_capture_",
                                                                      "pm_no_carbon_capture_"))
            and re.fullmatch(r"\$[\w-]+\$", value) is not None
            and any(key.removesuffix("_desc").endswith("_" + token) for token in tokens))


def plan_loc(plans, root: Path):
    mod, vanilla = loc_tables(root)
    lines = []
    for _mine, _good, mapping, template_groups in plans:
        for template, copy_name in [*mapping.items(), *template_groups.items()]:
            if template not in mod and template not in vanilla:
                raise ValueError(f"No localization for {template}")
            lines.append(f' {copy_name}:0 "${template}$"')
            if f"{template}_desc" in mod or f"{template}_desc" in vanilla:
                lines.append(f' {copy_name}_desc:0 "${template}_desc$"')
    path = root / LOC
    existing = path.read_text(encoding="utf-8-sig").splitlines()
    tokens = {mine.token for mine, *_ in plans}
    retained, notes = [], []
    for line in existing:
        if line.strip() in ("", "l_english:", "#", "# PRODUCTION_METHODS"):
            continue
        if not re.match(r"\s+[\w-]+:(?:\d+)?\s", line):
            notes.append(line)
            continue
        parsed = parse_loc_line(line)
        if parsed and owned_loc_key(*parsed, tokens):
            continue
        retained.append(line)
    # The layout gen_carbon_capture_pms.py writes this file in, so its run leaves it be.
    return ("l_english:\n\n#\n# PRODUCTION_METHODS\n#\n"
            + "\n".join(notes + sorted(retained + lines)) + "\n")


def plan_methods_and_groups(state, plans, root: Path):
    methods = state.mod_parsers["PMs"].data
    groups = state.mod_parsers["PM Groups"].data
    prices = pm_costs.goods_from_parsed(state.mod_parsers["Goods"].data)
    factors, scale = emission_factors(root)
    method_text = [HEADER, ""]
    group_text = [HEADER, ""]
    for mine, template_good, mapping, template_groups in plans:
        title = ", ".join(f"{good} {int(Decimal(share) * 100)}%" for good, share in mine.shares)
        intro = [f"# {mine.building}, from the {mine.family} family: {title}", f"# {mine.basis}"]
        method_text.extend(intro)
        blocks = []
        for template, name in mapping.items():
            entries = clone_method(template, methods[template], mine, template_good, mapping,
                                   prices, factors, scale)
            blocks.append(serialize(name, entries))
        for text in annotate(blocks, prices):
            method_text.extend([text, ""])
        group_text.extend(intro)
        for template, name in template_groups.items():
            entries = to_entries(copy.deepcopy(unwrap(groups[template])))
            rename(entries, mapping)
            group_text.extend([serialize(name, entries), ""])
    return "\n".join(method_text), "\n".join(group_text)


def plan_shared_unlocks(state, plans, root: Path):
    """{file: text} with the shared methods' unlocking lists naming the copies."""
    buildings = state.mod_parsers["Buildings"].data
    groups = state.mod_parsers["PM Groups"].data
    methods = state.mod_parsers["PMs"].data
    templates = set().union(*(mapping for _, _, mapping, _ in plans))
    additions = {}
    for mine, _good, mapping, template_groups in plans:
        listed = unwrap(unwrap(buildings[mine.building])["production_method_groups"])
        for group in listed:
            if group in template_groups.values() or group.startswith("pmg_carbon_capture_"):
                continue
            for pm in group_methods(groups, group):
                if pm in templates:
                    raise ValueError(f"{mine.building} runs template method {pm} through {group}")
                gate = unwrap(unwrap(methods[pm]).get("unlocking_production_methods", []))
                gate = [gate] if isinstance(gate, str) else gate
                for name in gate:
                    if name in mapping:
                        additions.setdefault(pm, []).append(mapping[name])
    outputs = {}
    found = set()
    for path in sorted((root / "common" / "production_methods").glob("*.txt")):
        if path.name in (METHODS.name, "carbon_capture_generated_pms.txt", pm_emissions.OUTPUT.name):
            continue
        original = path.read_text(encoding="utf-8-sig")
        masked = pm_emissions._mask(original)
        edits = []
        for match in pm_emissions._DEFINITION.finditer(masked):
            directive, name = pm_emissions.ParadoxFileParser()._split_directive(match[1])
            if name not in additions or directive in pm_emissions.INJECT_DIRECTIVES:
                continue
            found.add(name)
            end = pm_emissions._end(masked, match.end() - 1)
            edits.append((match.start(), end, _with_unlocks(original[match.start():end], additions[name])))
        result = original
        for start, end, replacement in reversed(edits):
            result = result[:start] + replacement + result[end:]
        if result != original:
            outputs[path.relative_to(root)] = result
    if missing := additions.keys() - found:
        raise ValueError(f"No mod definition to edit for {sorted(missing)}")
    return outputs


def _with_unlocks(text, names):
    masked = pm_emissions._mask(text)
    match = re.search(r"\bunlocking_production_methods\s*=\s*\{", masked)
    end = pm_emissions._end(masked, match.end() - 1)
    inner = text[match.end():end - 1]
    if MARKER in inner:
        inner = inner[:inner.index(MARKER)]
    inner = inner.rstrip() + "\n\n\t\t" + MARKER + "\n" + "".join(f"\t\t{name}\n" for name in names) + "\t"
    return text[:match.end()] + inner + text[end - 1:]


def plan_outputs(state=None, root: Path = ROOT):
    if state is None:
        state = load_state(root)
    plans = plan_clones(state, root)
    method_text, group_text = plan_methods_and_groups(state, plans, root)
    outputs = {METHODS: method_text, GROUPS: group_text, LOC: plan_loc(plans, root)}
    outputs.update(plan_shared_unlocks(state, plans, root))
    return outputs


def regenerate(state=None, *, root: Path = ROOT, dry_run: bool = False):
    changed = []
    for relative, text in plan_outputs(state, root).items():
        target = root / relative
        expected = text.encode("utf-8-sig")
        if not target.exists() or target.read_bytes() != expected:
            changed.append(str(relative))
            if not dry_run:
                target.write_bytes(expected)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report the files a run would change")
    mode.add_argument("--check", action="store_true", help="exit 1 if a run would change any file")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    changed = regenerate(root=args.root, dry_run=args.dry_run or args.check)
    for path in changed:
        print(f"{'would change' if args.dry_run or args.check else 'wrote'}: {path}")
    if not changed:
        print("mine co-product methods are current")
    return int(args.check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
