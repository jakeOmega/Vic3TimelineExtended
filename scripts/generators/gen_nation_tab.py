def budget_carriers():
    return {name for side in BUDGET_SOURCES.values() for _, names in side.values() for name in names}


def _matches(entry, name):
    if "*" not in entry:
        return name == entry
    head, tail = entry.split("*", 1)
    return name.startswith(head) and name.endswith(tail) and len(name) >= len(head) + len(tail)


def registry():
    """[(entry, kind, detail)] for every line of the registry."""
    out = []
    for section, entries in SECTIONS.items():
        out += [(entry, "section", section) for entry in entries]
    for row, (section, entries) in ROWS.items():
        out += [(entry, "row", row) for entry in entries]
    out += [(entry, "keep", reason) for entry, reason in KEEP_IN_LIST.items()]
    out += [(entry, "elsewhere", where) for entry, where in NOT_ON_COUNTRY.items()]
    return out


def classify(names):
    """{name: [(entry, kind, detail)]}: the registry lines each name matches.
    A budget carrier matches as ("budget", "budget", side) and nothing else."""
    carriers = budget_carriers()
    lines = registry()
    out = {}
    for name in names:
        if name in carriers:
            out[name] = [(name, "budget", "the Budget panel")]
        else:
            matched = [line for line in lines if _matches(line[0], name)]
            exact = [line for line in matched if line[0] == name]
            out[name] = exact or matched
    return out


def resolve(cands):
    """The exact names for each list, row and the hidden set, from candidates
    that match exactly one registry line."""
    classified = classify(cands)
    lists = {section: [] for section in SECTIONS}
    rows = {row: [] for row in ROWS}
    hidden = []
    for name, lines in sorted(classified.items()):
        if len(lines) != 1:
            continue
        _, kind, detail = lines[0]
        if kind == "section":
            lists[detail].append(name)
        elif kind == "row":
            rows[detail].append(name)
        if kind in ("section", "row", "budget"):
            hidden.append(name)
    return lists, rows, hidden


def carried_types(lists, rows, statics=None):
    """{type: sorted feeders}: every modifier type the blocks of the tab's
    modifiers (its lists' and its rows') carry, and which carry it."""
    statics = static_modifiers() if statics is None else statics
    found = {}
    for names in (*lists.values(), *rows.values()):
        for name in names:
            for field in statics.get(name, {}):
                if field != "icon":
                    found.setdefault(field, set()).add(name)
    return {kind: sorted(names) for kind, names in sorted(found.items())}


def type_registry():
    """[(entry, kind, section, group)] for every line of the type registry;
    a NOT_A_ROW line's section is its reason and its group None."""
    out = []
    for kind, table in (("row", TYPE_ROWS), ("status", STATUS_ROWS)):
        for section, groups in table.items():
            for group, entries in groups.items():
                out += [(entry, kind, section, group) for entry in entries]
    return out + [(entry, "none", reason, None) for entry, reason in NOT_A_ROW.items()]


def classify_types(types):
    """{type: [line]}: the type registry lines each type matches, an exact
    name winning over a family."""
    lines = type_registry()
    out = {}
    for kind in types:
        matched = [line for line in lines if _matches(line[0], kind)]
        out[kind] = [line for line in matched if line[0] == kind] or matched
    return out


def _groups(section):
    """A section's groups in order: TYPE_ROWS', then any STATUS_ROWS adds."""
    rows, status = TYPE_ROWS.get(section, {}), STATUS_ROWS.get(section, {})
    return list(rows) + [group for group in status if group not in rows]


def type_rows(carried):
    """{section: [(group, [(type, kind, feeders)])]} in the registry's order:
    the carried types one row or status line places, a family's members
    alphabetically in its place. Sections and groups with none are left out."""
    placed = classify_types(carried)
    out = {}
    for section in SECTIONS:
        groups = []
        for group in _groups(section):
            items = []
            for kind, table in (("row", TYPE_ROWS), ("status", STATUS_ROWS)):
                for entry in table.get(section, {}).get(group, ()):
                    line = (entry, kind, section, group)
                    items += [(name, kind, feeders) for name, feeders in carried.items() if placed[name] == [line]]
            if items:
                groups.append((group, items))
        if groups:
            out[section] = groups
    return out


