def budget_carriers():
    return {name for side in BUDGET_SOURCES.values() for _, names in side.values() for name in names}


def _matches(entry, name):
    if "*" not in entry:
        return name == entry
    head, tail = entry.split("*", 1)
    return name.startswith(head) and name.endswith(tail) and len(name) >= len(head) + len(tail)


def registry():
    """[(entry, kind, detail)] for every line of the registry."""
    out = []
    for section, entries in SECTIONS.items():
        out += [(entry, "section", section) for entry in entries]
    for row, (section, entries) in ROWS.items():
        out += [(entry, "row", row) for entry in entries]
    out += [(entry, "keep", reason) for entry, reason in KEEP_IN_LIST.items()]
    out += [(entry, "elsewhere", where) for entry, where in NOT_ON_COUNTRY.items()]
    return out


def classify(names):
    """{name: [(entry, kind, detail)]}: the registry lines each name matches.
    A budget carrier matches as ("budget", "budget", side) and nothing else."""
    carriers = budget_carriers()
    lines = registry()
    out = {}
    for name in names:
        if name in carriers:
            out[name] = [(name, "budget", "the Budget panel")]
        else:
            matched = [line for line in lines if _matches(line[0], name)]
            exact = [line for line in matched if line[0] == name]
            out[name] = exact or matched
    return out


def resolve(cands):
    """The exact names for each list and row, and the budget carriers, from
    candidates that match exactly one registry line."""
    classified = classify(cands)
    lists = {section: [] for section in SECTIONS}
    rows = {row: [] for row in ROWS}
    budget = []
    for name, lines in sorted(classified.items()):
        if len(lines) != 1:
            continue
        _, kind, detail = lines[0]
        if kind == "section":
            lists[detail].append(name)
        elif kind == "row":
            rows[detail].append(name)
        elif kind == "budget":
            budget.append(name)
    return lists, rows, budget


def listed(lists):
    """Every name a section lists, sorted."""
    return sorted({name for names in lists.values() for name in names})


def group_lines():
    """[(entry, group)] for every line of SOURCE_GROUPS."""
    return [(entry, group) for group, entries in SOURCE_GROUPS.items() for entry in entries]


def classify_groups(names):
    """{name: [(entry, group)]}: the SOURCE_GROUPS lines each listed name matches."""
    lines = group_lines()
    return {name: [line for line in lines if _matches(line[0], name)] for name in names}


def source_groups(names):
    """{group: sorted names} in SOURCE_GROUPS' order, a group no listed name
    reaches left out. Raises unless each name matches exactly one line."""
    placed = classify_groups(names)
    wrong = {name: [line[0] for line in lines] for name, lines in placed.items() if len(lines) != 1}
    if wrong:
        raise ValueError(f"listed modifiers with no SOURCE_GROUPS line or two (gen_nation_tab.py): {wrong}")
    groups = {group: sorted(name for name, lines in placed.items() if lines[0][1] == group)
              for group in SOURCE_GROUPS}
    return {group: names for group, names in groups.items() if names}


