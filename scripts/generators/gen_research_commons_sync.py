"""Generate the Research Commons' technology ladder: what any member knows, every member is granted.

The Research Commons power bloc identity (docs/systems/mod_systems/power_blocs.md § Research Commons;
design: docs/superpowers/specs/2026-11-16-power-bloc-identities-design.md § 6.3) shares every technology
among its members. Script has no technology iterator and can't read a technology's era or category
(the covert technology theft probe, docs/superpowers/archive/specs/2026-10-06-covert-tech-theft-design.md,
"Engine facts"), so the sharing is one generated branch per technology:

* common/scripted_effects/te_research_commons_sync_generated.txt: te_rc_sync_all, power bloc scope.
  For each technology, in prerequisite order: if a member has it and a member lacks it, every member
  that lacks it is granted it through te_rc_grant (te_research_commons_effects.txt).

Prerequisite order (each technology after every technology its unlocking_technologies name, ties by era
then key) means a member far behind receives each technology after the ones it rests on, whatever
add_technology_researched does about missing prerequisites.

All three categories are shared. The covert generator covers production and military only because no
covert operation steals society technologies (its design's "Out of scope"), not for an engine reason.
A technology defined with can_research = no (vanilla's sericulture, a regional unlock) is left out, and
so is any key in EXCLUDED_TECHNOLOGIES, the lever if play shows the Commons arming the world (§ 6.7);
it is empty in v1.

Inputs: technologies (vanilla snapshot + mod). Run
``python3 scripts/generators/gen_research_commons_sync.py [--dry-run | --check]``. No game install or
running server is needed. Full server reloads call ``regenerate``.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

# Technologies the Commons does not share, by key. Empty in v1 (design § 6.7): a key here reaches a
# member only by its own research, spread or an event.
EXCLUDED_TECHNOLOGIES: tuple[str, ...] = ()

OUT = Path("common/scripted_effects/te_research_commons_sync_generated.txt")
HEADER = (
    "# AUTO-GENERATED by scripts/generators/gen_research_commons_sync.py - do not edit manually.\n"
    "# The Research Commons' technology ladder: docs/systems/mod_systems/power_blocs.md § Research Commons.\n"
)


@dataclass(frozen=True)
class Tech:
    key: str
    category: str
    era: int
    prereqs: tuple[str, ...] = ()


def unwrap(value):
    """Strip the parser's ('=', value) wrappers."""
    while isinstance(value, (tuple, list)) and len(value) == 2 and value[0] == "=":
        value = value[1]
    return value


def load_state(root: Path = ROOT):
    """Technologies: vanilla from the committed snapshot, the mod's from disk."""
    from mod_state import VANILLA_COMMON_DIRS, ModState
    from vanilla_parsed import load

    kinds = ("Technologies",)
    snapshot = load(str(root / "vanilla_parsed"))
    state = ModState(
        {kind: "/nonexistent" for kind in kinds},
        {kind: str(root / "common" / VANILLA_COMMON_DIRS[kind]) for kind in kinds},
        vanilla_data=snapshot.data,
    )
    if state.parse_failures:
        raise ValueError(f"Cannot generate the Research Commons ladder from an incomplete parse: {state.parse_failures}")
    return state


def tech_catalog(mod_state, excluded: tuple[str, ...] = EXCLUDED_TECHNOLOGIES) -> list[Tech]:
    """Every shared technology, by key. Leaves out can_research = no and the exclusion list."""
    techs = mod_state.get_data("Technologies")
    rows = []
    for key in sorted(techs):
        body = unwrap(techs[key])
        if unwrap(body.get("can_research")) == "no" or key in excluded:
            continue
        category = unwrap(body.get("category"))
        era = int(str(unwrap(body["era"])).removeprefix("era_"))
        unlocking = unwrap(body.get("unlocking_technologies")) or []
        prereqs = tuple(unwrap(p) for p in (unlocking if isinstance(unlocking, list) else [unlocking]))
        rows.append(Tech(key, category, era, prereqs))
    return rows


def prerequisite_order(catalog: list[Tech]) -> list[Tech]:
    """Kahn's order: each technology after every prerequisite in the catalog; ties by (era, key).

    A prerequisite outside the catalog (excluded, or unresearchable) puts no constraint on the order.
    A cycle would leave technologies unplaced; that is an error, since the engine could never research them.
    """
    by_key = {tech.key: tech for tech in catalog}
    waiting = {tech.key: {p for p in tech.prereqs if p in by_key} for tech in catalog}
    ready = sorted((t for t in catalog if not waiting[t.key]), key=lambda t: (t.era, t.key))
    order: list[Tech] = []
    while ready:
        tech = ready.pop(0)
        order.append(tech)
        for other in catalog:
            if tech.key in waiting[other.key]:
                waiting[other.key].discard(tech.key)
                if not waiting[other.key]:
                    ready.append(other)
        ready.sort(key=lambda t: (t.era, t.key))
    if len(order) != len(catalog):
        stuck = sorted(set(by_key) - {t.key for t in order})
        raise ValueError(f"technology prerequisites form a cycle: {stuck}")
    return order


def render_sync(order: list[Tech]) -> str:
    n = len(order)
    lines = [
        "# Scope: power bloc (a Research Commons), through te_rc_sync_pass",
        "# (te_research_commons_effects.txt): once a month from te_rc_leader_pulse,",
        "# and from te_rc_share_acquired whenever a member or the leader acquires a",
        "# technology other than by a grant. For each technology, in",
        "# prerequisite order: if any member (the leader included) has it and any",
        "# member lacks it, every member that lacks it is granted it (te_rc_grant).",
        f"# Cost per pass: {n} technologies, {2 * n} any_power_bloc_member checks (each",
        "# stops at its first match, so about one member's read where every member",
        "# holds the technology or none does, and up to every member's otherwise) and",
        "# an every_power_bloc_member walk only where a member lacks what another has.",
        "te_rc_sync_all = {",
    ]
    for tech in order:
        lines += [
            "\tif = {",
            "\t\tlimit = {",
            f"\t\t\tany_power_bloc_member = {{ has_technology_researched = {tech.key} }}",
            f"\t\t\tany_power_bloc_member = {{ NOT = {{ has_technology_researched = {tech.key} }} }}",
            "\t\t}",
            "\t\tevery_power_bloc_member = {",
            f"\t\t\tlimit = {{ NOT = {{ has_technology_researched = {tech.key} }} }}",
            f"\t\t\tte_rc_grant = {{ TECH = {tech.key} }}",
            "\t\t}",
            "\t}",
        ]
    lines.append("}")
    return "\n".join(lines) + "\n"


def plan_outputs(mod_state) -> dict[Path, str]:
    order = prerequisite_order(tech_catalog(mod_state))
    return {OUT: HEADER + "\n" + render_sync(order)}


def regenerate(mod_state=None, *, root: Path = ROOT, dry_run: bool = False) -> dict:
    """Post-load entry point (server/post_load.py POST_LOAD_REGENERATORS) and CLI body.

    Writes the file only when its content changed, with one UTF-8 BOM.
    """
    if mod_state is None:
        mod_state = load_state(root)
    changed = []
    for relative, text in plan_outputs(mod_state).items():
        target = root / relative
        expected = text.encode("utf-8-sig")
        if not target.exists() or target.read_bytes() != expected:
            changed.append(str(relative))
            if not dry_run:
                target.write_bytes(expected)
    return {"changed": bool(changed), "changed_files": changed}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if the output is stale")
    args = parser.parse_args()
    result = regenerate(dry_run=args.dry_run or args.check)
    verb = "stale" if args.check else "would write" if args.dry_run else "wrote"
    for path in result["changed_files"]:
        print(f"{verb}: {path}")
    if not result["changed"]:
        print("research commons ladder: current")
    return int(args.check and result["changed"])


if __name__ == "__main__":
    raise SystemExit(main())
