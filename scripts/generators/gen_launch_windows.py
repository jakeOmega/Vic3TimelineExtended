# The off-window launch rule (spec § 5.2a), for the report and the test
# ---------------------------------------------------------------------------
APPROACH_WEIGHT = {"standard": 1, "ambitious": 2}  # Safe never launches off-window


def months_to_free_window(offset: int, cycle: int) -> int:
    """m: months from `offset` (signed months from this cycle's optimum) to the
    first month of the next free window, in a cycle of `cycle` months."""
    if -1 <= offset <= 1:
        return 0
    if offset < -1:
        return -1 - offset
    return cycle - 1 - offset


def launch_offsets(premium: dict[int, float], pace: float, approach: str, goal: float = 400.0,
                   cycle: int = 26) -> list[int]:
    """Offsets of a `cycle`-month cycle in which a full bar launches: the window,
    and every other month whose premium passes goal x premium / pace <= k x m.
    An offset past half the cycle belongs to the next optimum, and a tie to
    the earlier one, as sr_launch_offset_<body> has it."""
    weight = APPROACH_WEIGHT[approach]
    months = list(range(-((cycle - 1) // 2), cycle // 2 + 1))
    out = []
    for off in months:
        p = premium.get(off, PREMIUM_CAP)
        m = months_to_free_window(off, cycle)
        if p == 0.0 or goal * p / pace <= weight * m:
            out.append(off)
    return out


def describe_launches(offsets: list[int]) -> str:
    """'in the window only' / '+2 to +3 after' style summary for the report."""
    after = [o for o in offsets if o > 1]
    before = [o for o in offsets if o < -1]
    parts = []
    if after:
        parts.append(f"{after[0]}–{after[-1]} months after" if len(after) > 1 else f"{after[0]} months after")
    if before:
        parts.append(f"{-before[-1]}–{-before[0]} months before" if len(before) > 1 else f"{-before[0]} months before")
    return "; ".join(parts) if parts else "in the window only"


