def jd_to_datetime(jd: float) -> datetime:
    return datetime(2000, 1, 1, 12) + timedelta(days=float(jd) - J2000)


def datetime_to_jd(dt: datetime) -> float:
    return J2000 + (dt - datetime(2000, 1, 1, 12)).total_seconds() / DAY_S


def month_index(year: int, month: int) -> int:
    """te_history_month_index: year * 12 + (0 = January ... 11 = December)."""
    return year * 12 + month - 1


def month_of(index: int) -> tuple[int, int]:
    return index // 12, index % 12 + 1


def month_label(index: int) -> str:
    year, month = month_of(index)
    return f"{year}.{month:02d}"


def jd_month_index(jd: float) -> int:
    dt = jd_to_datetime(jd)
