def end_date(root: Path = ROOT) -> tuple[int, int, int]:
    text = (root / DEFINES).read_text(encoding="utf-8-sig")
    match = re.search(r'END_DATE\s*=\s*"(\d+)\.(\d+)\.(\d+)"', text)
    if not match:
        raise ValueError(f"no END_DATE in {DEFINES}")
    return tuple(int(x) for x in match.groups())  # type: ignore[return-value]


