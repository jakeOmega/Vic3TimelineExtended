def _num(x: float) -> str:
    text = f"{x:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


GUARD_YEARS = 20  # the step chains' outer guard: one block per 20 years


def _guarded_blocks(entries: list[tuple[int, int, str]], first: int, last: int) -> list[str]:
    """Body lines of a step function of the month index, guarded by `year`.

    `entries` are (threshold, value, comment): the value holds for every month
    up to and including its threshold, after the previous entry's. Each block
    of GUARD_YEARS lists only the entries its months can reach, its last as
    `else`, so a lookup reads `year` a few times and the month index only for
    the block's own windows."""
    lines = []
    first_year, last_year = month_of(first)[0], month_of(last)[0]
    decades = list(range(first_year - first_year % GUARD_YEARS, last_year + 1, GUARD_YEARS))
    for di, year in enumerate(decades):
        lo = month_index(year, 1) if di else -10 ** 9
        hi = month_index(year + GUARD_YEARS - 1, 12) if di < len(decades) - 1 else 10 ** 9
        start = next(i for i, e in enumerate(entries) if e[0] >= lo)
        stop = next((i for i, e in enumerate(entries) if e[0] >= hi), len(entries) - 1)
        chosen = entries[start:stop + 1]
        if di == 0:
            lines.append(f"\tif = {{\n\t\tlimit = {{ year < {year + GUARD_YEARS} }}")
        elif di < len(decades) - 1:
            lines.append(f"\telse_if = {{\n\t\tlimit = {{ year < {year + GUARD_YEARS} }}")
        else:
            lines.append("\telse = {")
        for ci, (threshold, value, comment) in enumerate(chosen):
            note = f" # {comment}" if comment else ""
            if len(chosen) == 1:
                lines.append(f"\t\tvalue = {value}{note}")
            elif ci == 0:
                lines.append(f"\t\tif = {{ limit = {{ te_history_month_index <= {threshold} }} value = {value} }}{note}")
            elif ci < len(chosen) - 1:
                lines.append(f"\t\telse_if = {{ limit = {{ te_history_month_index <= {threshold} }} value = {value} }}{note}")
            else:
                lines.append(f"\t\telse = {{ value = {value} }}{note}")
        lines.append("\t}")
    return lines


def _premium_tree(key: str, premium: dict[int, float], offsets: list[int], depth: int) -> list[str]:
    tab = "\t" * depth
    if len(offsets) == 1:
        return [f"{tab}value = {_num(premium[offsets[0]])} # offset {offsets[0]:+d}"]
    if all(premium[o] == premium[offsets[0]] for o in offsets):
        return [f"{tab}value = {_num(premium[offsets[0]])} # offsets {offsets[0]:+d} to {offsets[-1]:+d}"]
    mid = len(offsets) // 2
    left, right = offsets[:mid], offsets[mid:]
    lines = [f"{tab}if = {{", f"{tab}\tlimit = {{ sr_launch_offset_{key} < {right[0]} }}"]
    lines += _premium_tree(key, premium, left, depth + 1)
    lines += [f"{tab}}}", f"{tab}else = {{"]
    lines += _premium_tree(key, premium, right, depth + 1)
    lines += [f"{tab}}}"]
    return lines


def render_values(plans: list[BodyPlan], first: int, last: int) -> str:
    out = [HEADER, VALUES_PREAMBLE]
    for plan in plans:
        key, ws = plan.body.key, plan.windows
        out.append(f"# ===== {plan.body.name} ({len(ws)} windows) =====")
        # One branch per cycle: the current or next window's optimum month,
        # with the months since the optimum before it as two decimals.
        entries = []
        for i, w in enumerate(ws):
            gap = w.optimum_month - ws[i - 1].optimum_month if i else ws[1].optimum_month - w.optimum_month
            entries.append((w.end, f"{w.optimum_month}.{gap:02d}", f"{month_label(w.start)}–{month_label(w.end)}"))
        out.append(f"sr_window_next_{key} = {{")
        out.append("\tvalue = 0")
        out += _guarded_blocks(entries, first, last)
        out += ["}", f"sr_window_next_optimum_{key} = {{", f"\tvalue = sr_window_next_{key}", "\tfloor = yes", "}",
                f"sr_window_previous_gap_{key} = {{", f"\tvalue = sr_window_next_{key}",
                f"\tsubtract = sr_window_next_optimum_{key}", "\tmultiply = 100", "\tround = yes", "}",
                f"sr_window_months_to_next_{key} = {{", f"\tvalue = sr_window_next_optimum_{key}",
                "\tsubtract = 1", "\tsubtract = te_history_month_index", "\tmin = 0", "}",
                # Months from the next optimum (at most +1, inside its window), or
                # from the previous one where that is nearer; a tie goes to the
                # previous one.
                f"sr_launch_offset_{key} = {{", "\tvalue = te_history_month_index",
                f"\tsubtract = sr_window_next_optimum_{key}", "\tif = {",
                f"\t\tlimit = {{ sr_launch_nearer_previous_{key} <= 0 }}",
                f"\t\tadd = sr_window_previous_gap_{key}", "\t}", "}",
                f"sr_launch_nearer_previous_{key} = {{", "\tvalue = te_history_month_index",
                f"\tsubtract = sr_window_next_optimum_{key}", "\tmultiply = 2",
                f"\tadd = sr_window_previous_gap_{key}", "}", ""]
        # The premium by offset, a binary search on sr_launch_offset_<body>.
        offsets = sorted(plan.premium)
        out.append(f"# Premium by months from the optimum (fraction; 0.35 = +35%), from the mean extra delta-v of {plan.sampled} cycles:")
        for off in offsets:
            lo, hi = plan.spread[off]
            note = "window, free" if -1 <= off <= 1 else f"cycles {lo * 100:.0f}% to {hi * 100:.0f}%"
            out.append(f"#   {off:+3d}: {_num(plan.premium[off]):>7} ({note})")
        out.append(f"sr_launch_premium_{key} = {{")
        out.append("\tvalue = 0")
        out += _premium_tree(key, plan.premium, offsets, 1)
        out += ["}", ""]
    out += render_readers(plans)
    return "\n".join(out)


def render_triggers(plans: list[BodyPlan]) -> str:
    out = [HEADER, TRIGGERS_PREAMBLE]
    for plan in plans:
        key = plan.body.key
        out.append(f"# {plan.body.name}: {len(plan.windows)} windows, sites {', '.join(plan.body.sites)}")
        out.append(f"sr_window_open_{key} = {{ sr_window_months_to_next_{key} <= 0 }}")
    out += ["", IN_PLAY_PREAMBLE]
    for plan in plans:
        out += _in_play(f"sr_window_body_in_play_{plan.body.key}", plan.body.stage, plan.body.sites)
    for site, stage in UNGATED_SITES.items():
        out += _in_play(f"sr_window_{site}_in_play", stage, (site,))
    return "\n".join(out) + "\n"


def _in_play(name: str, stage: int, sites: tuple[str, ...]) -> list[str]:
    lines = [f"{name} = {{", f"\tsr_current_colonization_stage >= {stage}"]
    if len(sites) == 1:
        lines.append(f"\tNOT = {{ has_global_variable = sr_colony_{sites[0]} }}")
    else:
        lines.append("\tOR = {")
        lines += [f"\t\tNOT = {{ has_global_variable = sr_colony_{site} }}" for site in sites]
        lines.append("\t}")
    return lines + ["}"]


