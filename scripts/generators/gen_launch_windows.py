@dataclass
class Window:
    optimum_jd: float
    transfer_days: float

    @property
    def optimum_month(self) -> int:
        return jd_month_index(self.optimum_jd)

    @property
    def start(self) -> int:
        return self.optimum_month - 1

    @property
    def end(self) -> int:
        return self.optimum_month + 1

    @property
    def arrival_month(self) -> int:
        return jd_month_index(self.optimum_jd + self.transfer_days)


@dataclass
class BodyPlan:
    body: Body
    windows: list[Window]
    half_span: int  # largest |offset| the offset chain can return
    extra_dv: dict[int, float] = field(default_factory=dict)  # mean extra km/s by offset
    premium: dict[int, float] = field(default_factory=dict)  # stored fraction by offset
    spread: dict[int, tuple[float, float]] = field(default_factory=dict)  # per-cycle premium range
    best_dv: tuple[float, float] = (0.0, 0.0)  # cheapest window month: min, max over sampled cycles
    sampled: int = 0
    hohmann_days: float = 0.0  # median over its windows
    transit: dict[str, dict[int, int]] = field(default_factory=dict)  # drive -> offset -> months
    chem_dv: dict[int, float] = field(default_factory=dict)  # a month's cheapest delta-v by offset, mean over cycles
    cycles: list[Window] = field(default_factory=list)  # the sampled cycles


def _round_premium(p: float) -> float:
    return min(PREMIUM_CAP, round(p * 100.0) / 100.0)


def premium_from_extra(extra_kms: float) -> float:
    return math.exp(max(0.0, extra_kms) / EXHAUST_VELOCITY_KMS) - 1.0


def _sample_cycles(windows: list[Window], first: int, last: int) -> list[Window]:
    inside = [w for w in windows if first <= w.optimum_month <= last]
    if len(inside) <= PREMIUM_CYCLES:
        return inside
    step = (len(inside) - 1) / (PREMIUM_CYCLES - 1)
    return [inside[round(i * step)] for i in range(PREMIUM_CYCLES)]


def plan_body(body: Body, first_month: int, last_month: int) -> BodyPlan:
    jd0 = datetime_to_jd(datetime(month_of(first_month)[0] - 2, 1, 1))
    jd1 = datetime_to_jd(datetime(month_of(last_month)[0] + 3, 1, 1))
    windows = [Window(d, t) for d, t in hohmann_optima(body.key, jd0, jd1)]
    # Keep the windows that matter from START_YEAR to END_DATE, plus one either
    # side so the offset and months-to-next chains are defined at both ends.
    keep = [i for i, w in enumerate(windows) if w.end >= first_month and w.start <= last_month]
    lo, hi = max(keep[0] - 1, 0), min(keep[-1] + 2, len(windows))
    windows = windows[lo:hi]
    gaps = [b.optimum_month - a.optimum_month for a, b in zip(windows, windows[1:])]
    half_span = max(math.ceil(g / 2) for g in gaps)
    plan = BodyPlan(body, windows, half_span)

    cycles = _sample_cycles(windows, first_month, last_month)
    plan.sampled = len(cycles)
    offsets = list(range(-half_span, half_span + 1))
    departures, owners = [], []
    for ci, w in enumerate(cycles):
        for off in offsets:
            year, month = month_of(w.optimum_month + off)
            for day in NEAR_DAYS if abs(off) <= 2 else FAR_DAYS:
                departures.append(datetime_to_jd(datetime(year, month, day)))
                owners.append((ci, off))
    hohmann_days = float(np.median([w.transfer_days for w in windows]))
    dv = min_delta_v(body.key, np.array(departures), hohmann_days)
    by_cycle: dict[int, dict[int, float]] = {}
    for (ci, off), value in zip(owners, dv):
        month_best = by_cycle.setdefault(ci, {})
        month_best[off] = min(month_best.get(off, math.inf), float(value))
    extras: dict[int, list[float]] = {off: [] for off in offsets}
    refs = []
    for months in by_cycle.values():
        ref = min(months[-1], months[0], months[1])
        refs.append(ref)
        for off in offsets:
            extras[off].append(months[off] - ref)
    plan.best_dv = (min(refs), max(refs))
    plan.chem_dv = {off: float(np.mean([months[off] for months in by_cycle.values()])) for off in offsets}
    plan.cycles = cycles
    for off in offsets:
        values = np.array(extras[off])
        plan.extra_dv[off] = float(np.mean(values))
        if -1 <= off <= 1:
            plan.premium[off] = 0.0
        else:
            plan.premium[off] = _round_premium(premium_from_extra(plan.extra_dv[off]))
        per_cycle = [min(PREMIUM_CAP, premium_from_extra(v)) for v in values]
        plan.spread[off] = (min(per_cycle), max(per_cycle))
    # Transit by drive, on the same offsets and cycles (one departure each, on
    # TRANSIT_DAY): what a fleet leaving that month takes.
    plan.hohmann_days = hohmann_days
    transit_deps, transit_groups = [], []
    for w in cycles:
        for off in offsets:
            transit_deps.append(datetime_to_jd(datetime(*month_of(w.optimum_month + off), TRANSIT_DAY)))
            transit_groups.append(off)
    plan.transit = transit_months(body.key, np.array(transit_deps), np.array(transit_groups), hohmann_days)
    return plan


