"""Generate Solar System Colonization's launch windows (Global Commons § 5.3).

Chemical rockets reach the planets on minimum-energy (Hohmann) transfers, which
open once per synodic period. This works out, from Keplerian mean elements, the
departure dates of those transfers from 1900 to the game's END_DATE, and writes
them as month-index ranges against ``te_history_month_index``
(common/script_values/te_history_values.txt):

* common/scripted_triggers/sr_launch_windows_generated.txt:
  ``sr_window_open_<body>`` -- the body's window is open this month.
* common/script_values/sr_launch_windows_generated.txt:
  ``sr_window_months_to_next_<body>`` (0 while open), ``sr_launch_offset_<body>``
  (signed months from the nearest optimum) and ``sr_launch_premium_<body>``
  (the off-window premium for that offset, as a fraction: 0.35 = +35%).
* docs/engine/launch_windows_report.md -- every window body's cycle, its
  premium curve with the spread across cycles, the historical launches the
  method is checked against, the Mars windows of era 11, the transit
  times, and the fleets' legs.
* common/script_values/sr_fleet_legs_generated.txt -- the legs between the
  nine fleet locations (solar colonization slice 6 design § 1.2,
  docs/superpowers/specs/2026-10-26-solar-colonization-fleets-design.md): for
  every ordered pair and drive, ``sr_leg_months_<drive>_<a>_<b>`` and
  ``sr_leg_dv_<drive>_<a>_<b>`` (km/s), and the rapid response readers.

Transit times (solar colonization slices 2-3 design § 2,
docs/superpowers/specs/2026-10-25-solar-colonization-population-and-transit-design.md):
for every window body and Mercury, the months a colony fleet takes by each of
four drives (``DRIVES``), as ``sr_transit_<drive>_<body>`` by the same signed
months from the optimum as the premium. Chemical is the body's median Hohmann
time; fusion the shortest Lambert transfer within its delta-v budget; the
torch and antimatter drives a brachistochrone at their acceleration, capped by
their delta-v. Mercury, never gated, has one figure per drive.

The rule (spec § 5.3): a departure date *d* is optimal when the target's true
longitude at *d + T* equals Earth's at *d* + 180 degrees, where *T* is half the
period of the transfer ellipse from Earth's radius at *d* to the target's at
arrival. The window is the optimum's calendar month and the months either side.

The premium (spec § 5.2a) is the propellant an off-window transfer needs: for
each departure, a Lambert solver finds the least delta-v over all transfer
times (departure from a 200 km parking orbit, capture into a loose orbit at the
target, or rendezvous with a small body); the premium is the rocket equation's
extra mass, ``exp(extra delta-v / 3.7 km/s) - 1``, at a methane-oxygen engine's
exhaust velocity. A month's figure is its best departure day. The extra
delta-v is taken against the cycle's best window month, averaged over a sample
of cycles spread across the whole span, and stored up to +100,000%. Window
months are free whatever the curve says.

Sources:
* Planets: E. M. Standish, "Keplerian Elements for Approximate Positions of the
  Major Planets", JPL Solar System Dynamics, Table 1 (mean ecliptic and equinox
  of J2000, valid 1800-2050; https://ssd.jpl.nasa.gov/planets/approx_pos.html).
  Earth is the Earth-Moon barycentre. Past 2050 the linear rates extrapolate,
  which is well inside a month's precision by 2136.
* Asteroids and the Kuiper Belt: JPL Small-Body Database osculating elements
  (heliocentric, ecliptic J2000), propagated two-body. Epoch JD 2460600.5
  (2024-10-17.0 TDB) for Ceres, Vesta, Psyche, Pallas and Hygiea; JD 2457588.5
  (2016-07-31.0 TDB) for Pluto. Read 2026-10-16 through Wolfram|Alpha's
  MinorPlanet data, which serves the SBDB's elements (ssd.jpl.nasa.gov was not
  reachable from the session that wrote this).

Run ``python3 scripts/generators/gen_launch_windows.py [--dry-run | --check]``.
No game install, mod state or running server is needed; full server reloads
call ``regenerate``. Needs numpy (requirements.txt).
"""

