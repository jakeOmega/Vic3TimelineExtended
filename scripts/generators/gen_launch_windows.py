def _kepler(mean_anomaly: np.ndarray, e: np.ndarray | float) -> np.ndarray:
    m = np.remainder(mean_anomaly + np.pi, 2 * np.pi) - np.pi
    ecc = np.asarray(e, dtype=float)
    big_e = m + ecc * np.sin(m)
    for _ in range(30):
        delta = (big_e - ecc * np.sin(big_e) - m) / (1.0 - ecc * np.cos(big_e))
        big_e = big_e - delta
        if np.all(np.abs(delta) < 1e-13):
            break
    return big_e


def _elements(key: str, jd: np.ndarray):
    """(a, e, i, node, arg. peri, mean anomaly, mean motion) at each date."""
    jd = np.asarray(jd, dtype=float)
    if key in STANDISH:
        base, rate = STANDISH[key]
        t = (jd - J2000) / 36525.0
        a, e, inc, mean_long, peri_long, node = (b + r * t for b, r in zip(base, rate))
        inc, mean_long, peri_long, node = (x * DEG for x in (inc, mean_long, peri_long, node))
        mean_motion = (rate[3] - rate[4]) * DEG / 36525.0
        return a, e, inc, node, peri_long - node, mean_long - peri_long, mean_motion * np.ones_like(jd)
    epoch, a, e, inc, node, argp, m0 = SBDB[key]
    n = GAUSS_K / a ** 1.5
    ones = np.ones_like(jd)
    return (a * ones, e * ones, inc * DEG * ones, node * DEG * ones, argp * DEG * ones,
            m0 * DEG + n * (jd - epoch), n * ones)


def state(key: str, jd) -> tuple[np.ndarray, np.ndarray]:
    """Heliocentric ecliptic-J2000 position [AU] and velocity [AU/day]."""
    a, e, inc, node, argp, m, n = _elements(key, jd)
    big_e = _kepler(m, e)
    cos_e, sin_e = np.cos(big_e), np.sin(big_e)
    root = np.sqrt(1.0 - e * e)
    xp, yp = a * (cos_e - e), a * root * sin_e
    denom = 1.0 - e * cos_e
    vxp, vyp = -a * n * sin_e / denom, a * n * root * cos_e / denom
    co, so, cn, sn, ci, si = np.cos(argp), np.sin(argp), np.cos(node), np.sin(node), np.cos(inc), np.sin(inc)
    r11, r12 = co * cn - so * sn * ci, -so * cn - co * sn * ci
    r21, r22 = co * sn + so * cn * ci, -so * sn + co * cn * ci
    r31, r32 = so * si, co * si
    pos = np.stack([r11 * xp + r12 * yp, r21 * xp + r22 * yp, r31 * xp + r32 * yp], axis=-1)
    vel = np.stack([r11 * vxp + r12 * vyp, r21 * vxp + r22 * vyp, r31 * vxp + r32 * vyp], axis=-1)
    return pos, vel


def _semi_major(key: str) -> float:
    return STANDISH[key][0][0] if key in STANDISH else SBDB[key][1]


def hohmann_time(r1, r2):
    return np.pi * np.sqrt(((r1 + r2) / 2.0) ** 3 / MU_SUN)


def _phase(key: str, d: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """(target longitude at arrival - Earth's at departure - 180 deg, wrapped to
    +-pi; the Hohmann transfer time) for departure dates d."""
    earth, _ = state("earth", d)
    r_earth = np.linalg.norm(earth, axis=-1)
    tof = hohmann_time(r_earth, _semi_major(key))
    for _ in range(4):
        target, _ = state(key, d + tof)
        tof = hohmann_time(r_earth, np.linalg.norm(target, axis=-1))
    target, _ = state(key, d + tof)
    diff = np.arctan2(target[:, 1], target[:, 0]) - np.arctan2(earth[:, 1], earth[:, 0]) - np.pi
    return np.remainder(diff + np.pi, 2 * np.pi) - np.pi, tof


def hohmann_optima(key: str, jd_start: float, jd_end: float) -> list[tuple[float, float]]:
    """(departure JD, transfer time in days) of every optimum in the range: the
    zeros of _phase, bracketed on a 4-day grid and refined by bisection."""
    d = np.arange(math.floor(jd_start), math.ceil(jd_end) + 1, 4.0)
    f, _ = _phase(key, d)
    i = np.nonzero((np.sign(f[:-1]) != np.sign(f[1:])) & (np.abs(f[:-1]) < 1.5) & (np.abs(f[1:]) < 1.5))[0]
    lo, hi, f_lo = d[i], d[i + 1], f[i]
    for _ in range(16):  # 4 days / 2**16: a few seconds
        mid = 0.5 * (lo + hi)
        f_mid, _ = _phase(key, mid)
        same = np.sign(f_mid) == np.sign(f_lo)
        lo, f_lo = np.where(same, mid, lo), np.where(same, f_mid, f_lo)
        hi = np.where(same, hi, mid)
    roots = 0.5 * (lo + hi)
    _, tof = _phase(key, roots)
    return [(float(r), float(t)) for r, t in zip(roots, tof)]


# ---------------------------------------------------------------------------
# Lambert's problem (universal variables, zero revolutions, prograde)
# ---------------------------------------------------------------------------
def _stumpff(z: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Stumpff functions C(z), S(z), with a series near zero."""
    root = np.sqrt(np.abs(z))
    safe = np.where(np.abs(z) < 1e-6, 1.0, z)
    safe_root = np.where(np.abs(z) < 1e-6, 1.0, root)
    c = np.where(z > 0, (1.0 - np.cos(safe_root)) / safe, (np.cosh(safe_root) - 1.0) / -safe)
    s = np.where(z > 0, (safe_root - np.sin(safe_root)) / safe_root ** 3,
                 (np.sinh(safe_root) - safe_root) / safe_root ** 3)
    near = np.abs(z) < 1e-6
    c = np.where(near, 0.5 - z / 24.0, c)
    s = np.where(near, 1.0 / 6.0 - z / 120.0, s)
    return c, s


def lambert(r1: np.ndarray, r2: np.ndarray, tof: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Departure and arrival velocities [AU/day] for (N, 3) positions and N times."""
    n1 = np.linalg.norm(r1, axis=-1)
    n2 = np.linalg.norm(r2, axis=-1)
    cos_dnu = np.clip(np.sum(r1 * r2, axis=-1) / (n1 * n2), -1.0, 1.0)
    cross_z = r1[:, 0] * r2[:, 1] - r1[:, 1] * r2[:, 0]
    dnu = np.where(cross_z >= 0.0, np.arccos(cos_dnu), 2 * np.pi - np.arccos(cos_dnu))
    big_a = np.sin(dnu) * np.sqrt(n1 * n2 / np.maximum(1.0 - np.cos(dnu), 1e-14))
    sqrt_mu = math.sqrt(MU_SUN)
    lo = np.full_like(tof, -4.0 * np.pi ** 2)
    hi = np.full_like(tof, 4.0 * np.pi ** 2 - 1e-9)
    for _ in range(LAMBERT_ITERATIONS):
        z = 0.5 * (lo + hi)
        c, s = _stumpff(z)
        y = n1 + n2 + big_a * (z * s - 1.0) / np.sqrt(c)
        ok = y > 0.0
        chi = np.sqrt(np.where(ok, y, 0.0) / c)
        t = np.where(ok, (chi ** 3 * s + big_a * np.sqrt(np.where(ok, y, 0.0))) / sqrt_mu, -1.0)
        low = t < tof
        lo = np.where(low, z, lo)
        hi = np.where(low, hi, z)
    z = 0.5 * (lo + hi)
    c, s = _stumpff(z)
    y = np.maximum(n1 + n2 + big_a * (z * s - 1.0) / np.sqrt(c), 1e-12)
    f = 1.0 - y / n1
    g = big_a * np.sqrt(y / MU_SUN)
    gdot = 1.0 - y / n2
    v1 = (r2 - f[:, None] * r1) / g[:, None]
    v2 = (gdot[:, None] * r2 - r1) / g[:, None]
    return v1, v2


def _delta_v(key: str, v_inf_dep: np.ndarray, v_inf_arr: np.ndarray) -> np.ndarray:
    """Total delta-v [km/s] from hyperbolic excess speeds [km/s]."""
    v_circ = math.sqrt(MU_EARTH / R_PARKING)
    depart = np.sqrt(v_inf_dep ** 2 + 2 * MU_EARTH / R_PARKING) - v_circ
    if key in CAPTURE:
        mu, rp = CAPTURE[key]
        arrive = np.sqrt(v_inf_arr ** 2 + 2 * mu / rp) - math.sqrt(mu * (1 + CAPTURE_ECCENTRICITY) / rp)
    else:
        arrive = v_inf_arr  # rendezvous: no gravity worth the name
    return depart + arrive


def min_delta_v(key: str, departures: np.ndarray, hohmann_days: float) -> np.ndarray:
    """Least delta-v [km/s] over every transfer time, for each departure JD."""
    nd = departures.size
    earth_r, earth_v = state("earth", departures)
    grid = np.geomspace(TOF_RANGE[0], TOF_RANGE[1], TOF_GRID) * hohmann_days

    def cost(dep_index: np.ndarray, tof: np.ndarray) -> np.ndarray:
        r1, v_e = earth_r[dep_index], earth_v[dep_index]
        r2, v_t = state(key, departures[dep_index] + tof)
        v1, v2 = lambert(r1, r2, tof)
        dep = np.linalg.norm(v1 - v_e, axis=-1) * AU_PER_DAY_KMS
        arr = np.linalg.norm(v2 - v_t, axis=-1) * AU_PER_DAY_KMS
        return _delta_v(key, dep, arr)

    dep_index = np.repeat(np.arange(nd), TOF_GRID)
    tofs = np.tile(grid, nd)
    table = cost(dep_index, tofs).reshape(nd, TOF_GRID)
    best = np.argmin(table, axis=1)
    lo = grid[np.maximum(best - 1, 0)]
    hi = grid[np.minimum(best + 1, TOF_GRID - 1)]
    idx = np.arange(nd)
    golden = (math.sqrt(5) - 1) / 2
    x1 = hi - golden * (hi - lo)
    x2 = lo + golden * (hi - lo)
    f1, f2 = cost(idx, x1), cost(idx, x2)
    for _ in range(TOF_REFINE_STEPS):
        left = f1 < f2
        hi = np.where(left, x2, hi)
        lo = np.where(left, lo, x1)
        new_x = np.where(left, hi - golden * (hi - lo), lo + golden * (hi - lo))
        new_f = cost(idx, new_x)
        x2, f2, x1, f1 = (np.where(left, x1, new_x), np.where(left, f1, new_f),
                          np.where(left, new_x, x2), np.where(left, new_f, f2))
    return np.minimum(np.minimum(f1, f2), table.min(axis=1))


