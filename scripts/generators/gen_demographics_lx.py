def _threshold_tree(o, var, starts, leaf, lo=0, hi=None):
    """A balanced tree on local_var:<var> over the intervals [starts[i], starts[i + 1]): leaf(o, i) writes interval i;
    below starts[0] is interval 0, and from starts[-1] up the last."""
    hi = len(starts) - 1 if hi is None else hi
    if lo == hi:
        leaf(o, lo)
        return
    mid = (lo + hi) // 2
    o("if = {")
    o(f"limit = {{ local_var:{var} < {starts[mid + 1]} }}")
    _threshold_tree(o, var, starts, leaf, lo, mid)
    o("}")
    o("else = {")
    _threshold_tree(o, var, starts, leaf, mid + 1, hi)
    o("}")


def lx_sweep(o):
    N, W = P.RING_YEARS, P.LX_BAND_WIDTH
    o("# The step's sweep for a state in the late game (te_demog_lx_sweep_run): the plain sweep's slots in age order, each")
    o("# five-year birth band opened before its slots and closed after them (te_demog_lx_band_open, _close). A band below the")
    o("# open slot is all in pass 1; the rest, the band holding the open slot included, in pass 2 (its pass-1 slots are")
    o("# children, never treated).")
    o("te_demog_lx_sweep = {")
    for pass_ in (1, 2):
        for j in range(P.LX_BANDS - 1, -1, -1):
            top = W * j + W - 1
            o(f"te_demog_lx_pass{pass_}_band = {{ J = {j} TOP = {top} WHEN = open }}")
            for k in range(top, W * j - 1, -1):
                o(f"te_demog_lx_slot_p{pass_} = {{ S = {k} }}")
            o(f"te_demog_lx_pass{pass_}_band = {{ J = {j} TOP = {top} WHEN = close }}")
    o("}")
    o("")
    assert N == W * P.LX_BANDS


