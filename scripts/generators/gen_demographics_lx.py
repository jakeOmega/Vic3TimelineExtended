def old_age_pass(o):
    rem = P.OLD_AGE_REMAINING
    o("# THIS = a state, after a pass of te_demog_lx_tables: the age with this many years of life left, women's and men's")
    o(f"# averaged ({rem}; demographics_model.old_age), into local te_dg_lx_oa: te_demog_old_age_pass's arithmetic.")
    o("te_demog_lx_old_age_pass = {")
    for s in "fm":
        for st in OLD_STARTS:
            o(f"set_local_variable = {{ name = te_dg_oae{st}{s} value = {{ value = local_var:te_dg_py{s} "
              f"subtract = local_var:te_dg_oapy{st}{s} divide = {{ value = local_var:te_dg_oal{st}{s} "
              f"min = 0.00001 }} }} }}")
        prev = None
        for st in OLD_STARTS:
            o(f"{'if' if prev is None else 'else_if'} = {{")
            o(f"limit = {{ local_var:te_dg_oae{st}{s} <= {rem} }}")
            if prev is None:
                o(f"set_local_variable = {{ name = te_dg_oa{s} value = {st} }}")
            else:
                o(f"set_local_variable = {{ name = te_dg_oa{s} value = {{ value = local_var:te_dg_oae{prev}{s} "
                  f"subtract = {rem} divide = {{ value = local_var:te_dg_oae{prev}{s} "
                  f"subtract = local_var:te_dg_oae{st}{s} min = 0.00001 }} multiply = {st - prev} add = {prev} }} }}")
            o("}")
            prev = st
        o("else = {")
        o(f"set_local_variable = {{ name = te_dg_oa{s} value = {OLD_STARTS[-1]} }}")
        o("}")
    o("set_local_variable = { name = te_dg_lx_oa value = { value = local_var:te_dg_oaf add = local_var:te_dg_oam "
      "multiply = 0.5 } }")
    o("}")
    o("")


def _table_pass(o, kind):
    """One life table (demographics_model.lx_tables, life_table, old_age, survivors_at) over the groups, its rates from
    the sums of the sweep: kind untreated (the model's own), treated (their deaths over their people) or blend."""
    o("set_local_variable = { name = te_dg_lf value = 100000 }")
    o("set_local_variable = { name = te_dg_lm value = 100000 }")
    o("set_local_variable = { name = te_dg_pyf value = 0 }")
    o("set_local_variable = { name = te_dg_pym value = 0 }")
    for g, (start, width) in enumerate(P.GROUPS):
        for s in "fm":
            u, t, tq = (f"local_var:te_dg_lxa_{n}{s}{g}" for n in GROUP_SUMS)
            o(f"set_local_variable = {{ name = te_dg_q{s} value = local_var:te_dg_lxu_q{s}{g} }}")
            if kind == "treated":
                o(f"if = {{ limit = {{ {t} > 0 }} set_local_variable = {{ name = te_dg_q{s} value = {{ value = {tq} "
                  f"divide = {{ value = {t} min = 0.00001 }} }} }} }}")
            elif kind == "blend":
                o(f"set_local_variable = {{ name = te_dg_lx_n value = {{ value = {u} add = {t} }} }}")
                o(f"if = {{ limit = {{ local_var:te_dg_lx_n > 0 }} set_local_variable = {{ name = te_dg_q{s} value = {{ "
                  f"value = {u} multiply = local_var:te_dg_lxu_q{s}{g} add = {tq} divide = {{ value = local_var:te_dg_lx_n "
                  f"min = 0.00001 }} }} }} }}")
        if start >= P.OLD_AGE_FROM:
            for s in "fm":
                o(f"set_local_variable = {{ name = te_dg_oal{start}{s} value = local_var:te_dg_l{s} }}")
                o(f"set_local_variable = {{ name = te_dg_oapy{start}{s} value = local_var:te_dg_py{s} }}")
        if start == 65:
            o("set_local_variable = { name = te_dg_l65f value = local_var:te_dg_lf }")
            o("set_local_variable = { name = te_dg_l65m value = local_var:te_dg_lm }")
            o("set_local_variable = { name = te_dg_py65f value = local_var:te_dg_pyf }")
            o("set_local_variable = { name = te_dg_py65m value = local_var:te_dg_pym }")
        if start == P.LX_LIVING_TO:
            o("set_local_variable = { name = te_dg_lx_lt value = { value = local_var:te_dg_lf add = local_var:te_dg_lm "
              "divide = 200000 } }")
        o(f"te_demog_lt_group = {{ N = {width} FERTILE = no }}")
    o("te_demog_lx_old_age_pass = yes")


def tables(o):
    assert P.LX_LIVING_TO in STARTS
    first_adult = P.group_of(P.LX_JOIN_AGE)
    o("# THIS = a state after the late sweep (te_demog_lx_finish): the three period life tables (demographics_model.lx_tables)")
    o("# from the sums te_demog_lx_group_flush kept. The untreated's old-age threshold is te_dg_old_age_c (Linked to Common")
    o("# Longevity follows it) and its Living to 100 te_dg_lx_l100u; the treated's Living to 100 te_dg_lx_l100t; the blend")
    o("# is the state's own and replaces the step's life expectancy, e65 and old-age threshold (te_dg_e0, te_dg_old_age:")
    o("# Linked to Average Longevity follows it) with its Living to 100 te_dg_lx_l100. Then rho, the adults' treated deaths")
    o("# per head over the untreated's (demographics_model.lx_rho), te_dg_lx_rho.")
    o("te_demog_lx_tables = {")
    _table_pass(o, "untreated")
    o("set_variable = { name = te_dg_old_age_c value = local_var:te_dg_lx_oa }")
    o("set_variable = { name = te_dg_lx_l100u value = local_var:te_dg_lx_lt }")
    _table_pass(o, "treated")
    o("set_variable = { name = te_dg_lx_l100t value = local_var:te_dg_lx_lt }")
    _table_pass(o, "blend")
    o("set_variable = { name = te_dg_old_age value = local_var:te_dg_lx_oa }")
    o("set_variable = { name = te_dg_lx_l100 value = local_var:te_dg_lx_lt }")
    blend_tail(o)
    o("te_demog_lt_finish = { QF = local_var:te_dg_lt_tqf QM = local_var:te_dg_lt_tqm }")
    for name in ("tq", "tp", "uq", "up"):
        o(f"set_local_variable = {{ name = te_dg_lx_r{name} value = 0 }}")
    for g in range(first_adult, len(P.GROUPS)):
        for s in "fm":
            o(f"change_local_variable = {{ name = te_dg_lx_rtq add = local_var:te_dg_lxa_tq{s}{g} }}")
            o(f"change_local_variable = {{ name = te_dg_lx_rtp add = local_var:te_dg_lxa_t{s}{g} }}")
            o(f"change_local_variable = {{ name = te_dg_lx_ruq add = {{ value = local_var:te_dg_lxa_u{s}{g} "
              f"multiply = local_var:te_dg_lxu_q{s}{g} }} }}")
            o(f"change_local_variable = {{ name = te_dg_lx_rup add = local_var:te_dg_lxa_u{s}{g} }}")
    o("set_variable = { name = te_dg_lx_rho value = 1 }")
    o("if = {")
    o("limit = {")
    o("local_var:te_dg_lx_rtp > 0")
    o("local_var:te_dg_lx_rup > 0")
    o("local_var:te_dg_lx_ruq > 0")
    o("}")
    o("set_variable = { name = te_dg_lx_rho value = { value = local_var:te_dg_lx_rtq divide = { value = local_var:te_dg_lx_rtp "
      "min = 0.00001 } divide = { value = local_var:te_dg_lx_ruq divide = { value = local_var:te_dg_lx_rup min = 0.00001 } "
      "min = 0.00001 } } }")
    o("}")
    o("}")
    o("")


def blend_tail(o):
    """The blend's death rate past 150 (demographics_model.lx_tail_rate; the open last interval, 2026-10-20): the rate the
    pool died at this step, its untreated part at the last group's rate and its treated part at its biological one, both
    the model's own (te_demog_lx_fold_deaths' te_dg_lxp_*), weighted by their people; with no pool, the blend's last
    group's rate, still in te_dg_q<f|m>."""
    last = len(P.GROUPS) - 1
    o("# the blend's death rate past 150 for its survivors at 150 (demographics_model.lx_tail_rate): the pool's, its parts")
    o("# weighted by their people (te_demog_lx_fold_deaths), or with no pool the last group's")
    for s in "fm":
        o(f"set_local_variable = {{ name = te_dg_lt_tq{s} value = local_var:te_dg_q{s} }}")
        o("if = {")
        o(f"limit = {{ has_local_variable = te_dg_lxp_u{s} }}")
        o(f"set_local_variable = {{ name = te_dg_lx_n value = {{ value = local_var:te_dg_lxp_u{s} "
          f"add = local_var:te_dg_lxp_t{s} }} }}")
        o(f"if = {{ limit = {{ local_var:te_dg_lx_n > 0 }} set_local_variable = {{ name = te_dg_lt_tq{s} value = {{ "
          f"value = local_var:te_dg_lxp_u{s} multiply = local_var:te_dg_lxu_q{s}{last} add = {{ value = "
          f"local_var:te_dg_lxp_t{s} multiply = local_var:te_dg_lxp_bq{s} }} divide = {{ value = local_var:te_dg_lx_n "
          f"min = 0.00001 }} }} }} }}")
        o("}")


