"""Generate power bloc names built from the founder's capital city ("Berlin Pact", "League of Vienna").

A bloc name is a localization key the engine prints as it stands: no vanilla
bloc name holds a data function, and building names with one rendered raw
(#555). So the capital comes in through a `$HUB_NAME_<state>_city$` splice,
which the game fills in when it loads localization, and each state gets its own
entry, valid while the founder's capital is in it. A leader change re-picks the
name, so the name follows the new leader's capital.

Reads the mod's `map_data/state_regions/*.txt` (every state with a `city` hub has
vanilla's `HUB_NAME_<state>_city` key), so it needs no game install. Writes
`common/power_bloc_names/te_capital_power_bloc_names_generated.txt` and
`localization/english/te_power_bloc_names_generated_l_english.yml`, rendered
through `organize_loc` (category POWER_BLOC_NAMES_GENERATED) so a run of
`organize_loc.py` leaves it intact.

Run after a vanilla patch adds or renames states:
    python3 scripts/generators/gen_capital_bloc_names.py [--check]
`--check` lists drifted files, writes nothing and exits 1 on drift.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from organize_loc import _render_loc_file, section_label  # noqa: E402

NAMES_FILE = ROOT / "common/power_bloc_names/te_capital_power_bloc_names_generated.txt"
LOC_FILE = ROOT / "localization/english/te_power_bloc_names_generated_l_english.yml"
LOC_CATEGORY = "POWER_BLOC_NAMES_GENERATED"

# Family key -> name text, `{city}` standing for the capital's city splice.
FAMILIES = {
    "pact": "{city} Pact",  # the Warsaw Pact, the Baghdad Pact
    "league": "League of {city}",  # the League of Corinth
}

# States whose generated name would repeat a base-game name for the same city
# ("Pact of Madrid" beside "Madrid Pact"). Found once from vanilla's bloc names
# and city names; a vanilla name for another country that happens to share the
# text (Spain's League of Santiago, the USA's League of Providence) doesn't count.
SKIP = {
    "pact": {"STATE_ESTREMADURA", "STATE_LAZIO", "STATE_NEW_CASTILE", "STATE_TUNISIA", "STATE_VERACRUZ", "STATE_WEST_BENGAL"},
    "league": {"STATE_BOMBAY", "STATE_ISTRIA"},
}

HEADER = (
    "# AUTO-GENERATED by scripts/generators/gen_capital_bloc_names.py — do not edit manually\n"
    "# One name per family and state with a city hub, valid while the founder's capital is in that state.\n"
)


def city_states(root: Path = ROOT) -> list[str]:
    """Every state region with a `city` hub, in sorted order."""
    states = set()
    for path in sorted((root / "map_data/state_regions").glob("*.txt")):
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig"))
        for m in re.finditer(r"(?m)^(STATE_[A-Z0-9_]+)\s*=\s*\{", text):
            depth, j = 1, m.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[j], 0)
                j += 1
            if re.search(r"(?m)^\s*city\s*=", text[m.end():j]):
                states.add(m.group(1))
    return sorted(states)


def entries(states: list[str]) -> list[tuple[str, str, str]]:
    """(key, state, family) for every generated name."""
    return [
        (f"te_pb_name_{family}_{state}", state, family)
        for family in FAMILIES
        for state in states
        if state not in SKIP[family]
    ]


def render_names(rows) -> str:
    blocks = [
        f"{key} = {{\n\ttrigger = {{\n\t\tcapital = {{ state_region = s:{state} }}\n\t}}\n}}\n"
        for key, state, _ in rows
    ]
    return HEADER + "\n" + "\n".join(blocks)


def render_loc(rows) -> bytes:
    loc = {key: '0 "' + FAMILIES[family].format(city="$HUB_NAME_" + state + "_city$") + '"' for key, state, family in rows}
    return _render_loc_file([(section_label(LOC_CATEGORY), loc)])


def outputs(root: Path = ROOT) -> dict[Path, bytes]:
    rows = entries(city_states(root))
    return {NAMES_FILE: render_names(rows).encode("utf-8-sig"), LOC_FILE: render_loc(rows)}


def main(argv: list[str]) -> int:
    drifted = [path for path, data in outputs().items() if not path.is_file() or path.read_bytes() != data]
    if "--check" in argv:
        for path in drifted:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if drifted else 0
    for path, data in outputs().items():
        path.write_bytes(data)
    print(f"wrote {len(entries(city_states()))} names")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
