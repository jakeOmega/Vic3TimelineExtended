#!/usr/bin/env python3
"""Write common/terrain/te_state_pictures_generated.txt: the mod's state pictures.

The banner at the top of the state panel is the highest-weight entry of the
`textures` list of the state's prevailing terrain. This writes one `INJECT:` a
terrain, adding an entry for each picked picture of
scripts/image_pipeline/state_picture_registry.py (an INJECT adds to vanilla's
list; scripting_best_practices.md § "State pictures"). Every entry carries an
`effect`: the engine rejects one without it, and the state it matched then
shows the plains picture. A city picture is also written, one line an entry,
into every other land terrain's list, where it asks for a metropolis (the
registry's CITY_TAKEOVER_TERRAINS): the engine can hold a great city's state
to be farmland.

Each entry plays its own copy of its vanilla overlay, named for its kind and
technology (the registry's overlay_name()), so the banner's hover can say which
picture shows. The run also writes those copies,
gfx/models/particles/te_state_picture_overlays_generated.asset, and the hover's
text for each, localization/english/te_picture_hover_generated_l_english.yml
(te_sp_tt_<overlay name>, which strings together the hand-written te_sp_tt_*
lines in te_miscellaneous_l_english.yml).

Needs nothing but the repo. Re-run after the registry changes;
test_state_pictures.py fails CI when a committed file is stale:

    python3 scripts/generators/gen_state_pictures.py [--check]
"""
import argparse
import importlib.util
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "common", "terrain", "te_state_pictures_generated.txt")
OVERLAYS_OUT = os.path.join(REPO, "gfx", "models", "particles", "te_state_picture_overlays_generated.asset")
LOC_OUT = os.path.join(REPO, "localization", "english", "te_picture_hover_generated_l_english.yml")
LOC_CATEGORY = "PICTURE_HOVER_GENERATED"
VANILLA_TERRAINS = os.path.join(REPO, "vanilla_parsed", "common", "terrains.json")

_spec = importlib.util.spec_from_file_location(
    "state_picture_registry",
    os.path.join(REPO, "scripts", "image_pipeline", "state_picture_registry.py"))
registry = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(registry)

sys.path.insert(0, REPO)
from organize_loc import _render_loc_file, section_label  # noqa: E402


def picture_path(key):
    return f"gfx/state_pictures/te_{key}.dds"


def conditions(key, terrain=None):
    """The state triggers a picture needs, one a line; a nested line starts with its own tabs.

    In a terrain of the picture's `any_region` list its region isn't asked for. In a terrain a
    great city takes over, the city's size comes first, so every other state fails at once.
    """
    p = registry.PICTURES[key]
    lines = []
    if terrain and registry.takes_over(key, terrain):
        lines += registry.SIZES[registry.CITY_TAKEOVER_SIZE][0]
    lines += [f"owner = {{ has_technology_researched = {p['tech']} }}"]
    if p["region"] and terrain not in p.get("any_region", ()):
        lines += registry.region_conditions(p["region"])
    if p["size"]:
        lines += [line for line in registry.SIZES[p["size"]][0] if line not in lines]
    if p.get("scale"):
        lines += registry.SCALES[p["scale"]][0]
    if p.get("character"):
        lines += registry.CHARACTERS[p["character"]][0]
    if p.get("upkeep"):
        lines += registry.UPKEEP[p["upkeep"]][0]
    if p.get("means"):
        lines += registry.MEANS[p["means"]][0]
    if p.get("condition"):
        lines += registry.CONDITIONS[p["condition"]][0]
    lines += p.get("where", [])
    return lines


def by_terrain(pictures=None):
    """{terrain: [key, ...]}: terrains sorted, each one's pictures by their weight there."""
    pictures = registry.wired() if pictures is None else pictures
    out = {}
    for key in pictures:
        for terrain in registry.terrains(key):
            out.setdefault(terrain, []).append(key)
    return {t: sorted(keys, key=lambda k: (registry.weight(k, t), k)) for t, keys in sorted(out.items())}


def render(pictures=None):
    lines = [
        "# AUTO-GENERATED by scripts/generators/gen_state_pictures.py - do not edit manually.",
        "# Source: scripts/image_pipeline/state_picture_registry.py. Design:",
        "# docs/superpowers/specs/2026-11-10-state-pictures-design.md.",
        "# Each INJECT adds its pictures to the terrain's own list; the highest weight that",
        "# applies is the state's banner. Vanilla's weights are 1 and 2. The one-line entries are",
        "# the city pictures in a terrain a metropolis takes over.",
    ]
    for terrain, keys in by_terrain(pictures).items():
        lines += ["", f"INJECT:{terrain} = {{", "\ttextures = {"]
        for key in keys:
            if registry.takes_over(key, terrain):
                wants = " ".join(c.strip() for c in conditions(key, terrain))
                lines.append(
                    f"\t\t{{ weight = {{ value = 0 if = {{ limit = {{ scope:state = {{ {wants} }} }}"
                    f" add = {registry.weight(key, terrain)} }} }}"
                    f' path = "{picture_path(key)}" effect = "{registry.overlay_name(key, terrain)}" }}')
                continue
            lines += [
                "\t\t{",
                "\t\t\tweight = {",
                "\t\t\t\tvalue = 0",
                "\t\t\t\tif = {",
                "\t\t\t\t\tlimit = {",
                "\t\t\t\t\t\tscope:state = {",
            ]
            lines += [f"\t\t\t\t\t\t\t{c}" for c in conditions(key, terrain)]
            lines += [
                "\t\t\t\t\t\t}",
                "\t\t\t\t\t}",
                f"\t\t\t\t\tadd = {registry.weight(key, terrain)}",
                "\t\t\t\t}",
                "\t\t\t}",
                f'\t\t\tpath = "{picture_path(key)}"',
                f'\t\t\teffect = "{registry.overlay_name(key, terrain)}"',
                "\t\t}",
            ]
        lines += ["\t}", "}"]
    return "﻿" + "\n".join(lines) + "\n"


def render_overlays():
    """Each overlay copy: vanilla's one-event state entity (vfx_entities_ui.asset) under its own name."""
    lines = [
        "# AUTO-GENERATED by scripts/generators/gen_state_pictures.py - do not edit manually.",
        "# The state pictures' overlays: each is a copy of the vanilla overlay its picture would play,",
        "# under a name for the picture's kind and technology, which the banner's hover reads",
        "# (State.GetBestTextureEffect). Source: scripts/image_pipeline/state_picture_registry.py.",
    ]
    for name, (_kind, _tech, vanilla) in registry.overlays().items():
        lines += [
            "",
            "entity = {",
            f'\tname = "{name}"',
            "\tscale = 1",
            '\tdefault_state = "idle"',
            "\tstate = {",
            '\t\tname = "idle"',
            "\t\tstate_time = 1",
            "\t\tlooping = no",
            "\t\tstart_event = {",
            "\t\t\ttime = 0",
            f'\t\t\tparticle = "{registry.OVERLAY_PARTICLES[vanilla]}"',
            "\t\t\ttrigger_once = yes",
            "\t\t\tkeep_particle = no",
            "\t\t}",
            "\t}",
            "}",
        ]
    return "\n".join(lines) + "\n"


def hover_text(kind, tech):
    """The hover of one overlay: the picture and its decade, why it shows, then under the rule the
    technology it follows and, where the game's terrain decided, that terrain."""
    text = (f"#b $te_sp_tt_k_{kind}$, $te_sp_tt_e_{registry.decade(tech)}$#!\\n$te_sp_tt_why_{kind}$"
            f"\\n$TOOLTIP_DELIMITER$\\n$te_sp_tt_era_{tech}$")
    if kind in registry.CITY_KINDS:
        text += "$te_sp_tt_terrain_urban$"
    elif kind in registry.SCALE_TERRAIN:
        text += f"\\n$te_sp_tt_terrain_{registry.SCALE_TERRAIN[kind]}$"
    return text


def era_text(tech):
    """A technology's line: the decade its pictures paint, and that the state's owner has it."""
    return f"$te_sp_tt_e_{registry.decade(tech)}$: [State.GetOwner.GetName] has researched ${tech}$."


def vanilla_overlays():
    """Every overlay a vanilla terrain's pictures play (the committed vanilla_parsed/ snapshot)."""
    with open(VANILLA_TERRAINS, encoding="utf-8") as f:
        return sorted(set(re.findall(rf"{registry.VANILLA_OVERLAY_PREFIX}\w+", f.read())))


def hover_loc():
    """The hover of each overlay (te_sp_tt_<overlay>) and the line of each technology (te_sp_tt_era_<tech>).
    A vanilla overlay's hover is empty, so a vanilla picture shows none: the banner's tooltip is the bare lookup,
    the form read in game, and a key that doesn't exist would come back as itself."""
    out = {f"te_sp_tt_{name}": "" for name in vanilla_overlays()}
    for name, (kind, tech, _vanilla) in registry.overlays().items():
        out[f"te_sp_tt_{name}"] = hover_text(kind, tech)
        out[f"te_sp_tt_era_{tech}"] = era_text(tech)
    return out


def render_loc():
    return _render_loc_file([(section_label(LOC_CATEGORY), {k: f'0 "{v}"' for k, v in hover_loc().items()})])


def outputs():
    """[(path, bytes)] of every file the run writes."""
    return [(OUT, render().encode("utf-8")), (OVERLAYS_OUT, render_overlays().encode("utf-8")),
            (LOC_OUT, render_loc())]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed file is stale")
    args = ap.parse_args()
    stale = 0
    for path, data in outputs():
        rel = os.path.relpath(path, REPO)
        if args.check:
            try:
                with open(path, "rb") as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != data:
                print(f"stale: {rel} (run gen_state_pictures.py)")
                stale += 1
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print(f"wrote {rel}")
    if args.check:
        print("up to date" if not stale else f"{stale} stale")
        return 1 if stale else 0
    print(f"{sum(len(v) for v in by_terrain().values())} terrain entries, {len(registry.overlays())} overlays")
    return 0


if __name__ == "__main__":
    sys.exit(main())
