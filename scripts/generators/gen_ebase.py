"""The Extraplanetary Base's ground types in script: where the levels work and the mix.

Design: ``docs/superpowers/specs/2026-11-05-extraplanetary-base-ground-types-design.md``
(§ n below means that document's). Plan:
``docs/superpowers/plans/2026-11-21-extraplanetary-base-ground-types.md``.
``ebase_ground.py`` is the reference: every figure and rule here is written from it.

Outputs:

- ``common/script_values/sr_ebase_generated.txt`` (country scope): each place's room
  serving us now (``sr_eb_room_<k>``) and grade (``sr_eb_grade_<k>``, percent); each
  good's premium on our market (``sr_eb_price_rel_<good>``, a signed fraction, for the
  seven goods and every input of the mining methods); each mining method's share of our
  mining levels (``sr_eb_share_<pm>``); each type's margin, a level's profit a week at
  grade 0 (``sr_eb_margin_<type>``, the methods' goods at base prices and ``1 + mix``
  baked into constants); each place's profit a level (``sr_eb_profit_<k>``); the
  yardstick (``sr_eb_yardstick``) and the pace (``sr_eb_pace``).
- ``common/scripted_effects/sr_ebase_generated.txt`` (country scope): the method count,
  the fill, the mix (T and D(g), § 5.2) and the modifiers on every base building
  (§ 5.3), and the next level's grade. ``sr_ebase_refresh``
  (``sr_colony_module_effects.txt``) is the one caller.

A place is the near-Earth asteroids (``near_earth``, index 0) or one of the 40 sites
(``Site.index`` 1 to 40), in ``ebase_ground.PLACES`` order. Only the mining methods
count (``ebase_ground.mining_methods()``): those whose outputs are all within the seven
goods.

Locals: every effect here uses its own family of locals, ``sr_ebm_`` (a month's
counts), ``sr_ebc_`` (the method count) and ``sr_ebx_`` (the mix), so none collides with
another effect's in the same run (locals are shared by every effect a call runs).

Run ``python3 scripts/generators/gen_ebase.py [--dry-run | --check]``. A post-load
regenerator (``server/post_load.py``'s ``POST_LOAD_REGENERATORS``), right after
``gen_solar_sites``.
"""

