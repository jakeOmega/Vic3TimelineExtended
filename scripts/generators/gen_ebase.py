MONTH = "sr_ebm"


# --- Places -------------------------------------------------------------------------

def places() -> list[tuple[int, str]]:
    """(index, key) for the 41 places, in PLACES order: the index is the script's."""
    return list(enumerate(eg.PLACES))


def name(k: str) -> str:
    return "the near-Earth asteroids" if k == eg.NEAR_EARTH else SITES[k].name


def grade_pct(k: str) -> int:
    """A place's grade in percent (near-Earth 0)."""
    return 0 if k == eg.NEAR_EARTH else SITES[k].ebase_grade


def held(k: str) -> str:
    """THIS holds the place: a site's holder is THIS; the near-Earth asteroids are
    everyone's with Asteroid Mining."""
    if k == eg.NEAR_EARTH:
        return f"has_technology_researched = {gss.NEAR_EARTH_TECH}"
    return f"global_var:sr_site_holder_{k} ?= this"


def serves(k: str) -> str:
    """The place serves THIS this run (gss.site_serves: held, not blockaded, not
    occupied; the near-Earth asteroids with Asteroid Mining)."""
    if k == eg.NEAR_EARTH:
        return f"has_technology_researched = {gss.NEAR_EARTH_TECH}"
    return gss.site_serves(SITES[k])


def room_value(k: str) -> str:
    """The place's room, serving or not: a site's levels' and Mining Complexes'."""
    return str(gss.NEAR_EARTH_ROOM) if k == eg.NEAR_EARTH else f"sr_site_ebase_room_{k}"


def num(x: float, places_: int = 4) -> str:
    """A literal to at most `places_` decimals, trailing zeros dropped."""
    text = f"{x:.{places_}f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def at(fam: str, k: str) -> str:
    return f"{fam}_at_{k}"


# --- Script values ------------------------------------------------------------------

def render_values() -> str:
    out = [HEADER.rstrip("\n"),
           "# Extraplanetary Base ground types (ground types design § 8.3), country scope. See",
           "# scripts/generators/gen_ebase.py.",
           "",
           "# ---- Each place's room serving us now (§ 8.2 step 1) and grade (percent) ----"]
    for i, k in places():
        out += [f"# {name(k)} (place {i})",
                f"sr_eb_room_{k} = {{",
                "\tvalue = 0",
                f"\tif = {{ limit = {{ {serves(k)} }} value = {room_value(k)} }}",
                "}",
                f"sr_eb_grade_{k} = {{ value = {grade_pct(k)} }}"]
    out += ["",
            "# ---- Each good's premium on our market (§ 8.3), a signed fraction (0 = base price) ----",
            "# Built as max(pricier, 0) less max(cheaper, 0), right whether the engine clamps",
            "# either read at zero or not (scripting_best_practices.md, \"Is it signed below base",
            "# price?\")."]
    for g in eg.method_goods():
        out += [f"sr_eb_price_up_{g} = {{",
                "\tvalue = 0",
                f"\tmarket = {{ mg:{g} = {{ add = market_goods_pricier }} }}",
                "\tmin = 0",
                "}",
                f"sr_eb_price_down_{g} = {{",
                "\tvalue = 0",
                f"\tmarket = {{ mg:{g} = {{ add = market_goods_cheaper }} }}",
                "\tmin = 0",
                "}",
                f"sr_eb_price_rel_{g} = {{ value = sr_eb_price_up_{g} subtract = sr_eb_price_down_{g} }}"]
    out += ["",
            "# ---- Our levels on each mining method, and its share of our mining levels (§ 8.3's f(m)) ----",
            "# From the counts sr_eb_count_methods stores each refresh. Only the mining methods",
            "# count: those whose outputs are all within the seven goods.",
            "sr_eb_mining_levels = {",
            "\tvalue = 0",
            "\tif = { limit = { has_variable = sr_eb_lv_mining } value = var:sr_eb_lv_mining }",
            "}",
            "# What a margin divides by: the mining levels, at least 1 (with none, every term is 0).",
            "sr_eb_mining_divisor = { value = sr_eb_mining_levels min = 1 }"]
    for pm in eg.mining_methods():
        out += [f"sr_eb_levels_{pm} = {{",
                "\tvalue = 0",
                f"\tif = {{ limit = {{ has_variable = sr_eb_lv_{pm} }} value = var:sr_eb_lv_{pm} }}",
                "}",
                f"sr_eb_share_{pm} = {{ value = sr_eb_levels_{pm} divide = sr_eb_mining_divisor }}"]
    out += ["",
            "# ---- Each type's margin (§ 8.3): a level's profit a week at grade 0 on its ground ----",
            "# sum over methods m and goods g of f(m) x term(m, g) x (1 + premium(g)). A term is",
            "# out x base price x (1 + mix) for an output, -(in x base price) for an input",
            "# (ebase_ground.margin_terms). Fixed point: each term is multiplied by the method's",
            "# levels and the sum divided by the mining levels once, at the end, rather than",
            "# multiplied by a share cut to five decimals."]
    for t in eg.TYPES:
        terms = eg.margin_terms(t)
        out += [f"sr_eb_margin_{t} = {{", "\tvalue = 0"]
        for pm, row in terms.items():
            out.append(f"\t# {pm}: {sum(row.values()):,.2f} a level at base prices")
            for g, v in row.items():
                out.append(f"\tadd = {{ value = sr_eb_price_rel_{g} add = 1 multiply = {num(v)} "
                           f"multiply = sr_eb_levels_{pm} }}")
        out += ["\tdivide = sr_eb_mining_divisor", "}"]
    out += ["",
            "# ---- Each place's profit a level a week (§ 8.3): (1 + grade) x its type's margin ----"]
    for _, k in places():
        out.append(f"sr_eb_profit_{k} = {{ value = sr_eb_margin_{eg.GROUND[k]} "
                   f"multiply = {100 + grade_pct(k)} divide = 100 }}")
    out += ["",
            "# The yardstick (§ 8.3): our methods' profit a level at grade 0 and base prices,",
            "# weighted by their levels. A move must gain 5% of it a level.",
            "sr_eb_yardstick = {", "\tvalue = 0"]
    for pm in eg.mining_methods():
        out.append(f"\tadd = {{ value = sr_eb_levels_{pm} multiply = {num(eg.margin('mixed', {pm: 1.0}, {}))} }}")
    out += ["\tdivide = sr_eb_mining_divisor",
            "}",
            "",
            f"# The pace (§ 8.5): ceil(L / {eg.PACE_MONTHS}) levels a month, at least 1.",
            f"sr_eb_pace = {{ value = sr_ebase_levels divide = {eg.PACE_MONTHS} ceiling = yes min = 1 }}"]
    return "\n".join(out) + "\n"


# --- Effects: the pieces ------------------------------------------------------------

def _store_counts(fam: str) -> list[str]:
    """The family's counts written back to the country (§ 8.1): `sr_eb_at_<k>` while
    above 0 (removed at 0) and `sr_eb_over`."""
    out = []
    for _, k in places():
        out += ["\tif = {",
                f"\t\tlimit = {{ local_var:{at(fam, k)} > 0 }}",
                f"\t\tset_variable = {{ name = sr_eb_at_{k} value = local_var:{at(fam, k)} }}",
                "\t}",
                f"\telse_if = {{ limit = {{ has_variable = sr_eb_at_{k} }} remove_variable = sr_eb_at_{k} }}"]
    out.append(f"\tset_variable = {{ name = sr_eb_over value = local_var:{fam}_over }}")
    return out


def render_count_methods() -> list[str]:
    pms = list(eg.mining_methods())
    out = ["# Our levels on each mining method, and on all of them (§ 8.3's f(m)), into",
           "# var:sr_eb_lv_<pm> and var:sr_eb_lv_mining for sr_eb_share_<pm>: one walk of our",
           "# Extraplanetary Bases. A method outside the seven goods is not counted.",
           "sr_eb_count_methods = {"]
    out += [f"\tset_local_variable = {{ name = sr_ebc_{pm} value = 0 }}" for pm in pms]
    out += ["\tevery_scope_state = {",
            "\t\tevery_scope_building = {",
            f"\t\t\tlimit = {{ is_building_type = {BUILDING} }}"]
    for n, pm in enumerate(pms):
        out.append(f"\t\t\t{'if' if n == 0 else 'else_if'} = {{ limit = {{ has_active_production_method = {pm} }} "
                   f"change_local_variable = {{ name = sr_ebc_{pm} add = level }} }}")
    out += ["\t\t}", "\t}"]
    out += [f"\tset_variable = {{ name = sr_eb_lv_{pm} value = local_var:sr_ebc_{pm} }}" for pm in pms]
    out += ["\tset_variable = {", "\t\tname = sr_eb_lv_mining", "\t\tvalue = {", "\t\t\tvalue = 0"]
    out += [f"\t\t\tadd = local_var:sr_ebc_{pm}" for pm in pms]
    out += ["\t\t}", "\t}", "}"]
    return out


def render_fill_by_grade() -> list[str]:
    """Today's order (§ 4): the built levels fill the room serving us best grade first,
    the rest past all of it."""
    out = ["# Today's order (§ 4): our built levels fill the room serving us best grade first",
           f"# ({MONTH}_at_<k>), the rest past all of it ({MONTH}_over); written to",
           "# var:sr_eb_at_<k> and var:sr_eb_over.",
           "sr_eb_fill_by_grade = {",
           f"\tset_local_variable = {{ name = {MONTH}_pool value = sr_ebase_levels }}"]
    for k in eg.by_grade():
        out += [f"\t# {name(k)} ({grade_pct(k):+d}%)",
                f"\tset_local_variable = {{ name = {at(MONTH, k)} value = {{ value = sr_eb_room_{k} "
                f"max = local_var:{MONTH}_pool }} }}",
                f"\tchange_local_variable = {{ name = {MONTH}_pool subtract = local_var:{at(MONTH, k)} }}"]
    out.append(f"\tset_local_variable = {{ name = {MONTH}_over value = local_var:{MONTH}_pool }}")
    out += _store_counts(MONTH)
    out.append("}")
    return out


def mix_factor(k: str, good: str) -> float:
    """A level's output of `good` at place `k` against the method's at grade 0, × 100:
    (100 + G)(1 + mix)."""
    return (100 + grade_pct(k)) * (1 + eg.mix(eg.GROUND[k])[good])


OVER_FACTOR = 100 + gss.OVERFLOW_GRADE  # a level past the room: (100 - 75) x Mixed


def render_compute_mix(effect: str = "sr_eb_compute_mix", fam: str = MONTH) -> list[str]:
    """§ 5.2 over the family's counts: T, the average grade over the levels (past the
    room at OVERFLOW_GRADE), into var:sr_ebase_grade; D(g) for each good, the levels'
    types' mixes weighted by levels x (1 + grade) (past the room as Mixed), signed in
    percent into var:sr_ebase_mix_<good> and its size into var:sr_ebase_mix_<good>_units."""
    over = f"local_var:{fam}_over"
    out = ["# The base's two layers (§ 5.2) from where its levels work: T, the average grade",
           f"# over the levels, past the room at {gss.OVERFLOW_GRADE}%, into var:sr_ebase_grade (percent);",
           "# and each good's D(g), the places' types' mixes weighted by levels x (1 + grade),",
           "# past the room as Mixed, into var:sr_ebase_mix_<good> (signed, percent) and",
           "# var:sr_ebase_mix_<good>_units (its size, the modifiers' multiplier). Multiplied",
           "# first, divided last (fixed point).",
           f"{effect} = {{",
           "\tset_local_variable = {", "\t\tname = sr_ebx_levels", "\t\tvalue = {", f"\t\t\tvalue = {over}"]
    out += [f"\t\t\tadd = local_var:{at(fam, k)}" for _, k in places()]
    out += ["\t\t}", "\t}",
            "\tset_local_variable = {", "\t\tname = sr_ebx_grade_sum", "\t\tvalue = {",
            f"\t\t\tvalue = {over}", f"\t\t\tmultiply = {gss.OVERFLOW_GRADE}"]
    out += [f"\t\t\tadd = {{ value = local_var:{at(fam, k)} multiply = {grade_pct(k)} }}"
            for _, k in places() if grade_pct(k)]
    out += ["\t\t}", "\t}",
            "\tset_variable = { name = sr_ebase_grade value = 0 }",
            "\tif = {",
            "\t\tlimit = { local_var:sr_ebx_levels > 0 }",
            "\t\tset_variable = { name = sr_ebase_grade value = { value = local_var:sr_ebx_grade_sum "
            "divide = local_var:sr_ebx_levels } }",
            "\t}",
            "\tset_local_variable = {", "\t\tname = sr_ebx_weight", "\t\tvalue = {",
            f"\t\t\tvalue = {over}", f"\t\t\tmultiply = {OVER_FACTOR}"]
    out += [f"\t\t\tadd = {{ value = local_var:{at(fam, k)} multiply = {100 + grade_pct(k)} }}" for _, k in places()]
    out += ["\t\t}", "\t}"]
    for g in eg.GOODS:
        out += [f"\t# {GOOD_NAMES[g]}",
                "\tset_local_variable = {", "\t\tname = sr_ebx_made", "\t\tvalue = {",
                f"\t\t\tvalue = {over}", f"\t\t\tmultiply = {OVER_FACTOR}"]
        out += [f"\t\t\tadd = {{ value = local_var:{at(fam, k)} multiply = {num(mix_factor(k, g), 5)} }}"
                for _, k in places()]
        out += ["\t\t}", "\t}",
                f"\tset_variable = {{ name = sr_ebase_mix_{g} value = 0 }}",
                "\tif = {",
                "\t\tlimit = { local_var:sr_ebx_weight > 0 }",
                f"\t\tset_variable = {{ name = sr_ebase_mix_{g} value = {{ value = local_var:sr_ebx_made multiply = 100 "
                "divide = local_var:sr_ebx_weight subtract = 100 } }",
                "\t}",
                f"\tset_variable = {{ name = sr_ebase_mix_{g}_units value = var:sr_ebase_mix_{g} }}",
                "\tif = {",
                f"\t\tlimit = {{ var:sr_ebase_mix_{g} < 0 }}",
                f"\t\tset_variable = {{ name = sr_ebase_mix_{g}_units value = {{ value = var:sr_ebase_mix_{g} "
                "multiply = -1 } }",
                "\t}"]
    out.append("}")
    return out


