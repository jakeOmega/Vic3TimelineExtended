def render_read_inputs() -> list[str]:
    out = ["# The month's inputs, read once into locals (§ 8.2 step 1, § 8.3, § 8.5): the places",
           f"# (sr_eb_read_places) and each place's profit a level ({INPUTS}_p_<k>, sr_eb_read_profits,",
           "# which evaluates the margins at this month's prices). The passes then compare locals.",
           "sr_eb_read_inputs = {",
           "\tsr_eb_read_places = yes",
           "\tsr_eb_read_profits = yes",
           "}",
           "# A click's inputs (sr_eb_after_click): the places as the month reads them, and the",
           "# profits the last refresh stored (sr_eb_read_stored_profits), never the margins again.",
           "sr_eb_read_click_inputs = {",
           "\tsr_eb_read_places = yes",
           "\tsr_eb_read_stored_profits = yes",
           "}",
           f"# Each place's held ({INPUTS}_held_<k>, 1 or 0), serving us ({INPUTS}_sv_<k>: held, not",
           f"# blockaded, not occupied) and room serving us ({INPUTS}_room_<k>, 0 when it doesn't); the",
           "# built levels and the pace.",
           "sr_eb_read_places = {"]
    built = f"{INPUTS}_built"
    pace = f"{{ value = {lv(built)} divide = {eg.PACE_MONTHS} ceiling = yes min = 1 }}"
    out += [f"\t{_setl(built, 'sr_ebase_levels')}", f"\t{_setl(f'{INPUTS}_pace', pace)}"]
    for i, k in places():
        h, sv, room, _ = _inputs(k)
        out += [f"\t# {name(k)} (place {i})",
                f"\t{_setl(h, '0')}", f"\t{_setl(sv, '0')}", f"\t{_setl(room, '0')}",
                f"\tif = {{ limit = {{ {held(k)} }} {_setl(h, '1')} }}",
                "\tif = {",
                f"\t\tlimit = {{ {serves(k)} }}",
                f"\t\t{_setl(sv, '1')}",
                f"\t\t{_setl(room, room_value(k))}",
                "\t}"]
    out.append("}")
    return out


def render_stored_profits() -> list[str]:
    """F4 of the Tasks 5 and 6 review: the month's profit figures as country variables
    (every country: the Bases view and a click read them, never the margins), and the
    reader that puts them back into the month's locals for a click."""
    yard, margin = f"{INPUTS}_yard", f"{INPUTS}_margin"
    out = ["# The month's profit figures, stored at every refresh for every country (the Bases view",
           "# reads them, and a click's forecast and totals: the margins are evaluated once a refresh):",
           "# var:sr_eb_level_profit_<k>, each place's profit a level a week, and var:sr_eb_yardstick.",
           "sr_eb_store_profits = {"]
    out += [f"\tset_variable = {{ name = sr_eb_level_profit_{k} value = {lv(_inputs(k)[3])} }}" for _, k in places()]
    out += [f"\tset_variable = {{ name = sr_eb_yardstick value = {lv(yard)} }}", "}",
            "# The stored figures back into the month's locals, as sr_eb_read_profits sets them (a level",
            f"# past the room earns a near-Earth level's, Mixed at grade 0, x {OVER_FACTOR} / 100). 0 before any refresh.",
            "sr_eb_read_stored_profits = {"]
    for _, k in places():
        p = _inputs(k)[3]
        out += [f"\t{_setl(p, '0')}",
                f"\tif = {{ limit = {{ has_variable = sr_eb_level_profit_{k} }} {_setl(p, f'var:sr_eb_level_profit_{k}')} }}"]
    near = lv(_inputs(eg.NEAR_EARTH)[3])
    out += [f"\t{_setl(yard, '0')}",
            f"\tif = {{ limit = {{ has_variable = sr_eb_yardstick }} {_setl(yard, 'var:sr_eb_yardstick')} }}",
            f"\t{_setl(margin, f'{{ value = {lv(yard)} multiply = {num(eg.MARGIN)} }}')}",
            f"\t{_setl(OVER_PROFIT, f'{{ value = {near} multiply = {OVER_FACTOR} divide = 100 }}')}",
            "}"]
    return out


def render_read_profits() -> list[str]:
    out = ["# The seven margins once (sr_eb_margin_<type>), then each place's profit a level,",
           f"# (1 + grade) x its type's margin ({INPUTS}_p_<k>, as sr_eb_profit_<k> reads it); the",
           f"# yardstick ({INPUTS}_yard) and the move's margin, {num(eg.MARGIN)} of it ({INPUTS}_margin); a",
           f"# level's profit past all of the room ({OVER_PROFIT}).",
           "sr_eb_read_profits = {"]
    out += [f"\t{_setl(f'{INPUTS}_m_{t}', f'sr_eb_margin_{t}')}" for t in eg.TYPES]
    yard = f"{INPUTS}_yard"
    margin = f"{{ value = {lv(yard)} multiply = {num(eg.MARGIN)} }}"
    out += [f"\t{_setl(yard, 'sr_eb_yardstick')}", f"\t{_setl(f'{INPUTS}_margin', margin)}"]
    for _, k in places():
        profit = f"{{ value = {lv(f'{INPUTS}_m_{eg.GROUND[k]}')} multiply = {100 + grade_pct(k)} divide = 100 }}"
