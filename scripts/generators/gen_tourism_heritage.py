#!/usr/bin/env python3
"""Write tourism_heritage_generated.txt: the base appeal each state's monuments take.

A state's base tourism appeal (base_tourism_appeal_value, common/script_values/
tourism.txt) was scored partly on its historical monuments, which the Grand
Monuments and the vanilla wonders count again (docs/superpowers/archive/specs/
2026-10-23-tourism-heritage-design.md). The scores keep their values; the
points each monument stands for come off through tourism_heritage_moved, read by
tourism_bonus_from_base_appeal, and only while the monuments that take them can
exist (§ 6.3): a vanilla wonder's always, a landmark's while the Grand Monuments
rule is on and the 1836 landmarks were seeded (a To History landmark's, while
the seeding that placed them set gm_landmarks_seeded_2), a site's while the rule
is on.

The moves are scripts/generators/data/tourism_heritage_moves.csv (state, points,
monument, kind, reason); rows with 0 points are the revisit lists, kept for pass
2. Needs nothing but the repo. Re-run after editing the CSV;
test_tourism_heritage.py fails CI when the committed file is stale:

    python3 scripts/generators/gen_tourism_heritage.py [--check]

--annotate instead notes each moved state's total on its score's comment in
tourism.txt, so a reader of the table sees it; tourism.txt is hand-written, so
this is a one-shot editor, never a regenerator. Re-run it with the generator.
"""
import argparse
import collections
import csv
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(REPO, "scripts", "generators", "data", "tourism_heritage_moves.csv")
OUT = os.path.join(REPO, "common", "script_values", "tourism_heritage_generated.txt")
TOURISM = os.path.join(REPO, "common", "script_values", "tourism.txt")
NOTE = " ({} moved to monuments: tourism_heritage_generated.txt)"
NOTE_RE = re.compile(r" \(\d+ moved to monuments: tourism_heritage_generated\.txt\)")

Move = collections.namedtuple("Move", "state points monument kind reason")

KINDS = ("vanilla_wonder", "existing_landmark", "existing_site", "new_landmark", "new_site")

# What must hold for a kind's points to come off (spec § 6.3). None: always.
GATES = {
    "vanilla_wonder": None,
    "existing_landmark": "gm_system_enabled = yes has_global_variable = gm_landmarks_seeded",
    "existing_site": "gm_system_enabled = yes",
    "new_landmark": "gm_system_enabled = yes has_global_variable = gm_landmarks_seeded_2",
    "new_site": "gm_system_enabled = yes",
}


def load_moves(path=CSV):
    """The CSV's moves with points, in file order."""
    with open(path, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    moves = []
    for r in rows:
        points = int(r["points"])
        if points <= 0:
            continue
        if r["kind"] not in GATES:
            raise ValueError(f"{r['state']}: unknown kind {r['kind']!r}")
        moves.append(Move(r["state"], points, r["monument"], r["kind"], r["reason"]))
    return moves


def render(moves):
    states = []
    by_gate = collections.defaultdict(collections.Counter)
    for m in moves:
        if m.state not in states:
            states.append(m.state)
        by_gate[m.state][GATES[m.kind]] += m.points
    gate_order = []
    for kind in KINDS:
        if GATES[kind] not in gate_order:
            gate_order.append(GATES[kind])
    lines = [
        "# AUTO-GENERATED by scripts/generators/gen_tourism_heritage.py — do not edit manually.",
        "# The base appeal each state's monuments take (tourism heritage spec 2026-10-23 § 6.3), from",
        "# scripts/generators/data/tourism_heritage_moves.csv. A move counts only while the monuments that take it",
        "# can exist: a vanilla wonder's always, a landmark's while the Grand Monuments rule is on and the 1836",
        "# landmarks were seeded (a To History landmark's while gm_landmarks_seeded_2 says they were), a site's",
        "# while the rule is on. Re-run the generator after editing the CSV; test_tourism_heritage.py fails",
        "# when this file is stale.",
        "",
        "# State scope. Read by tourism_bonus_from_base_appeal (tourism.txt); 0-1, as base_tourism_appeal_value is.",
        "tourism_heritage_moved = {",
        "\tvalue = 0",
    ]
    for i, state in enumerate(states):
        lines.append(f"\t{'if' if i == 0 else 'else_if'} = {{")
        lines.append(f"\t\tlimit = {{ state_region = s:{state} }}")
        for gate in gate_order:
            points = by_gate[state].get(gate)
            if not points:
                continue
            if gate is None:
                lines.append(f"\t\tadd = {points}")
            else:
                lines.append(f"\t\tif = {{ limit = {{ {gate} }} add = {points} }}")
        lines.append("\t}")
    lines.append("\tdivide = 100")
    lines.append("}")
    return "\n".join(lines) + "\n"


def annotate(text, moves):
    """text with each moved state's total noted on its score's comment; every earlier note goes first, so a
    state whose moves have gone loses its note."""
    text = NOTE_RE.sub("", text)
    totals = collections.Counter()
    for m in moves:
        totals[m.state] += m.points
    for state, points in totals.items():
        pattern = re.compile(rf"(state_region = s:{state} \}}\n\t\tvalue = \d+)( #[^\n]*)?")
        match = pattern.search(text)
        if not match:
            raise ValueError(f"{state}: no score in tourism.txt")
        comment = (match.group(2) or " #").rstrip()
        text = text[:match.start()] + match.group(1) + comment + NOTE.format(points) + text[match.end():]
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale; write nothing")
    parser.add_argument("--annotate", action="store_true", help="note each move on its score in tourism.txt")
    args = parser.parse_args()
    moves = load_moves()
    if args.annotate:
        with open(TOURISM, encoding="utf-8-sig", newline="") as f:
            text = f.read()
        with open(TOURISM, "w", encoding="utf-8-sig", newline="") as f:
            f.write(annotate(text, moves))
        print(f"noted {len({m.state for m in moves})} states in {os.path.relpath(TOURISM, REPO)}")
        return 0
    text = render(moves)
    if args.check:
        try:
            with open(OUT, encoding="utf-8-sig") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f"{os.path.relpath(OUT, REPO)} is stale: run scripts/generators/gen_tourism_heritage.py")
            return 1
        print(f"{os.path.relpath(OUT, REPO)} is current")
        return 0
    with open(OUT, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print(f"wrote {len({m.state for m in moves})} states to {os.path.relpath(OUT, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
