"""Generate how far an undersea cable reaches across the sea (Power Grids).

Script has no Sea Node scope and no iterator over a Sea Node's neighbours, only
``every_sea_node_adjacent_state`` (the states that share a Sea Node with a
state). A walk in script therefore went from coast to coast and stopped at open
ocean that no coast touches: Bermuda, the only state on the Sargasso Sea,
reached no state at any range, and Hawaii sat five steps from the nearest
American cable with a range of three (2026-11-24). This measures the sea
offline instead, from the game's map, and writes the table
``te_grid_sea_reach_effect`` reads (docs/systems/mod_systems/power_grids.md
§ Undersea cables).

**Distance** is the number of Sea Nodes a cable crosses. A cable on a coast
crosses each Sea Node that coast touches (1). From a Sea Node it goes on to one
that borders it on the map, or to one a coastal state touches beside it,
landing on that coast as the walk in script did. So no two states are farther
apart than the old walk put them, and open ocean counts like any other Sea
Node. The two Southern Ocean nodes are not crossed at all (``UNCROSSABLE``).

**Coastal** means a land state region with a ``naval_exit_id``; only those are
in the table, and only their coasts carry a cable on. Six Arctic regions
border a sea on the map without one (Kolyma, the Northwest Territories, Ob,
Upper Yeniseysk, Yakutsk, Yukon), and every sea they touch is one the game
marks impassable, so they are assumed not coastal to the engine (unverified:
``TE_SELF_CHECK grid_sea_table`` reads ``missing=`` if a walk from a state
beside one finds the engine listing it). A region's Sea Nodes are the ones its
provinces touch on the map; its ``naval_exit_id`` counts only where they touch
none (no region today: Lithuania's exit is the Northern Baltic, which it
doesn't touch, and it stays two Sea Nodes from that sea's coasts, as the walk
in script had it).

Inputs:

* ``grid_sea_borders.json`` beside this file: each Sea Node's province and the
  provinces it borders in ``game/map_data/provinces.png``, a pixel of one
  touching a pixel of the other across a row or a column (the map wraps east
  to west). The map isn't in the repo and CI has no game, so the borders are
  committed. ``--refresh`` rewrites them from the install (needs NumPy and
  Pillow); ``--check-map`` exits 1 when the install's map has changed. Stored by
  province, not by state region, so a change to the mod's region files is
  picked up without a refresh.
* ``map_data/state_regions/*.txt``, the mod's copy of the whole map (the game
  reads it in place of vanilla's): each land region's provinces and naval exit,
  each Sea Node's province.

Output: ``common/scripted_effects/te_grid_sea_reach_generated.txt``,
``te_grid_sea_reach_table_effect``: one ``if``/``else_if`` branch per coastal
state region, listing the coastal regions within ``MAX_HOPS`` Sea Nodes by
distance, its own region first (its other states, when it is split).

Run ``python3 scripts/generators/gen_grid_sea_reach.py [--dry-run | --check]``.
The table needs no game install or running server; full server reloads call
``regenerate`` (server/post_load.py POST_LOAD_REGENERATORS).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

STATE_REGIONS = Path("map_data/state_regions")
SEAS_FILE = STATE_REGIONS / "99_seas.txt"
OUT = Path("common/scripted_effects/te_grid_sea_reach_generated.txt")
BORDERS = Path(__file__).resolve().parent / "grid_sea_borders.json"

# The farthest the table goes. A cable's range is the HVDC method's 1 plus 1
# each from Smart Grids and Quantum Materials; test_grid_sea_reach.py fails
# when the mod's range lines add up to more.
MAX_HOPS = 3

# Sea Nodes no cable crosses (owner, 2026-11-24). Their size is the reason: the
# median Sea Node covers about 83,000 pixels of provinces.png, and these two
# about 1.2 and 2.5 million, a band around Antarctica, so counted as one
# crossing each they took a cable from the Falklands to Queensland in two.
# Neither is shared by two coasts (01 has none, 02 only the South Atlantic
# Islands), so leaving them out lengthens no link the walk in script made.
UNCROSSABLE = frozenset({"STATE_SOUTHERN_OCEAN_01", "STATE_SOUTHERN_OCEAN_02"})

_STATE_RE = re.compile(r"^(STATE_\w+)\s*=\s*\{", re.M)
_PROVINCES_RE = re.compile(r"\bprovinces\s*=\s*\{([^}]*)\}")
_PROVINCE_RE = re.compile(r"\b[xX]([0-9A-Fa-f]{6})\b")
_ID_RE = re.compile(r"\bid\s*=\s*(\d+)")
_EXIT_RE = re.compile(r"\bnaval_exit_id\s*=\s*(\d+)")

HEADER = (
    "# AUTO-GENERATED by scripts/generators/gen_grid_sea_reach.py - do not edit manually.\n"
    "# Power Grids, undersea cables: docs/systems/mod_systems/power_grids.md § Undersea cables\n"
)
PREAMBLE = """\
# Scope: state, the start of a walk across the sea, called by
# te_grid_sea_reach_effect (power_grid_effects.txt) with
# local_var:te_grid_sea_radius set. Marks every coastal state within that many
# Sea Nodes of this one with var:te_grid_sea_hops, its distance, and lists it
# in te_grid_sea_reach (te_grid_sea_reach_region_effect), its own region first,
# up to {max_hops}. The distance is the Sea Nodes a cable crosses, from the
# game's map: from one Sea Node on to one bordering it, or to one a coast
# touches beside it. The Southern Ocean is not crossed. A state matching no
# branch (landlocked, or on no Sea Node but those) reaches nothing.
"""


def _norm(token: str) -> str:
    return "x" + token[-6:].upper()


def _blocks(text: str):
    """(name, body) of each top-level ``STATE_X = { ... }`` block."""
    starts = list(_STATE_RE.finditer(text))
    for i, m in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else len(text)
        yield m.group(1), text[m.end():end]


def _provinces(body: str) -> list[str]:
    m = _PROVINCES_RE.search(body)
    return [_norm(p) for p in _PROVINCE_RE.findall(m.group(1))] if m else []


def read_seas(root: Path = ROOT) -> dict[str, dict]:
    """Sea Node -> {"id": its id, "provinces": [its provinces]}, from 99_seas.txt."""
    text = (root / SEAS_FILE).read_text(encoding="utf-8-sig")
    out = {}
    for name, body in _blocks(text):
        m = _ID_RE.search(body)
        out[name] = {"id": int(m.group(1)) if m else None, "provinces": _provinces(body)}
    return out


def read_land(root: Path = ROOT) -> dict[str, dict]:
    """Land state region -> {"provinces": [...], "naval_exit": id or None}."""
    out = {}
    for path in sorted((root / STATE_REGIONS).glob("*.txt")):
        if path.name == SEAS_FILE.name:
            continue
        for name, body in _blocks(path.read_text(encoding="utf-8-sig")):
            exits = [int(n) for n in _EXIT_RE.findall(body)]
            out[name] = {"provinces": _provinces(body), "naval_exit": exits[0] if exits else None}
    return out


# ---------------------------------------------------------------------------
# The map's sea borders (needs the install)
# ---------------------------------------------------------------------------

def _game_dir(arg: str | None = None) -> Path:
    if arg:
        return Path(arg)
    sys.path.insert(0, str(ROOT))
    import path_constants
    return Path(path_constants.base_game_path) / "game"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_borders(game_dir: Path, root: Path = ROOT) -> dict:
    """Each Sea Node province's bordering provinces in provinces.png."""
    import numpy as np
    from PIL import Image

    Image.MAX_IMAGE_PIXELS = None
    png = Path(game_dir) / "map_data" / "provinces.png"
    seas = {int(p[1:], 16) for sea in read_seas(root).values() for p in sea["provinces"]}
    img = np.asarray(Image.open(png).convert("RGB"), dtype=np.uint32)
    colour = (img[:, :, 0] << 16) | (img[:, :, 1] << 8) | img[:, :, 2]
    borders: dict[int, set[int]] = {s: set() for s in seas}
    # Across a column, across a row, and across the east-west seam.
    for a, b in ((colour[:, :-1], colour[:, 1:]), (colour[:-1, :], colour[1:, :]), (colour[:, -1:], colour[:, :1])):
        diff = a != b
        keys = np.unique((a[diff].astype(np.uint64) << np.uint64(24)) | b[diff].astype(np.uint64))
        for k in keys.tolist():
            x, y = k >> 24, k & 0xFFFFFF
            if x in borders:
                borders[x].add(y)
            if y in borders:
                borders[y].add(x)
    return {
        "provinces_png": {"size": png.stat().st_size, "sha256": _sha256(png)},
        "sea_borders": {f"x{s:06X}": sorted(f"x{n:06X}" for n in v) for s, v in sorted(borders.items())},
    }


def load_borders(path: Path = BORDERS) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _dump_borders(data: dict) -> str:
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


# ---------------------------------------------------------------------------
# The table
# ---------------------------------------------------------------------------

def sea_map(root: Path = ROOT, borders: dict | None = None) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    """(coastal region -> the Sea Nodes it touches, Sea Node -> the Sea Nodes a
    cable goes on to from it), the Southern Ocean left out of both. Raises when
    a Sea Node's province is missing from the borders (refresh them)."""
    borders = load_borders() if borders is None else borders
    sea_borders = borders["sea_borders"]
    seas = read_seas(root)
    land = read_land(root)
    by_id = {s["id"]: name for name, s in seas.items()}
    sea_of = {}
    for name, s in seas.items():
        for p in s["provinces"]:
            if p not in sea_borders:
                raise ValueError(f"{name}'s province {p} is not in {BORDERS.name}: run --refresh")
            sea_of[p] = name
    region_of = {p: name for name, r in land.items() for p in r["provinces"]}

    region_seas: dict[str, set[str]] = {}
    sea_next: dict[str, set[str]] = {name: set() for name in seas if name not in UNCROSSABLE}
    for p, nbrs in sea_borders.items():
        sea = sea_of.get(p)
        if sea is None or sea in UNCROSSABLE:
            continue
        for n in nbrs:
            if n in sea_of:
                if sea_of[n] != sea and sea_of[n] not in UNCROSSABLE:
                    sea_next[sea].add(sea_of[n])
            elif n in region_of and land[region_of[n]]["naval_exit"] is not None:
                region_seas.setdefault(region_of[n], set()).add(sea)
    for name, r in land.items():
        exit_sea = by_id.get(r["naval_exit"])
        if exit_sea and exit_sea not in UNCROSSABLE and not region_seas.get(name):
            region_seas[name] = {exit_sea}
    # Landing on a coast: a cable goes on from any Sea Node it touches to any other.
    for touched in region_seas.values():
        for a in touched:
            sea_next[a] |= touched - {a}
    return region_seas, sea_next


def reach(region_seas: dict[str, set[str]], sea_next: dict[str, set[str]],
          max_hops: int = MAX_HOPS) -> dict[str, dict[str, int]]:
    """Coastal region -> {coastal region within max_hops: Sea Nodes crossed}, itself at 1."""
    on_sea: dict[str, set[str]] = {}
    for region, touched in region_seas.items():
        for s in touched:
            on_sea.setdefault(s, set()).add(region)
    out = {}
    for src, touched in region_seas.items():
        dist = {s: 1 for s in touched}
        queue = deque(touched)
        while queue:
            s = queue.popleft()
            if dist[s] >= max_hops:
                continue
            for n in sea_next[s]:
                if n not in dist:
                    dist[n] = dist[s] + 1
                    queue.append(n)
        hops: dict[str, int] = {}
        for s, d in dist.items():
            for region in on_sea.get(s, ()):
                if d < hops.get(region, max_hops + 1):
                    hops[region] = d
        out[src] = hops
    return out


def render(table: dict[str, dict[str, int]], max_hops: int = MAX_HOPS) -> str:
    pairs = sum(len(v) - 1 for v in table.values())
    lines = [HEADER, PREAMBLE.format(max_hops=max_hops)]
    lines.append(f"# {len(table)} coastal state regions; {pairs} ordered pairs within {max_hops} Sea Nodes.\n")
    lines.append("te_grid_sea_reach_table_effect = {\n")
    for i, src in enumerate(sorted(table)):
        hops = table[src]
        lines.append(f"\t{'if' if i == 0 else 'else_if'} = {{\n")
        lines.append(f"\t\tlimit = {{ state_region = s:{src} }}\n")
        for d in range(1, max_hops + 1):
            ring = sorted(r for r, h in hops.items() if h == d and r != src)
            if d == 1:
                ring = [src] + ring
            if not ring:
                continue
            lines.append("\t\tif = {\n")
            lines.append(f"\t\t\tlimit = {{ local_var:te_grid_sea_radius >= {d} }}\n")
            lines.extend(f"\t\t\tte_grid_sea_reach_region_effect = {{ REGION = s:{r} HOPS = {d} }}\n" for r in ring)
            lines.append("\t\t}\n")
        lines.append("\t}\n")
    lines.append("}\n")
    return "".join(lines)


def plan_outputs(root: Path = ROOT, borders: dict | None = None) -> dict[Path, str]:
    region_seas, sea_next = sea_map(root, borders)
    return {OUT: render(reach(region_seas, sea_next))}


def regenerate(mod_state=None, *, root: Path = ROOT, dry_run: bool = False) -> dict:
    """Post-load entry point (server/post_load.py POST_LOAD_REGENERATORS) and CLI body.

    Reads the committed borders and the map files; `mod_state` is unused.
    Writes the file only when its content changed, with one UTF-8 BOM.
    """
    changed = []
    for relative, text in plan_outputs(root).items():
        target = root / relative
        expected = text.encode("utf-8-sig")
        if not target.exists() or target.read_bytes() != expected:
            changed.append(str(relative))
            if not dry_run:
                target.write_bytes(expected)
    return {"changed": bool(changed), "changed_files": changed}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if the table is stale")
    mode.add_argument("--refresh", action="store_true",
                      help=f"rewrite {BORDERS.name} from the install's provinces.png, then the table")
    mode.add_argument("--check-map", action="store_true",
                      help=f"exit 1 if the install's provinces.png no longer gives {BORDERS.name}")
    parser.add_argument("--game-dir", help="the base game's game/ folder (default: path_constants)")
    args = parser.parse_args()
    if args.refresh or args.check_map:
        fresh = _dump_borders(build_borders(_game_dir(args.game_dir)))
        if args.check_map:
            stale = not BORDERS.exists() or BORDERS.read_text(encoding="utf-8") != fresh
            print(f"{BORDERS.name}: {'stale: run --refresh' if stale else 'current'}")
            return int(stale)
        BORDERS.write_text(fresh, encoding="utf-8")
        print(f"wrote: {BORDERS.relative_to(ROOT)}")
    result = regenerate(dry_run=args.dry_run or args.check)
    verb = "stale" if args.check else "would write" if args.dry_run else "wrote"
    for path in result["changed_files"]:
        print(f"{verb}: {path}")
    if not result["changed"]:
        print("grid sea reach: current")
    return int(args.check and result["changed"])


if __name__ == "__main__":
    sys.exit(main())
