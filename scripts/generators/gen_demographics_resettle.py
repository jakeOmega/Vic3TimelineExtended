#!/usr/bin/env python3
"""Internal Resettlement's known moves and the US frontier's 1836 seed: the generated census script (2026-10-19).

The master spec (docs/superpowers/specs/2026-10-08-demographics-design.md) §2.5 "Known kills" and §2.6.
gen_demographics.plan_outputs() writes these two files beside its own, so `gen_demographics.py --check` covers them:
    common/scripted_effects/te_demog_resettle_generated_effects.txt
        te_demog_rs_add                 a programme's movers into a state's counters by class and sex (SIDE = i at
                                        the destination, o at the source)
        te_demog_rs_known_rates         the step's known rates from the counters over last year's class sums
        te_demog_rs_enter_class         the known rates into the migrant class's gain and loss shares
        te_demog_rs_youth_hook          Rustication's ages that are no class's first: the class re-entered there
        te_demog_rs_clear               the counters removed (the step, the seed)
        te_demog_frontier_ratios        the US frontier's men per woman by age group, by state region
        te_demog_frontier_slot          one seed slot's men at its age group's ratio
    common/script_values/te_demog_resettle_generated_values.txt
        te_demog_rs_labour_f, te_demog_rs_dbg_in/_out/_dead (the console's te_debug_demog.120),
        te_demog_frontier_listed
The hand-written logic is common/scripted_effects/te_demog_resettle_effects.txt; demographics_resettle.py is the twin.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "analysis"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import demographics_params as P  # noqa: E402
import demographics_resettle as RS  # noqa: E402

RS_EFFECTS = Path("common/scripted_effects/te_demog_resettle_generated_effects.txt")
RS_VALUES = Path("common/script_values/te_demog_resettle_generated_values.txt")
HEADER = ("# AUTO-GENERATED by scripts/generators/gen_demographics.py (gen_demographics_resettle.py) - do not edit manually.\n"
          "# docs/superpowers/specs/2026-10-08-demographics-design.md §2.5-2.6; parameters in\n"
          "# scripts/analysis/demographics_params.py (Internal Resettlement's known moves, the US frontier).\n")
N_CLASSES = len(P.MIGRANT_CLASSES)
CLASS_STARTS = [lo for lo, _hi in P.MIGRANT_CLASSES]
YOUTH_LO, YOUTH_HI = P.RESETTLE_KINDS["youth"]["ages"]
# the youth's people are the five-year bands that cover its ages exactly (te_dg_bf<b>, te_dg_bm<b>)
assert YOUTH_LO % 5 == 0 and (YOUTH_HI + 1) % 5 == 0, "Rustication's ages are whole five-year bands"
YOUTH_BANDS = list(range(YOUTH_LO // 5, (YOUTH_HI + 1) // 5))
# the classes the youth's ages touch
YOUTH_CLASSES = [c for c, (lo, hi) in enumerate(P.MIGRANT_CLASSES) if lo <= YOUTH_HI and hi >= YOUTH_LO]
# the ages where the youth's rates start or end and no class starts: the class is entered again there
YOUTH_HOOKS = sorted({YOUTH_LO, YOUTH_HI + 1} - set(CLASS_STARTS))
KEYS = [(c, s) for c in range(N_CLASSES) for s in "fm"] + [("youth", s) for s in "fm"]


def _name(side, key):
    c, s = key
    return f"te_dg_rs_{side}_y{s}" if c == "youth" else f"te_dg_rs_{side}_{s}{c}"


def counter_names():
    """Every counter variable a state can hold (te_demog_rs_clear)."""
    return ["te_dg_rs_in", "te_dg_rs_out", "te_dg_rs_dead"] + [_name(side, k) for side in "io" for k in KEYS]


def _share_terms(programme):
    """{key: (constant, per unit of the destination's labour women's share)} of a programme's movers."""
    at0 = RS.programme_shares(programme, 0.0)
    at1 = RS.programme_shares(programme, 1.0)
    out = {}
    for k in set(at0) | set(at1):
        a, b = at0.get(k, 0.0), at1.get(k, 0.0) - at0.get(k, 0.0)
        if abs(a) > 1e-12 or abs(b) > 1e-12:
            out[k] = (a, b)
    return out


def _add_block(o, programme):
    from gen_demographics import lit
    for key, (a, b) in sorted(_share_terms(programme).items(), key=lambda kv: str(kv[0])):
        name = _name("$SIDE$", key)
        share = lit(a) if abs(b) < 1e-12 else f"{{ value = local_var:te_dg_rs_lf multiply = {lit(b)} add = {lit(a)} }}"
        amount = f"{{ value = local_var:te_dg_rs_amt multiply = {share} }}"
        o("if = {")
        o(f"limit = {{ has_variable = {name} }}")
        o(f"change_variable = {{ name = {name} add = {amount} }}")
        o("}")
        o("else = {")
        o(f"set_variable = {{ name = {name} value = {amount} }}")
        o("}")


def render_rs_effects():
    from gen_demographics import Out, tree
    o = Out()
    o(HEADER.rstrip("\n"))
    o("")
    o("# THIS = the state whose counters grow: a destination's arrivals (SIDE = i) or a source's departures and transit")
    o("# dead (SIDE = o). Locals: te_dg_rs_code (the programme, var:rs_programme), te_dg_rs_amt (people) and te_dg_rs_lf")
    o("# (the destination's jobs' women's share, te_demog_rs_labour_f). Adds the programme's movers by class and sex")
    o("# (te_dg_rs_<SIDE>_f<c>, _m<c>) and at Rustication's single years (te_dg_rs_<SIDE>_yf, _ym), by")
    o("# demographics_params.RESETTLE_PROFILES (demographics_resettle.book).")
    o("te_demog_rs_add = {")
    tree(o, "te_dg_rs_code", 0, len(P.RESETTLE_PROGRAMMES) - 1, lambda o, code: _add_block(o, P.RESETTLE_PROGRAMMES[code]))
    o("}")
    o("")
    o("# THIS = a state at its census step, holding counters (te_demog_rs_take). Each class and sex's arrivals")
    o("# (te_dg_rk_g<s><c>) and departures (te_dg_rk_d<s><c>) over its last-year sum (var:te_dg_c<s><c>); Rustication's")
    o("# over the people at its ages (te_dg_rk_gy<s>, te_dg_rk_dy<s>; the bands " +
      ", ".join(f"te_dg_b<s>{b}" for b in YOUTH_BANDS) + "); what a class or the youth's ages with under")
    o("# one person can't take, at one flat rate over every class with people (te_dg_rk_gflat, te_dg_rk_dflat). No cap:")
    o("# a known move is a count (demographics_resettle.known_rates).")
    o("te_demog_rs_known_rates = {")
    o("set_local_variable = { name = te_dg_rk_all value = 0 }")
    o("set_local_variable = { name = te_dg_rk_gleft value = 0 }")
    o("set_local_variable = { name = te_dg_rk_dleft value = 0 }")
    for c in range(N_CLASSES):
        for s in "fm":
            last = f"var:te_dg_c{s}{c}"
            o(f"set_local_variable = {{ name = te_dg_rk_g{s}{c} value = 0 }}")
            o(f"set_local_variable = {{ name = te_dg_rk_d{s}{c} value = 0 }}")
            o("if = {")
            o(f"limit = {{ {last} >= 1 }}")
            o(f"change_local_variable = {{ name = te_dg_rk_all add = {last} }}")
            for side, rate in (("i", "g"), ("o", "d")):
                o("if = {")
                o(f"limit = {{ has_variable = {_name(side, (c, s))} }}")
                o(f"set_local_variable = {{ name = te_dg_rk_{rate}{s}{c} value = {{ value = var:{_name(side, (c, s))} "
                  f"divide = {{ value = {last} min = 1 }} }} }}")
                o("}")
            o("}")
            o("else = {")
            for side, left in (("i", "gleft"), ("o", "dleft")):
                o("if = {")
                o(f"limit = {{ has_variable = {_name(side, (c, s))} }}")
                o(f"change_local_variable = {{ name = te_dg_rk_{left} add = var:{_name(side, (c, s))} }}")
                o("}")
            o("}")
    for s in "fm":
        people = " ".join(["value = var:te_dg_b" + s + str(YOUTH_BANDS[0])]
                          + [f"add = var:te_dg_b{s}{b}" for b in YOUTH_BANDS[1:]])
        o(f"set_local_variable = {{ name = te_dg_rk_yp{s} value = {{ {people} }} }}")
        o(f"set_local_variable = {{ name = te_dg_rk_gy{s} value = 0 }}")
        o(f"set_local_variable = {{ name = te_dg_rk_dy{s} value = 0 }}")
        for side, rate, left in (("i", "g", "gleft"), ("o", "d", "dleft")):
            name = _name(side, ("youth", s))
            o("if = {")
            o(f"limit = {{ has_variable = {name} }}")
            o("if = {")
            o(f"limit = {{ local_var:te_dg_rk_yp{s} >= 1 }}")
            o(f"set_local_variable = {{ name = te_dg_rk_{rate}y{s} value = {{ value = var:{name} "
              f"divide = {{ value = local_var:te_dg_rk_yp{s} min = 1 }} }} }}")
            o("}")
            o("else = {")
            o(f"change_local_variable = {{ name = te_dg_rk_{left} add = var:{name} }}")
            o("}")
            o("}")
    for flat, left in (("gflat", "gleft"), ("dflat", "dleft")):
        o(f"set_local_variable = {{ name = te_dg_rk_{flat} value = 0 }}")
        o("if = {")
        o("limit = { local_var:te_dg_rk_all >= 1 }")
        o(f"set_local_variable = {{ name = te_dg_rk_{flat} value = {{ value = local_var:te_dg_rk_{left} "
          "divide = { value = local_var:te_dg_rk_all min = 1 } } }")
        o("}")
    o("}")
    o("")
    o("# THIS = a state in its step's sweep, after te_demog_enter_class, while it holds known moves (local te_dg_rk_on):")
    o("# the class's known rates and the flat ones added to its gain and loss shares (te_dg_mig_gain_<s>,")
    o(f"# te_dg_mig_frac_<s>), and Rustication's at rate ages {YOUTH_LO}-{YOUTH_HI} (demographics_resettle.Known.rates).")
    o("te_demog_rs_enter_class = {")

    def leaf(o, c):
        for s in "fm":
            o("if = {")
            o(f"limit = {{ var:te_dg_c{s}{c} >= 1 }}")
            o(f"change_local_variable = {{ name = te_dg_mig_gain_{s} add = {{ value = local_var:te_dg_rk_g{s}{c} "
              "add = local_var:te_dg_rk_gflat } }")
            o(f"change_local_variable = {{ name = te_dg_mig_frac_{s} add = {{ value = local_var:te_dg_rk_d{s}{c} "
              "add = local_var:te_dg_rk_dflat } }")
            if c in YOUTH_CLASSES:
                o("if = {")
                o(f"limit = {{ local_var:te_dg_r >= {YOUTH_LO} local_var:te_dg_r <= {YOUTH_HI} }}")
                o(f"change_local_variable = {{ name = te_dg_mig_gain_{s} add = local_var:te_dg_rk_gy{s} }}")
                o(f"change_local_variable = {{ name = te_dg_mig_frac_{s} add = local_var:te_dg_rk_dy{s} }}")
                o("}")
            o("}")
    tree(o, "te_dg_acls", 0, N_CLASSES - 1, leaf)
    o("}")
    o("")
    o("# THIS = a state in its step's sweep, at every slot while it holds known moves: at a rate age where Rustication's")
    o("# rates start or end and no class starts, the class's shares are taken again, so its rates reach exactly its ages.")
    o("te_demog_rs_youth_hook = {")
    if YOUTH_HOOKS:
        o("if = {")
        o("limit = {")
        if len(YOUTH_HOOKS) > 1:
            o("OR = {")
        for a in YOUTH_HOOKS:
            o(f"local_var:te_dg_r = {a}")
        if len(YOUTH_HOOKS) > 1:
            o("}")
        o("}")
        o("te_demog_enter_class = yes")
        o("te_demog_rs_enter_class = yes")
        o("}")
    else:
        o("# no such age: the youth's ages start and end at class boundaries")
        o("set_local_variable = { name = te_dg_rk_hook value = 0 }")
    o("}")
    o("")
    o("# THIS = a state: its known-move counters removed (te_demog_rs_take after the step reads them; te_demog_seed, which")
    o("# counts the people as they are). Every add also raises one of the three totals, so a state with none has none.")
    o("# And the last step's known net (te_dg_rs_net), which te_demog_flows writes again after the take.")
    o("te_demog_rs_clear = {")
    o("if = {")
    o("limit = { has_variable = te_dg_rs_net }")
    o("remove_variable = te_dg_rs_net")
    o("}")
    o("if = {")
    o("limit = {")
    o("OR = {")
    for n in counter_names()[:3]:
        o(f"has_variable = {n}")
    o("}")
    o("}")
    for n in counter_names():
        o("if = {")
        o(f"limit = {{ has_variable = {n} }}")
        o(f"remove_variable = {n}")
        o("}")
    o("}")
    o("}")
    o("")
    frontier_effects(o)
    return o.text()


def frontier_groups():
    """The frontier's age groups, one list every state region shares: [(first age, last age)]."""
    groups = None
    for region, row in P.FRONTIER_1836.items():
        g = sorted(row["ratios"])
        assert groups is None or g == groups, f"{region}: every frontier region takes the same age groups"
        groups = g
    return groups or []


def frontier_effects(o):
    from gen_demographics import lit
    groups = frontier_groups()
    o("# THIS = a state the history marks as the US frontier (te_dg_frontier), at its 1836 seed (te_demog_frontier_begin):")
    o("# its men per woman at each age group (te_dg_fr_<j>) by its state region, from the 1840 census's free white men")
    o("# per 100 women weighted by the region's settler share (demographics_params.FRONTIER_1836).")
    o("te_demog_frontier_ratios = {")
    for j in range(len(groups)):
        o(f"set_local_variable = {{ name = te_dg_fr_{j} value = 0 }}")
    first = True
    for region, row in sorted(P.FRONTIER_1836.items()):
        o(("if" if first else "else_if") + " = {")
        o(f"limit = {{ state_region = s:{region} }}")
        for j, g in enumerate(groups):
            o(f"set_local_variable = {{ name = te_dg_fr_{j} value = {lit(row['ratios'][g])} }}")
        o("}")
        first = False
    o("}")
    o("")
    o("# THIS = a state in its seed's sweep, frontier on (local te_dg_fr_on), after slot $S$'s cohort is written: at an")
    o("# age group's ages the cohort's men are its women x the group's ratio (te_dg_fr_<j>; a ratio 0, a region not")
    o("# listed, leaves the seed's men). The seed's normalisation then keeps the state's people")
    o("# (demographics_resettle.frontier_seed).")
    o("te_demog_frontier_slot = {")
    if groups:
        # contiguous groups from the first age to the ring's last: an if on the first age, then each group by its last
        assert all(groups[j][1] + 1 == groups[j + 1][0] for j in range(len(groups) - 1)), "contiguous frontier groups"
        assert groups[-1][1] >= P.RING_YEARS - 1, "the last frontier group runs to the ring's end"
        o("if = {")
        o(f"limit = {{ local_var:te_dg_age >= {groups[0][0]} }}")
        for j, (_lo, hi) in enumerate(groups):
            last = j == len(groups) - 1
            o("else = {" if last and j else (("if" if j == 0 else "else_if") + " = {"))
            if not (last and j):
                o(f"limit = {{ local_var:te_dg_age <= {hi} }}")
            o("if = {")
            o(f"limit = {{ local_var:te_dg_fr_{j} > 0 }}")
            o(f"set_variable = {{ name = te_dg_m$S$ value = {{ value = var:te_dg_f$S$ multiply = local_var:te_dg_fr_{j} }} }}")
            o("}")
            o("}")
        o("}")
    o("}")
    o("")


def render_rs_values():
    from gen_demographics import Out
    o = Out()
    o(HEADER.rstrip("\n"))
    o("")
    o("# State scope, a destination: the labour kind's women's share by its jobs (the Development Program's labour; the")
    o("# residual's te_dg_labour_f before its balance ramp, demographics_resettle.labour_female_share). The walk's")
    o("# te_dg_fjob_share, or the minimum before a state's first walk.")
    o("te_demog_rs_labour_f = {")
    o("value = te_demog_k_labour_female_min")
    o("if = {")
    o("limit = { has_variable = te_dg_fjob_share }")
    o("value = te_demog_k_labour_female_max")
    o("subtract = te_demog_k_labour_female_min")
    o("multiply = var:te_dg_fjob_share")
    o("multiply = { value = te_demog_female_work_share divide = { value = te_demog_k_full_female_work_share min = 0.01 } }")
    o("add = te_demog_k_labour_female_min")
    o("min = te_demog_k_labour_female_min")
    o("max = te_demog_k_labour_female_max")
    o("}")
    o("}")
    o("")
    o("# State scope, for the console's te_debug_demog.120: each total, 0 without it.")
    for n in counter_names()[:3]:
        o(f"te_demog_rs_dbg_{n[len('te_dg_rs_'):]} = {{")
        o("value = 0")
        o(f"if = {{ limit = {{ has_variable = {n} }} value = var:{n} }}")
        o("}")
    o("")
    o("# State scope: 1 in a state region the US frontier's 1836 seed lists (demographics_params.FRONTIER_1836), else 0.")
    o("te_demog_frontier_listed = {")
    o("value = 0")
    if P.FRONTIER_1836:
        o("if = {")
        o("limit = {")
        o("OR = {")
        for region in sorted(P.FRONTIER_1836):
            o(f"state_region = s:{region}")
        o("}")
        o("}")
        o("value = 1")
        o("}")
    o("}")
    return o.text()


def plan_outputs():
    return {RS_EFFECTS: render_rs_effects(), RS_VALUES: render_rs_values()}
