#!/usr/bin/env python3
"""Uploaded minds' generated census script (docs/superpowers/specs/2026-10-16-demographics-uploaded-minds-design.md).

gen_demographics.plan_outputs() writes these two files beside its own, so `gen_demographics.py --check` covers them:
    common/scripted_effects/te_demog_um_generated_effects.txt
        te_demog_um_group_ic        every age group's infection and chronic death rate at the step's own multipliers
        te_demog_um_ic_at           a treated part's at its biological rate age te_dg_lx_rb
        te_demog_um_group_flush     the late sweep's treated infection-and-chronic sums for the age group te_dg_g
        te_demog_um_sex_sums        those sums over every group, women and men
        te_demog_um_l100            Living to 100 counting uploads: the blended table less the uploads
    common/script_values/te_demog_um_generated_values.txt
        te_demog_k_um_* constants
gen_demographics.medicine_effects calls backup_inputs (Mind Backups' restore x E in te_demog_cause_inputs_store). The
hand-written logic is common/scripted_effects/te_demog_um_effects.txt; demographics_uploads.py is the twin.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "analysis"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import demographics_model as M  # noqa: E402
import demographics_params as P  # noqa: E402

UM_EFFECTS = Path("common/scripted_effects/te_demog_um_generated_effects.txt")
UM_VALUES = Path("common/script_values/te_demog_um_generated_values.txt")
HEADER = ("# AUTO-GENERATED by scripts/generators/gen_demographics.py (gen_demographics_um.py) - do not edit manually.\n"
          "# docs/superpowers/specs/2026-10-16-demographics-uploaded-minds-design.md; parameters in\n"
          "# scripts/analysis/demographics_params.py (Uploaded minds).\n")
STARTS = [s for s, _w in P.GROUPS]


def _lit(x):
    from gen_demographics import lit
    return lit(x)


def backup_inputs(o):
    """Mind Backups' restore (call 2) into te_demog_cause_inputs_store: each BACKUP_TYPES line x last step's longevity care
    E (te_dg_elig), added to its cause's input; a state without E (no late game) takes none of it."""
    o("# uploaded minds' call 2 (2026-10-19): Mind Backups' restore only for those in longevity care, its lines x last")
    o("# step's share in care (te_dg_elig; demographics_model.plain_multiplier)")
    o("if = {")
    o("limit = { has_variable = te_dg_elig }")
    for cause, t in P.BACKUP_TYPES.items():
        short = P.CAUSE_SHORT[cause]
        o(f"set_variable = {{ name = te_dg_in_{short} value = {{ value = var:te_dg_in_{short} add = {{ value = 0 "
          f"add = modifier:{t} multiply = var:te_dg_elig }} }} }}")
    o("}")


def group_ic(o):
    o("# THIS = a state, in te_demog_um_begin (te_demog_lx_begin, after te_demog_lx_group_rates_unscaled: the step's own")
    o("# multipliers, before the on-top scales): every age group's infection and chronic death rate per 100,000, women's and")
    o("# men's (demographics_uploads.ic_rates), at most the group's whole rate, into te_dg_umu_ic<f|m><group>.")
    o("te_demog_um_group_ic = {")
    for g in range(len(P.GROUPS)):
        adult = g in M.INFECTION_ADULT_GROUPS
        for s in "fm":
            rf, rc = P.INFECTION[s][g], P.CHRONIC[s][g]
            parts = []
            if rf:
                inf = f"value = local_var:te_dg_m_inf multiply = {_lit(rf)}"
                if adult:
                    inf += " multiply = local_var:te_dg_inf_ad"
                parts.append(inf)
            if rc:
                chr_ = f"value = local_var:te_dg_m_chr multiply = {_lit(rc)}"
                parts.append(chr_ if not parts else f"add = {{ {chr_} }}")
            body = " ".join(parts) if parts else "value = 0"
            o(f"set_local_variable = {{ name = te_dg_umu_ic{s}{g} value = {{ {body} max = local_var:te_dg_lxu_q{s}{g} }} }}")
    o("}")
    o("")


def _threshold_tree(o, var, starts, leaf):
    from gen_demographics_lx import _threshold_tree as tree
    tree(o, var, starts, leaf)


def ic_at(o):
    o("# THIS = a state, in the late sweep: a treated part's infection and chronic rate at its biological rate age")
    o("# local_var:te_dg_lx_rb (demographics_uploads.Sums.slot), into te_dg_um_icf and te_dg_um_icm.")
    o("te_demog_um_ic_at = {")

    def leaf(o, g):
        for s in "fm":
            o(f"set_local_variable = {{ name = te_dg_um_ic{s} value = local_var:te_dg_umu_ic{s}{g} }}")
    _threshold_tree(o, "te_dg_lx_rb", STARTS, leaf)
    o("}")
    o("")


def group_flush(o):
    from gen_demographics import tree
    o("# THIS = a state, in te_demog_lx_group_flush while te_dg_um_sums: the age group local_var:te_dg_g's treated")
    o("# infection-and-chronic sums (people x rate at their biological age), by sex, into te_dg_uma_tic<f|m><group>; the")
    o("# running sums start again.")
    o("te_demog_um_group_flush = {")

    def leaf(o, g):
        for s in "fm":
            o(f"set_local_variable = {{ name = te_dg_uma_tic{s}{g} value = local_var:te_dg_um_gtic{s} }}")
    tree(o, "te_dg_g", 0, len(P.GROUPS) - 1, leaf)
    for s in "fm":
        o(f"set_local_variable = {{ name = te_dg_um_gtic{s} value = 0 }}")
    o("}")
    o("")


def sex_sums(o):
    o("# THIS = a state, in te_demog_um_step: the treated infection-and-chronic sums over every age group, women's and men's,")
    o("# into te_dg_um_sf and te_dg_um_sm (the uploads' split by sex).")
    o("te_demog_um_sex_sums = {")
    for s in "fm":
        o(f"set_local_variable = {{ name = te_dg_um_s{s} value = 0 }}")
        for g in range(len(P.GROUPS)):
            o(f"change_local_variable = {{ name = te_dg_um_s{s} add = local_var:te_dg_uma_tic{s}{g} }}")
    o("}")
    o("")


def l100(o):
    living = [(g, start, width) for g, (start, width) in enumerate(P.GROUPS) if start < P.LX_LIVING_TO]
    o("# THIS = a state, in te_demog_um_step after the late sweep (demographics_uploads.l100_counting): Living to 100 with an")
    o("# upload counting as living, the state's blended table (te_demog_lx_tables') with the treated's infection and chronic")
    o("# deaths x (1 - local te_dg_um_u, the share of them that uploaded); women's and men's averaged, into te_dg_um_l100.")
    o("te_demog_um_l100 = {")
    o("set_local_variable = { name = te_dg_um_lf value = 100000 }")
    o("set_local_variable = { name = te_dg_um_lm value = 100000 }")
    for g, _start, width in living:
        for s in "fm":
            u, t, tq, tic = (f"local_var:te_dg_lxa_u{s}{g}", f"local_var:te_dg_lxa_t{s}{g}",
                             f"local_var:te_dg_lxa_tq{s}{g}", f"local_var:te_dg_uma_tic{s}{g}")
            o(f"set_local_variable = {{ name = te_dg_um_q value = local_var:te_dg_lxu_q{s}{g} }}")
            o(f"set_local_variable = {{ name = te_dg_um_n value = {{ value = {u} add = {t} }} }}")
            o(f"if = {{ limit = {{ local_var:te_dg_um_n > 0 }} set_local_variable = {{ name = te_dg_um_q value = {{ "
              f"value = {u} multiply = local_var:te_dg_lxu_q{s}{g} add = {tq} subtract = {{ value = {tic} multiply = "
              f"local_var:te_dg_um_u }} divide = {{ value = local_var:te_dg_um_n min = 0.00001 }} }} }} }}")
            o("set_local_variable = { name = te_dg_um_p value = { value = 1 subtract = { value = local_var:te_dg_um_q "
              "divide = 100000 } } }")
            o("set_local_variable = { name = te_dg_um_pn value = 1 }")
            o(f"while = {{ count = {width} change_local_variable = {{ name = te_dg_um_pn multiply = local_var:te_dg_um_p }} }}")
            o(f"change_local_variable = {{ name = te_dg_um_l{s} multiply = local_var:te_dg_um_pn }}")
    o("set_variable = { name = te_dg_um_l100 value = { value = local_var:te_dg_um_lf add = local_var:te_dg_um_lm "
      "divide = 200000 } }")
    o("}")
    o("")


def render_um_effects():
    from gen_demographics import Out
    o = Out()
    o(HEADER.rstrip("\n"))
    o("")
    group_ic(o)
    ic_at(o)
    group_flush(o)
    sex_sums(o)
    l100(o)
    return o.text()


def render_um_values():
    from gen_demographics import Out
    o = Out()
    o(HEADER.rstrip("\n"))
    o("")
    o("# Constants uploaded minds' hand-written script reads (demographics_params.py, Uploaded minds).")
    k = {"per_level": P.UM_PER_LEVEL, "end_rate": P.UM_END_RATE, "keep_rate": 1 - P.UM_END_RATE,
         "research": P.UM_RESEARCH_PER_LEVEL, "politics": 1 if P.UM_POLITICS else 0,
         "devout_share": P.UM_DEVOUT_SHARE}
    for name, value in k.items():
        o(f"te_demog_k_um_{name} = {{ value = {_lit(value)} }}")
    o("")
    o("# The Nexus's factors under Full (te_demog_um_nexus_good: each good's line x utilisation x its factor).")
    for good, f in P.UM_OUTPUT_FACTORS.items():
        o(f"te_demog_k_um_out_{good} = {{ value = {_lit(f)} }}")
    for good, f in P.UM_INPUT_FACTORS.items():
        o(f"te_demog_k_um_in_{good} = {{ value = {_lit(f)} }}")
    o("")
    return o.text()


def plan_outputs():
    return {UM_EFFECTS: render_um_effects(), UM_VALUES: render_um_values()}
