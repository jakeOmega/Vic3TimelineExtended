def render_stage_check() -> list[str]:
    out = ["# Check if current colonization stage is complete and advance",
           "sr_check_colony_stage_effect = {"]
    for stage in range(1, 6):
        nxt = "All done" if stage == 5 else f"Stage {stage + 1}"
        out.append(f"\t# Stage {stage} complete → {nxt}")
        out.append("\tif = {" if stage == 1 else "\telse_if = {")
        out += ["\t\tlimit = {", f"\t\t\tglobal_var:sr_colonization_stage = {stage}"]
        out += [f"\t\t\thas_global_variable = sr_colony_{s.key}" for s in stage_sites(stage)]
        out.append("\t\t}")
        if stage == 5:
            out.append("\t\tset_global_variable = { name = sr_all_colonies_complete value = yes }")
        else:
            out.append(f"\t\tset_global_variable = {{ name = sr_colonization_stage value = {stage + 1} }}")
        out.append("\t}")
    out.append("}")
    return out


def render_effects() -> str:
    parts = [
        HEADER.rstrip("\n"),
        "# Solar System Colonization's per-world effects, from gen_solar_sites.SITES.",
        "",
        *render_draw(),
        "",
        *render_stage_check(),
    ]
    return "\n".join(parts) + "\n"


def plan_outputs(root: Path = ROOT) -> dict[Path, str]:
    return {EFFECTS_OUT: render_effects()}


def regenerate(mod_state=None, *, root: Path = ROOT, dry_run: bool = False) -> dict:
    """Post-load entry point (mod_state_server.POST_LOAD_REGENERATORS) and CLI body.

    Needs no mod state. Writes a file only when its content changed; script
    files get one UTF-8 BOM.
    """
    changed = []
    for relative, text in plan_outputs(root).items():
        target = root / relative
        expected = text.encode("utf-8-sig")
        if not target.exists() or target.read_bytes() != expected:
            changed.append(str(relative))
            if not dry_run:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)
    return {"changed": bool(changed), "changed_files": changed}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    args = parser.parse_args()
    result = regenerate(dry_run=args.dry_run or args.check)
    verb = "stale" if args.check else "would write" if args.dry_run else "wrote"
    for path in result["changed_files"]:
        print(f"{verb}: {path}")
    if not result["changed"]:
        print("solar sites: current")
    return int(args.check and result["changed"])


if __name__ == "__main__":
    raise SystemExit(main())
