"""Solar System Colonization's 34 worlds, from one table.

Every per-world block of the colony record is written from ``SITES`` below.
Design: ``docs/superpowers/specs/2026-10-25-solar-colonization-holders-and-cession-design.md``.

The global record is the truth: ``sr_site_holder_<key>`` (the holder, a
country), ``sr_site_spec_<key>`` (1 or 2, the specialization chosen in the
founding event), ``sr_site_region_<key>`` (the holder's capital state region),
``sr_site_mirror_<key>`` (the country whose variables show the site), and per
discovery ``sr_site_disc_<d>`` (1 or 2) and ``sr_site_disc_<d>_pending``. The
holder's ``<modifier>_held`` variables and its journal entry's modifiers are the
projection, written by ``sr_site_sync_<key>``.

Outputs:

- ``common/scripted_effects/sr_sites_generated.txt``: the founding draw and the
  stage check (``sr_launch_month`` calls the draw), and per world the sync,
  mirror, release, transfer and monthly step; the choice dispatcher
  (``sr_site_choose_<modifier>``, called by ``sr_grant_colony_modifier``); the
  migration, the revolution repoint, the panel snapshot, Cede Colony's apply and
  the console's helpers.
- ``common/scripted_triggers/sr_sites_generated.txt``: Cede Colony's input filter
  and ``sr_any_site_unclaimed``.
- ``common/script_values/sr_sites_generated.txt``: ``sr_sites_held_count`` and the
  AI's value of a ceded world.
- ``common/script_values/sr_sites_display_generated.txt``: the panel's
  ``sr_disp_site_<key>``, read by the GUI only.
- ``common/buildings/sr_site_buildings_generated.txt``: one hidden building type
  per world, which only names it in the treaty designer.
- ``common/customizable_localization/sr_sites_generated_custom_loc.txt``: a
  world's name from its index, for the notices.

The table is the script's own: each world's stage, launch-window body
(``gen_launch_windows.BODIES``; Mercury has none), founding event
(``space_race_colony_events.N``), the two specializations its event offers in
option order, and the discoveries its founding seeds. ``test_solar_sites.py``
re-derives all of them from the events and the launch windows and fails when the
table and the script disagree.

Run ``python3 scripts/generators/gen_solar_sites.py [--dry-run | --check]``.
A post-load regenerator (``mod_state_server.POST_LOAD_REGENERATORS``).
"""

