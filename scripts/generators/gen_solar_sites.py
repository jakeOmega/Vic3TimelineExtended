def spec_modifiers(site: Site) -> tuple[str, str]:
    prefix = SPEC_PREFIX.get(site.key, site.key)
    a, b = (f"sr_colony_{prefix}_{suffix}" for suffix in site.specs)
    return a, b


def discovery_modifiers(discovery: str) -> tuple[str, str]:
    return f"sr_discovery_{discovery}_a", f"sr_discovery_{discovery}_b"


def stage_sites(stage: int) -> list[Site]:
    return [s for s in SITES if s.stage == stage]


def site_building(site: Site) -> str:
    return f"building_sr_site_{site.key}"


def panel_order() -> list[Site]:
    return [s for loc in LOCATIONS for s in SITES if s.location == loc]


def choices() -> list[tuple[str, Site, str, int]]:
    """Every modifier sr_grant_colony_modifier receives: (modifier, site, kind, option)."""
    out = []
    for site in SITES:
        for option, modifier in enumerate(spec_modifiers(site), start=1):
            out.append((modifier, site, "spec", option))
        for discovery in site.discoveries:
            for option, modifier in enumerate(discovery_modifiers(discovery), start=1):
                out.append((modifier, site, discovery, option))
    return out


