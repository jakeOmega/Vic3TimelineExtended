def _mirror_on(site: Site) -> list[str]:
    a, b = spec_modifiers(site)
    k = site.key
    out = [f"sr_site_mirror_on_{k} = {{",
           "\tif = {",
           f"\t\tlimit = {{ has_global_variable = sr_site_spec_{k} global_var:sr_site_spec_{k} = 1 }}",
           f"\t\tsr_site_show_modifier = {{ MODIFIER = {a} }}",
           f"\t\tsr_site_hide_modifier = {{ MODIFIER = {b} }}",
           "\t}",
           "\telse_if = {",
           f"\t\tlimit = {{ has_global_variable = sr_site_spec_{k} global_var:sr_site_spec_{k} = 2 }}",
           f"\t\tsr_site_show_modifier = {{ MODIFIER = {b} }}",
           f"\t\tsr_site_hide_modifier = {{ MODIFIER = {a} }}",
           "\t}"]
    for d in site.discoveries:
        da, db = discovery_modifiers(d)
        out += ["\tif = {",
                f"\t\tlimit = {{ has_global_variable = sr_site_disc_{d} global_var:sr_site_disc_{d} = 1 }}",
                f"\t\tsr_site_show_modifier = {{ MODIFIER = {da} }}",
                f"\t\tsr_site_hide_modifier = {{ MODIFIER = {db} }}",
                f"\t\tsr_site_set_discovery_done = {{ DISCOVERY = {d} }}",
                "\t}",
                "\telse_if = {",
                f"\t\tlimit = {{ has_global_variable = sr_site_disc_{d} global_var:sr_site_disc_{d} = 2 }}",
                f"\t\tsr_site_show_modifier = {{ MODIFIER = {db} }}",
                f"\t\tsr_site_hide_modifier = {{ MODIFIER = {da} }}",
                f"\t\tsr_site_set_discovery_done = {{ DISCOVERY = {d} }}",
                "\t}",
                "\telse_if = {",
                f"\t\tlimit = {{ has_global_variable = sr_site_disc_{d}_pending }}",
                f"\t\tsr_site_set_discovery_pending = {{ DISCOVERY = {d} }}",
                "\t}"]
    out += ["\tset_variable = { name = sr_colony_count value = sr_sites_held_count }", "}"]
    return out


def _unmirror(site: Site) -> list[str]:
    a, b = spec_modifiers(site)
    out = [f"sr_site_unmirror_{site.key} = {{",
           f"\tsr_site_hide_modifier = {{ MODIFIER = {a} }}",
           f"\tsr_site_hide_modifier = {{ MODIFIER = {b} }}"]
    for d in site.discoveries:
        da, db = discovery_modifiers(d)
        out += [f"\tsr_site_hide_modifier = {{ MODIFIER = {da} }}",
                f"\tsr_site_hide_modifier = {{ MODIFIER = {db} }}",
                f"\tsr_site_clear_discovery = {{ DISCOVERY = {d} }}"]
    out += ["\tset_variable = { name = sr_colony_count value = sr_sites_held_count }", "}"]
    return out


