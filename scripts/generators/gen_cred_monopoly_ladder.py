"""Generate the Creditors' Consortium's monopoly ladder: company type -> its building types.

A rescue's concessions term (te_cred_demand_monopolies,
common/scripted_effects/te_creditors_consortium_effects.txt) demands monopolies
for the leader's companies in the member: vanilla's acquire_monopoly_for_company
article, which needs a company and a building type as inputs. Script cannot
read a company's building types (there is no iterator or trigger for them;
only is_company_type and company_has_building_type_monopoly), so this writes
the ladder that knows them:

* common/scripted_effects/te_cred_monopoly_ladder_generated.txt:
  te_cred_monopoly_ladder_generated, in the member's scope with
  scope:te_cred_mono_company set, one branch per company type, each calling
  te_cred_try_monopoly = { BT = <building type> } for every building type in
  the type's ``building_types`` (not its extension types, which a company
  builds only once it has grown into them), in the order the type lists them.
* common/scripted_triggers/te_cred_monopoly_ladder_generated.txt:
  te_cred_company_can_take_monopoly_generated, in a company's scope with
  scope:te_cc_debtor set: does the member have a building of one of this
  company's types? The concessions term asks it (te_cred_term_concessions_available)
  so it is not offered where Foreign Investment Rights already stand and no
  monopoly could be made.

Inputs: company types (vanilla snapshot + common/company_types/). Run
``python3 scripts/generators/gen_cred_monopoly_ladder.py [--dry-run | --check]``.
No game install or running server is needed. Not run on /reload;
test_creditors_consortium.py fails CI when the committed file is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

OUT = Path("common/scripted_effects/te_cred_monopoly_ladder_generated.txt")
OUT_TRIGGER = Path("common/scripted_triggers/te_cred_monopoly_ladder_generated.txt")
ENTITY_TYPE = "Company Types"

HEADER = "# AUTO-GENERATED by scripts/generators/gen_cred_monopoly_ladder.py - do not edit manually.\n"

PREAMBLE = """\
# Scope: the member in a Creditors' Consortium rescue; scope:te_cred_mono_company
# a company of its consortium's leader (scope:te_cc_creditor). One branch per
# company type, trying each of the type's building types in turn
# (te_cred_try_monopoly, te_creditors_consortium_effects.txt), which demands the
# monopoly where the member has such a building and the count is not spent.
"""


def load_state(root: Path = ROOT):
    """Company types: vanilla from the committed snapshot, the mod's from disk."""
    from mod_state import VANILLA_COMMON_DIRS, ModState
    from vanilla_parsed import load

    snapshot = load(str(root / "vanilla_parsed"))
    state = ModState(
        {ENTITY_TYPE: "/nonexistent"},
        {ENTITY_TYPE: str(root / "common" / VANILLA_COMMON_DIRS[ENTITY_TYPE])},
        vanilla_data=snapshot.data,
    )
    if state.parse_failures:
        raise ValueError(f"Cannot generate the monopoly ladder from an incomplete parse: {state.parse_failures}")
    return state


def _unwrap(v):
    if isinstance(v, (list, tuple)) and len(v) == 2 and isinstance(v[0], str):
        return v[1]
    return v


def _names(v) -> list[str]:
    out: list[str] = []

    def walk(x):
        x = _unwrap(x)
        if isinstance(x, str):
            out.append(x)
        elif isinstance(x, (list, tuple)):
            for y in x:
                walk(y)

    walk(v)
    return out


def ladder_rows(company_types: dict) -> list[tuple[str, list[str]]]:
    """(company type, its building types) for every type with at least one, by name."""
    rows = []
    for name in sorted(company_types):
        body = _unwrap(company_types[name])
        if not isinstance(body, dict):
            continue
        buildings = []
        for b in _names(body.get("building_types")):
            if b.startswith("building_") and b not in buildings:
                buildings.append(b)
        if buildings:
            rows.append((name, buildings))
    return rows


def render(rows) -> str:
    branches = []
    for i, (company, buildings) in enumerate(rows):
        keyword = "if" if i == 0 else "else_if"
        tries = "".join(f"\t\tte_cred_try_monopoly = {{ BT = {b} }}\n" for b in buildings)
        branches.append(
            f"\t{keyword} = {{\n"
            f"\t\tlimit = {{ scope:te_cred_mono_company = {{ is_company_type = company_type:{company} }} }}\n"
            f"{tries}"
            "\t}\n"
        )
    return HEADER + PREAMBLE + "\nte_cred_monopoly_ladder_generated = {\n" + "".join(branches) + "}\n"


TRIGGER_PREAMBLE = """\
# Scope: a company of a Creditors' Consortium's leader; scope:te_cc_debtor the
# member being rescued. Does the member have a building of one of this
# company's types, so a monopoly could be demanded for it
# (te_cred_term_concessions_available, te_creditors_consortium_triggers.txt)?
# The treaty's own gates (can_ratify, the once-per-inputs limit) are asked when
# the monopoly is made (te_cred_try_monopoly).
"""


def render_trigger(rows) -> str:
    branches = []
    for company, buildings in rows:
        types = "".join(f"\t\t\t\t\tis_building_type = {b}\n" for b in buildings)
        branches.append(
            "\t\tAND = {\n"
            f"\t\t\tis_company_type = company_type:{company}\n"
            "\t\t\tscope:te_cc_debtor = {\n"
            "\t\t\t\tany_scope_building = {\n"
            "\t\t\t\t\tOR = {\n"
            f"{types.replace(chr(9) * 5, chr(9) * 6)}"
            "\t\t\t\t\t}\n"
            "\t\t\t\t}\n"
            "\t\t\t}\n"
            "\t\t}\n"
        )
    return (HEADER + TRIGGER_PREAMBLE + "\nte_cred_company_can_take_monopoly_generated = {\n\tOR = {\n"
            + "".join(branches) + "\t}\n}\n")


def plan_outputs(root: Path = ROOT) -> dict:
    state = load_state(root)
    rows = ladder_rows(state.get_data(ENTITY_TYPE) or {})
    return {OUT: render(rows), OUT_TRIGGER: render_trigger(rows)}


def plan_output(root: Path = ROOT) -> str:
    return plan_outputs(root)[OUT]


def regenerate(*, root: Path = ROOT, dry_run: bool = False) -> dict:
    """Write the ladder and its trigger where their content changed, each with one UTF-8 BOM."""
    changed_files = []
    for rel, text in plan_outputs(root).items():
        expected = text.encode("utf-8-sig")
        target = root / rel
        if not target.exists() or target.read_bytes() != expected:
            changed_files.append(str(rel))
            if not dry_run:
                target.write_bytes(expected)
    return {"changed": bool(changed_files), "changed_files": changed_files}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if the output is stale")
    args = parser.parse_args(argv)
    result = regenerate(dry_run=args.dry_run or args.check)
    verb = "stale" if args.check else "would write" if args.dry_run else "wrote"
    for path in result["changed_files"]:
        print(f"{verb}: {path}")
    if not result["changed"]:
        print("monopoly ladder: current")
    return int(args.check and result["changed"])


if __name__ == "__main__":
    raise SystemExit(main())
