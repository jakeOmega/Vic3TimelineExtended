ROW_WIDTH = 3
COMMENT_WIDTH = 118


def _comment(text: str, mark: str = "#", indent: str = "") -> list[str]:
    """text as comment lines of at most COMMENT_WIDTH characters, counting the indent's tabs as four."""
    width = COMMENT_WIDTH - 4 * indent.count("\t") - len(mark) - 1
    return [f"{mark} {line}" for line in textwrap.wrap(text, width)]


def by_key() -> dict[str, dict]:
    return {m["key"]: m for m in MAPS}


def expand(slot: str) -> list[str]:
    """The maps a row's place holds: itself, or a class's two picks (SLOTS)."""
    return SLOTS.get(slot, [slot])


def row_maps(row: list[str]) -> list[str]:
    return [k for s in row for k in expand(s)]


def validate() -> None:
    """Every map in exactly one group's row, every selector one map's, no row too wide."""
    classes.validate()
    keys = [m["key"] for m in MAPS]
    sels = [m["sel"] for m in MAPS]
    if len(set(keys)) != len(keys) or len(set(sels)) != len(sels):
        raise ValueError("a map key or a selector is listed twice")
    placed = [k for g in GROUPS for row in g["rows"] for k in row_maps(row)]
    if sorted(placed) != sorted(keys):
        missing = sorted(set(keys) - set(placed))
        extra = sorted(set(placed) - set(keys))
        twice = sorted({k for k in placed if placed.count(k) > 1})
        raise ValueError(f"groups don't place every map once: missing {missing}, unknown {extra}, twice {twice}")
    for g in GROUPS:
        for row in g["rows"]:
            if not 1 <= len(row) <= ROW_WIDTH:
                raise ValueError(f"{g['key']}: a row of {len(row)}")


def group_gates(group: dict) -> list[str] | None:
    """The distinct gates of a group whose every map is gated, in order; None when a map shows to every player."""
    maps = by_key()
    gates = [maps[k].get("gate") for row in group["rows"] for k in row_maps(row)]
    if any(g is None for g in gates):
        return None
    return list(dict.fromkeys(gates))


def row_gate(row: list[str]) -> str | None:
    """The one gate every map of a row shares, or None."""
    maps = by_key()
    gates = {maps[k].get("gate") for k in row_maps(row)}
    return gates.pop() if len(gates) == 1 else None


def _shown_lines(m: dict) -> list[str]:
    """What a pick's is_shown asks besides a player: its gate, and a class map's switch setting."""
    lines = [m["gate"]] if m.get("gate") else []
    if "mode" in m:
        lines.append(f"te_jmap_class_mode = {m['mode']}")
    return lines


def _is_shown(gate_lines: list[str]) -> list[str]:
    if not gate_lines:
        return ["\tis_shown = { is_player = yes }"]
    return ["\tis_shown = {", "\t\tis_player = yes", *[f"\t\t{line}" for line in gate_lines], "\t}"]


def render_sguis() -> str:
    maps = by_key()
    out = [
        HEADER,
        "# The Map Room's picks (docs/systems/mod_systems/journal_map_modes.md), called from the page's rows",
        "# (te_jmap_pick_row, te_map_room_picks_generated.gui), from the Demographics tab's map button and from each",
        "# system's tab (te_map_widgets.gui). The AI never uses these: the map is a player's view. Scripted GUIs, not the",
        "# entry's scripted buttons: the Map Room is contextless with nobody involved, and the engine locks a scripted button",
        "# for a country not involved in its entry (play-test check 14, 2026-11-05).",
        "#",
        "# is_valid is false on the current pick, which the button draws pressed. is_shown hides a census map while the",
        "# census doesn't run (te_demog_cohorts_run) and a system's map while its rule is off; a class has two, its people",
        "# and its share, of which Map Options' Count/Share switch shows one (te_jmap_class_mode). A pick also notes the player",
        "# as the maps' viewer (te_jmap_set_selector), for the maps drawn for \"your\" country. Selector numbers:",
        "# te_journal_map_values.txt. The options' scripted GUIs are hand-written: te_journal_map_sguis.txt.",
        "",
    ]
    for group in GROUPS:
        out += _comment(f"{group['name']}: {group['note']}.") + [""]
        for row in group["rows"]:
            for key in row_maps(row):
                m = maps[key]
                out += [
                    f"te_jmap_pick_{key}_sgui = {{",
                    "\tscope = country",
                    *_is_shown(_shown_lines(m)),
                    "\tai_is_valid = { always = no }",
                    f"\tis_valid = {{ NOT = {{ te_jmap_selector = {m['sel']} }} }}",
                    "\teffect = {",
                    f"\t\tte_jmap_set_selector = {{ SEL = {m['sel']} }}",
                    "\t}",
                    "}",
                    "",
                ]
    gated = [g["name"] for g in GROUPS if group_gates(g) is not None]
    out += _comment("A group whose every map is gated shows its header while any of them is shown (the page's "
                    f"te_jmap_pick_row): {', '.join(gated)}.") + [""]
    for group in GROUPS:
        gates = group_gates(group)
        if gates is None:
            continue
        lines = gates if len(gates) == 1 else ["OR = {", *[f"\t{g}" for g in gates], "}"]
        out += [
            f"te_jmap_cat_{group['key']}_sgui = {{",
            "\tscope = country",
            *_is_shown(lines),
            "\tai_is_valid = { always = no }",
            "\tis_valid = { always = no }",
            "\teffect = { }",
            "}",
            "",
        ]
    return "\n".join(out).rstrip("\n") + "\n"


def _shown(sgui: str) -> str:
    return f"GetScriptedGui('{sgui}').IsShown( GuiScope.SetRoot( GetPlayer.MakeScope ).End )"


def _button(key: str) -> list[str]:
    sgui = f"te_jmap_pick_{key}_sgui"
    scope = "GuiScope.SetRoot( GetPlayer.MakeScope ).End"
    return [
        "te_jmap_pick_button = {",
        f"\ttext = \"te_jmap_pick_{key}\"",
        f"\ttooltip = \"te_jmap_pick_{key}_desc\"",
        f"\tvisible = \"[{_shown(sgui)}]\"",
        f"\tdown = \"[Not( GetScriptedGui('{sgui}').IsValid( {scope} ) )]\"",
        f"\tonclick = \"[GetScriptedGui('{sgui}').Execute( {scope} )]\"",
        "\tonclick = \"[PdxGuiTriggerAllAnimations('te_jmap_repaint')]\"",
        "}",
    ]


def _indent(lines: list[str], n: int) -> list[str]:
    return [("\t" * n + line) if line else "" for line in lines]


def _group(group: dict) -> list[str]:
    key = group["key"]
    flag = f"te_jmap_cat_{key}_open"
    gated = group_gates(group) is not None
    open_now = f"GetVariableSystem.Exists('{flag}')"
    out = _comment(f"{group['name']}: {group['note']}.", indent="\t\t") + ["te_jmap_category_header = {"]
    if gated:
        out.append(f"\tvisible = \"[{_shown(f'te_jmap_cat_{key}_sgui')}]\"")
    out += [
        "\tblockoverride \"left_text\" {",
        f"\t\ttext = \"te_jmap_cat_{key}\"",
        "\t}",
    ]
    if group.get("right"):
        out += [
            "\tblockoverride \"right_text\" {",
            "\t\tsection_header_right_text = {",
            f"\t\t\ttext = \"{group['right']}\"",
            "\t\t}",
            "\t}",
        ]
    out += [
        "\tblockoverride \"onclick\" {",
        f"\t\tonclick = \"[GetVariableSystem.Toggle('{flag}')]\"",
        "\t}",
        "\tblockoverride \"onclick_showmore\" {",
        f"\t\tvisible = \"[Not({open_now})]\"",
        "\t}",
        "\tblockoverride \"onclick_showless\" {",
        f"\t\tvisible = \"[{open_now}]\"",
        "\t}",
        "}",
        "te_jmap_category = {",
    ]
    if gated:
        out.append(f"\tvisible = \"[And( {open_now}, {_shown(f'te_jmap_cat_{key}_sgui')} )]\"")
    else:
        out.append(f"\tvisible = \"[{open_now}]\"")
    for row in group["rows"]:
        gate = row_gate(row)
        out += ["", "\tflowcontainer = {"]
        if gate is not None:
            out.append(f"\t\tvisible = \"[{_shown(f'te_jmap_pick_{row_maps(row)[0]}_sgui')}]\"")
        out += [
            "\t\tdirection = horizontal",
            "\t\tparentanchor = hcenter",
            "\t\tignoreinvisible = yes",
            "\t\tspacing = 4",
        ]
        for key_ in row_maps(row):
            out += [""] + _indent(_button(key_), 2)
        out.append("\t}")
    out.append("}")
    return out


def render_gui() -> str:
    body = [
        "### The Map Room's picks, one per map (te_journal_map_picks_generated.txt), in groups by theme (owner,",
        "### 2026-11-23), each a collapsible section: a header (te_jmap_category_header, te_map_widgets.gui) and its rows,",
        "### shown while the group's client-side flag te_jmap_cat_<key>_open is set. Every group starts collapsed (a long",
        "### list: gui_style_guide.md, Sections), and the flags outlive a pick's reopen (the GetVariableSystem's, as the",
        "### see-through page's), so a group opened stays open from map to map. A button is pressed while it is the pick and",
        "### hidden while its map can't be drawn (a census map while the census doesn't run, a system's map while its rule",
        "### is off). A group whose every map is gated hides with them, header and all (te_jmap_cat_<key>_sgui), and a row",
        "### whose maps share a gate hides with it. Three 150-wide buttons to a row fit the page.",
        "type te_jmap_pick_row = flowcontainer {",
        "\tdirection = vertical",
        "\tparentanchor = hcenter",
        "\tignoreinvisible = yes",
        "\tspacing = 4",
    ]
    for group in GROUPS:
        body += [""] + _indent(_group(group), 1)
    body.append("}")
    return (
        HEADER
        + "### The Map Room's page (te_map_room_widget.gui) mounts te_jmap_pick_row above its options. Edit MAPS and GROUPS\n"
        "### in the generator, not this file.\n"
        "types te_map_room_picks_generated\n"
        "{\n"
        + "\n".join(_indent(body, 1))
        + "\n}\n"
    )


def outputs(root: Path = ROOT) -> dict[Path, bytes]:
    validate()
    return {
        root / SGUI_FILE: render_sguis().encode("utf-8-sig"),
        root / GUI_FILE: render_gui().encode("utf-8-sig"),
    }


def main(argv: list[str]) -> int:
    data = outputs()
    drifted = [path for path, body in data.items() if not path.is_file() or path.read_bytes() != body]
    if "--check" in argv:
        for path in drifted:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if drifted else 0
    for path, body in data.items():
        path.write_bytes(body)
    print(f"wrote {len(data)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
