"""Restate every vanilla party's join_weight with the First Past the Post terms.

Writes common/parties/zz_te_party_join_weights.txt: one
``INJECT:<party> = { join_weight = { ... } }`` per vanilla party. An injected
join_weight replaces vanilla's whole field rather than adding to it (read in
game 2026-10-25; docs/guides/scripting_best_practices.md), so each block
restates vanilla's lines, read from the game files, with the amendment's two
terms added (restate: a bonus for the two largest parties in place of
vanilla's party-size multipliers, a penalty for the rest at the end). Three
changes to vanilla's lines:

* the ``usa_two_party_system`` terms are left out: the amendment replaces
  vanilla's culture-based American two-party system, and the countries that
  term covered start with the amendment instead (te_fptp_effects.txt);
* the revolutionary party is skipped: it exists only for a revolution and is
  never ranked;
* the `if` that opens the size chain becomes an `else_if`, continuing the
  major party's bonus, so one of the two largest parties skips the chain.

The mod's own parties (green, populist, technocratic) carry the same terms in
their own files. Design: docs/superpowers/specs/2026-10-25-first-past-the-post-design.md.

Run ``python3 scripts/generators/gen_party_join_weights.py [--check]`` on a
machine with the game; ``--check`` writes nothing and exits 1 when the
committed file is stale. Not run on /reload. The header records the game
version the lines came from; test_first_past_the_post.py fails when it differs
from the committed vanilla snapshot's (vanilla_parsed/manifest.json), so a
vanilla patch forces a rerun. The same test holds the restated lines to the
snapshot's parties (vanilla_parsed/common/parties.json, #1164) in values,
descs, lines dropped or added, and order within one key. The snapshot keeps no
order across keys, so a restated `else_if` moved under another `if`, or a step
moved past a term of another key, passes CI: only --check (or the test's
game-files comparison, which skips without the game) catches it.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import path_constants  # noqa: E402
import vanilla_parsed  # noqa: E402
from ig_feminism import _code, _indent, _masked, field_lines  # noqa: E402

OUTPUT_RELPATH = os.path.join("common", "parties", "zz_te_party_join_weights.txt")

# Vanilla parties the generator leaves alone.
SKIPPED_PARTIES = frozenset({"revolutionary_party"})

# The desc of each vanilla term the generated copies leave out.
DROPPED_TERM_DESCS = ("usa_two_party_system",)

# The desc that marks vanilla's party-size multiplier chain near the end of
# every vanilla join_weight (x2 with at most one prior member when the group
# isn't powerful, x0.5 with two, x0 with three or more); the major party's
# bonus goes just ahead of the chain's opening `if`, which becomes an else_if.
SIZE_CHAIN_DESC = "from_two_prior_members"

HEADER = """# AUTO-GENERATED by scripts/generators/gen_party_join_weights.py - Do not edit manually
# Restated from vanilla {version}.
#
# Each join_weight restates vanilla's lines, then adds the First Past the Post
# terms. An injected join_weight replaces vanilla's whole field, so leaving
# vanilla's lines out would drop them. Vanilla's usa_two_party_system terms are
# left out: amendment_first_past_the_post replaces them. The zz_ prefix sorts
# this file after the vanilla files it injects into.
"""


def party_key(text):
    """The party a vanilla file defines (its first top-level key)."""
    match = re.search(r"^(\w+_party)\s*=\s*\{", _masked(text), flags=re.MULTILINE)
    if not match:
        raise ValueError("no party defined")
    return match.group(1)


def top_level_chunks(lines):
    """`lines` (a field's stripped lines) grouped into its top-level entries: a
    block with every line inside it, or a single line (a comment, a bare key)."""
    chunks = []
    block = []
    depth = 0
    for line in lines:
        code = _code(line)
        if depth == 0 and not block and "{" not in code:
            chunks.append([line])
            continue
        block.append(line)
        depth += code.count("{") - code.count("}")
        if depth == 0:
            chunks.append(block)
            block = []
    if block:
        raise ValueError("unbalanced braces in the field")
    return chunks


def _names_desc(chunk, desc):
    return re.search(rf'desc\s*=\s*"?{re.escape(desc)}"?(\s|$|\}})', "\n".join(chunk)) is not None


def restate(lines, key, descs=DROPPED_TERM_DESCS):
    """Vanilla's join_weight lines without the `descs` terms, with the major
    party's bonus in place of vanilla's party-size multipliers and the other
    parties' penalty at the end.

    Near the end of every vanilla join_weight, a chain multiplies by 2 when at
    most one group would join first (and the group isn't powerful), by 0.5 when
    two would and by 0 when three or more would (SIZE_CHAIN_DESC). It caps a
    party at three groups, so with eight interest groups two majors left at
    least two groups in no party (2026-11-01). So the bonus opens an if chain
    and the size chain's opening `if` becomes an else_if: a major party skips
    the multipliers and takes the bonus, less a little for each group joining
    first, so it never fills up and a group's fit still picks between the two.
    The bonus can't simply follow the chain: x0 also wipes out a group's
    strong dislike of a party (vanilla's -100 slaver and abolitionist terms),
    so a bonus after it would carry that group into a full party it opposes.
    The penalty comes after every multiplier, so it is the full size whatever
    the group's other terms.

    Both edits respect if/else_if chains: a dropped term must stand alone, and
    the bonus goes ahead of the `if` that opens the size chain (in some parties
    the chain opens with another multiplier and the size step is an else_if)."""
    chunks = top_level_chunks(lines)
    kept = []
    for i, chunk in enumerate(chunks):
        if any(_names_desc(chunk, d) for d in descs):
            following = chunks[i + 1][0] if i + 1 < len(chunks) else ""
            if _opens_branch(chunk[0]) or _opens_branch(following):
                raise ValueError(f"a dropped term is part of an if/else_if chain: {chunk[0]}")
            continue
        kept.append(chunk)
    sizes = [i for i, chunk in enumerate(kept) if _names_desc(chunk, SIZE_CHAIN_DESC)]
    if len(sizes) != 1:
        raise ValueError(f"expected one {SIZE_CHAIN_DESC} block, found {len(sizes)}")
    head = sizes[0]
    while head > 0 and _opens_branch(kept[head][0]):
        head -= 1
    if not re.match(r"if\s*=", _code(kept[head][0]).strip()):
        raise ValueError(f"the size chain doesn't open with an if: {kept[head][0]}")
    kept[head] = [re.sub(r"^(\s*)if(\s*=)", r"\1else_if\2", kept[head][0], count=1), *kept[head][1:]]
    kept.insert(head, major_term_lines(key))
    kept.append(minor_term_lines(key))
    return [line for chunk in kept for line in chunk]


def _opens_branch(line):
    """True for a line that continues an if chain (else_if, else)."""
    return re.match(r"(else_if|else)\s*=", _code(line).strip()) is not None


def _in_force_lines(major_test):
    return [
        "limit = {",
        "owner = {",
        "te_fptp_in_force = yes",
        "has_variable = te_fptp_two_majors",
        major_test,
        "}",
        "}",
    ]


def major_term_lines(key):
    """The bonus for party `key` while it is one of the two largest, unindented.
    It opens the if chain that the party-size multipliers continue as
    else_ifs (restate). Its second step reads scope:number as a value, which
    vanilla only compares; if that doesn't read, the step adds nothing and the
    two majors still take every group that fits them
    (docs/testing/first-past-the-post-playtest.md)."""
    return [
        "# First Past the Post (amendment_first_past_the_post): one of the two",
        "# largest parties, as te_fptp_effects.txt ranks them monthly. In place",
        "# of the party-size multipliers (the else_ifs below), so a major party",
        "# never fills up: each group joining first takes a little off instead.",
        "if = {",
        *_in_force_lines(f"has_variable = te_fptp_major_{key}"),
        "add = {",
        "value = te_fptp_major_party_join_weight",
        'desc = "te_fptp_major_party_join"',
        "}",
        "if = {",
        "limit = { scope:number > 0 }",
        "add = {",
        "value = scope:number",
        "multiply = te_fptp_major_party_crowding_weight",
        'desc = "te_fptp_major_party_crowding"',
        "}",
        "}",
        "}",
    ]


def minor_term_lines(key):
    """The penalty for party `key` while it is not one of the two largest, unindented."""
    return [
        "# First Past the Post: any party but the two largest.",
        "if = {",
        *_in_force_lines(f"NOT = {{ has_variable = te_fptp_major_{key} }}"),
        "add = {",
        "value = te_fptp_minor_party_join_weight",
        'desc = "te_fptp_minor_party_join"',
        "}",
        "}",
    ]


def unrestate(lines, key):
    """The inverse of restate's insertions, not of its drops: `lines` (a
    restated join_weight, stripped) without party `key`'s two terms, and with
    the size chain's head back to vanilla's `if`. The tests rebuild vanilla's
    lines from the committed file with it. Raises when a term is missing or
    altered, or the line after the bonus isn't the size chain's else_if."""
    out = list(lines)
    major = major_term_lines(key)
    for term in (major, minor_term_lines(key)):
        at = next((i for i in range(len(out)) if out[i : i + len(term)] == term), None)
        if at is None:
            raise ValueError(f"{key}: a First Past the Post term is missing or altered: {term[-6:]}")
        del out[at : at + len(term)]
        if term is major:
            if at >= len(out) or not re.match(r"else_if\s*=", _code(out[at]).strip()):
                raise ValueError(f"{key}: the bonus isn't followed by the size chain's else_if")
            out[at] = re.sub(r"^(\s*)else_if(\s*=)", r"\1if\2", out[at], count=1)
    return out


def build_inject(vanilla_text):
    """One INJECT block restating the party's join_weight with the terms."""
    key = party_key(vanilla_text)
    body = restate(field_lines(vanilla_text, "join_weight"), key)
    lines = [f"INJECT:{key} = {{"]
    lines += _indent(["join_weight = {", *body, "}"], 1)
    lines.append("}")
    return "\n".join(lines)


def vanilla_party_files(input_dir):
    """The vanilla party files the generator restates, in name order."""
    names = []
    for filename in sorted(os.listdir(input_dir)):
        if not filename.endswith(".txt"):
            continue
        with open(os.path.join(input_dir, filename), encoding="utf-8-sig") as file:
            text = file.read()
        if party_key(text) not in SKIPPED_PARTIES:
            names.append(filename)
    return names


def build_file(input_dir, version):
    """The whole generated file, from the vanilla party files in `input_dir`
    of game version `version`."""
    blocks = []
    for filename in vanilla_party_files(input_dir):
        with open(os.path.join(input_dir, filename), encoding="utf-8-sig") as file:
            blocks.append(build_inject(file.read()))
    return HEADER.format(version=version) + "\n" + "\n\n".join(blocks) + "\n"


def vanilla_parties_dir():
    return os.path.join(path_constants.base_game_path, "game", "common", "parties")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    args = parser.parse_args(argv)
    version = vanilla_parsed.live_game_version(path_constants.base_game_path)
    if version is None:
        print("No game version found (launcher/launcher-settings.json); is the game installed?")
        return 1
    text = build_file(vanilla_parties_dir(), version)
    output = ROOT / OUTPUT_RELPATH
    if args.check:
        current = output.read_text(encoding="utf-8-sig") if output.exists() else None
        if current != text:
            print(f"{OUTPUT_RELPATH} is stale: run scripts/generators/gen_party_join_weights.py")
            return 1
        print(f"{OUTPUT_RELPATH} is current.")
        return 0
    # `utf-8-sig` writes the one leading BOM the engine expects.
    with open(output, "w", encoding="utf-8-sig", newline="\n") as file:
        file.write(text)
    print(f"Wrote {OUTPUT_RELPATH}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
