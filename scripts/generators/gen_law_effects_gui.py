"""Vanilla's law tooltips and change-law panel, with a taxation law's effects
text behind a hover.

For a law in lawgroup_taxation, LawType.GetEffectDesc lists the law's effects at
each of the five tax levels with the revenue each would raise, and the engine
prices the whole country's taxes for every level each time it builds that text.
Vanilla builds it three times a frame wherever a law's effects show (two
`visible` checks and the text itself): in the law tooltip
(custom_tooltip.gui's FancyTooltip_Law, and FancyTooltip_LawWithCountryContext
for another country's law) and twice in the change-law panel
(politics_panel_change_law.gui). Late in a game that held the frame rate near
4 fps while a tax law was hovered or open. The script profiler doesn't see it:
the cost is engine code inside the data function.

So at each of those four sites, vanilla's two widgets (the Effects header and
the text) go in a container hidden for a taxation law, and a taxation law shows
the header and one line instead, whose nested tooltip holds the text. The engine
builds a nested tooltip's text only while the player hovers it. Since 1.15 the
selected law in the change-law panel also has an All effects / Comparative
effects toggle, whose `visible` builds the text too, and a comparison with the
current law (GetDeltaEffectDesc), which prices the taxes at the current level:
there the toggle and the comparison go in the container as well (a vbox there, since
the toggle is an hbox and a flowcontainer can't hold one), and a taxation
law shows the toggle and the two headers with a line each
(te_law_tax_delta_effects for the comparison). Both facts were
checked in game on 2026-10-18 (scripting_best_practices.md, "Script
Performance"). Other laws keep vanilla's text. The line's loc is
te_law_tax_effects (te_law_tax_effects_country with another country's law).

Run after a vanilla patch, with both fixtures replaced by the new vanilla files
(test_fixtures/vanilla_gui/custom_tooltip.gui, politics_panel_change_law.gui):
    python3 scripts/generators/gen_law_effects_gui.py
It writes gui/00_te_law_effects.gui; never hand-edit it. The four types are
redefined from that file, and the mod's definition wins (gui_modding_guide.md
gotcha #30). Every change is in a `### MOD: Tax law effects` block, and the
vanilla lines between the blocks are vanilla's, re-indented.
"""
from __future__ import annotations

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "test_fixtures" / "vanilla_gui"
OUT = ROOT / "gui" / "00_te_law_effects.gui"

MOD_OPEN = "### MOD: Tax law effects"
MOD_CLOSE = "### END MOD ###"
HEADER = "AUTO-GENERATED by scripts/generators/gen_law_effects_gui.py; do not edit manually."

IS_TAX = "EqualTo_string(Law.GetGroup.GetKey, 'lawgroup_taxation')"

# (fixture, the types redefined from it, as (type, the country vanilla gives
# GetEffectDesc, the key of the line that replaces the text, the key of the line
# that replaces the comparison's text or None for a type without one))
SOURCES = (
    ("custom_tooltip.gui", "te_law_effects_tooltips", (
        ("FancyTooltip_Law", "GetPlayer.Self", "te_law_tax_effects", None),
        ("FancyTooltip_LawWithCountryContext", "Country.Self", "te_law_tax_effects_country", None),
    )),
    ("politics_panel_change_law.gui", "te_law_effects_change_law", (
        ("politics_panel_change_law", "GetPlayer.Self", "te_law_tax_effects", None),
        ("selected_or_enacting_law_content", "GetPlayer.Self", "te_law_tax_effects", "te_law_tax_delta_effects"),
    )),
)


def _effect_desc(country):
    return f"Law.GetLawType.GetEffectDesc({country})"


def _delta_desc(country):
    return f"Law.GetLawType.GetDeltaEffectDesc({country})"


# A `visible` test that builds a costly text: it becomes the taxation test.
COSTLY = re.compile(r"Not\(StringIsEmpty\(Law\.GetLawType\.Get(?:Delta)?EffectDesc\([\w.]+\)\)\)")


def type_span(lines, name):
    """The first and last line of `type <name> = ...` in a vanilla file."""
    start = next((i for i, line in enumerate(lines) if line.strip().startswith(f"type {name} = ")), None)
    if start is None:
        raise ValueError(f"vanilla has no `type {name} = `: update gen_law_effects_gui.py")
    depth = 0
    for i in range(start, len(lines)):
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0:
            return start, i
    raise ValueError(f"vanilla's {name} never closes")


def _widget_span(lines, i):
    """The widget (`name = {` ... `}`) that holds line i."""
    indent = len(lines[i]) - len(lines[i].lstrip("\t"))
    start = next(j for j in range(i, -1, -1)
                 if lines[j].rstrip().endswith("{") and len(lines[j]) - len(lines[j].lstrip("\t")) == indent - 1)
    depth = 0
    for end in range(start, len(lines)):
        depth += lines[end].count("{") - lines[end].count("}")
        if depth == 0:
            return start, end
    raise ValueError(f"the widget at line {start + 1} never closes")


def _tax_copy(lines, country, link, delta_link, what):
    """A copy of vanilla's widget for a taxation law: each `visible` with its
    costly test replaced by the taxation test, the effects text by its link
    line. Raises if a costly call is left."""
    out = []
    for line in lines:
        stripped = line.strip()
        indent = line[:len(line) - len(line.lstrip())]
        if stripped == f'text = "[{_effect_desc(country)}]"':
            line = f'{indent}text = "{link}"'
        elif stripped == f'text = "[{_delta_desc(country)}]"':
            line = f'{indent}text = "{delta_link}"'
        elif stripped.startswith("visible = ") and "EffectDesc(" in line:
            line = COSTLY.sub(IS_TAX, line).replace(f"Or({IS_TAX}, {IS_TAX})", IS_TAX)
        if "EffectDesc(" in line:
            raise ValueError(f"{what}: `{stripped}` still builds the effects text for a taxation law")
        out.append(line)
    return out


def redefine(body, name, country, link, delta_link=None):
    """One vanilla type with its effects widgets hidden for a taxation law,
    which shows the same widgets with the link line instead of the text.

    Two shapes: the effects header and text (the tooltips; the change-law
    panel's law list), or, since 1.15, the selected law's view toggle (All
    effects / Comparative effects) above the header and text and the
    comparison's header and text below. The comparison prices the country's
    taxes too (at the current level), so it is behind a hover as well. Raises,
    naming what moved, if vanilla's widgets aren't where they were."""
    def moved(what):
        return ValueError(f"vanilla's {name} moved {what}: update gen_law_effects_gui.py")

    calls = [i for i, line in enumerate(body) if "GetEffectDesc(" in line]
    deltas = [i for i, line in enumerate(body) if "GetDeltaEffectDesc(" in line]
    if any(_effect_desc(country) not in body[i] for i in calls) or any(_delta_desc(country) not in body[i]
                                                                        for i in deltas):
        raise moved(f"its effects text (a call no longer reads {country})")
    if len(calls) == 3 and not deltas:
        widgets = [_widget_span(body, calls[0]), _widget_span(body, calls[1])]
        if _widget_span(body, calls[2]) != widgets[1]:
            raise moved("its effects text (the header and the text are no longer two widgets)")
        headers = {0: "DATA_LAW_EFFECTS_HEADER"}
    elif len(calls) == 4 and len(deltas) == 4 and deltas[0] == calls[0]:
        widgets = [_widget_span(body, calls[0]), _widget_span(body, calls[1]), _widget_span(body, calls[2]),
                   _widget_span(body, deltas[1]), _widget_span(body, deltas[2])]
        if _widget_span(body, calls[3]) != widgets[2] or _widget_span(body, deltas[3]) != widgets[4]:
            raise moved("its effects text (a header and its text are no longer two widgets)")
        headers = {1: "DATA_LAW_EFFECTS_HEADER", 3: "DATA_LAW_DELTA_EFFECTS_HEADER"}
        if delta_link is None:
            raise moved("its effects text (it has a comparison view, and no line was given for it)")
    else:
        raise moved(f"its effects text (expected three {_effect_desc(country)} calls, or four with the "
                    f"comparison's, found {len(calls)} and {len(deltas)})")
    if len(set(widgets)) != len(widgets) or any(a[1] >= b[0] for a, b in zip(widgets, widgets[1:])):
        raise moved("its effects text (the widgets are no longer separate and in order)")
    for a, b in zip(widgets, widgets[1:]):
        if any(body[k].strip() and not body[k].strip().startswith("#") for k in range(a[1] + 1, b[0])):
            raise moved("its effects text (something now sits between its widgets)")
    for k, key in headers.items():
        if f'text = "{key}"' not in [line.strip() for line in body[widgets[k][0]:widgets[k][1] + 1]]:
            raise moved(f"its effects header (no {key})")
    copies = []
    for start, end in widgets:
        copies += _tax_copy(body[start:end + 1], country, link, delta_link, f"{name}'s effects") + [""]
    first, last = widgets[0][0], widgets[-1][1]
    indent = body[first][:len(body[first]) - len(body[first].lstrip())]
    if len(widgets) == 2:
        what = "header and text"
        shown = ["a taxation law shows the header and one line, whose hover holds the",
                 f"text ({link}), built only while the player hovers it"]
        wrapper = [
            f"{indent}### frame, so vanilla's {what} go in a container hidden for one",
            f"{indent}flowcontainer = {{",
            f"{indent}\tdirection = vertical",
        ]
    else:
        what = "view toggle, headers and texts"
        shown = ["a taxation law shows the toggle and the headers, and a line for each text whose",
                 f"hover holds it ({link}, {delta_link}), built only while the player hovers it"]
        # The toggle is an hbox, and a flowcontainer can't have an hbox/vbox as a direct child:
        # building it overflowed the stack and crashed the game (gui_modding_guide.md gotcha #48).
        wrapper = [
            f"{indent}### frame, so vanilla's {what} go in a vbox hidden for one. Not a",
            f"{indent}### flowcontainer: it can't hold the toggle's hbox, and building that overflowed the stack (2026-11-05)",
            f"{indent}vbox = {{",
        ]

    out = body[:first]
    out += [f"{indent}{MOD_OPEN}: a taxation law's effects text prices its revenue at every tax level each"]
    out += wrapper
    out += [
        f'{indent}\tvisible = "[Not({IS_TAX})]"',
        f"{indent}{MOD_CLOSE}",
    ]
    out += ["\t" + line if line.strip() else line for line in body[first:last + 1]]
    out += [
        f"{indent}{MOD_OPEN}: {shown[0]}",
        f"{indent}### {shown[1]}",
        f"{indent}}}",
        "",
    ] + copies[:-1] + [f"{indent}{MOD_CLOSE}"]
    return out + body[last + 1:]


def generated_gui(fixture_texts=None):
    """gui/00_te_law_effects.gui, as text without a BOM. fixture_texts maps a
    fixture's name to its text, for the tests' drift checks."""
    head, blocks = [], []
    for fixture, block, types in SOURCES:
        if fixture_texts and fixture in fixture_texts:
            text = fixture_texts[fixture]
        else:
            text = (FIXTURES / fixture).read_text(encoding="utf-8-sig")
        lines = text.split("\n")
        constants = {m.group(1): line for line in lines if (m := re.match(r"(@\w+)\s*=", line))}
        out = []
        for name, country, link, delta_link in types:
            start, end = type_span(lines, name)
            body = redefine(lines[start:end + 1], name, country, link, delta_link)
            for used in sorted(set(re.findall(r"@\w+", "\n".join(body)))):
                if used not in constants:
                    raise ValueError(f"vanilla's {name} uses {used}, which {fixture} doesn't define")
                if constants[used] not in head:
                    head.append(constants[used])
            out += body + [""]
        blocks += [f"types {block}", "{"] + out[:-1] + ["}", ""]
    parts = [
        f"### {HEADER}",
        "### Vanilla's law tooltips (gui/custom_tooltip.gui) and change-law panel",
        "### (gui/politics_panel_change_law.gui), redefined from this file (gui_modding_guide.md",
        "### gotcha #30). Copied from test_fixtures/vanilla_gui/; only the `### MOD: Tax law effects`",
        "### blocks differ. Why: scripts/generators/gen_law_effects_gui.py.",
        "",
    ] + head + [""] + blocks
    return "\n".join(parts)


def main():
    OUT.write_text("﻿" + generated_gui(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
