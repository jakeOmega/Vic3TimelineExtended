"""Generate the Demographics tab's Largest Cities: the town classes and the rows (owner, 2026-11-03).

A state's towns are its map hubs, each named by vanilla's `HUB_NAME_<state>_<kind>` key: the capital (`city`), the
port town (`port`), the mining town (`mine`), the farming town (`farm`) and the logging town (`wood`). The census
orders a state's towns by the people at work in each kind of building and splits its urban people among them
(te_demog_place_effects.txt). This generator writes what that needs from the data:

- `common/scripted_triggers/te_demog_town_triggers_generated.txt`:
  - building scope, `te_demog_town_<kind>_work` for port, mine, farm and wood, and `te_demog_town_subsistence_work`: the
    building's town. That is vanilla's own `city_type`, the hub a building's meshes stand in, except that a building
    that draws no mesh (`levels_per_mesh = -1`) and says `city` takes the one kind every meshed base-game building of
    its nearest group shares: the mod's discoverable mines say `city` with no mesh, and are mines. A subsistence
    building (its group `is_subsistence`) counts for no town, its peasants being the countryside's own; every other
    building, those with no `city_type` among them (railways, canals, most monuments), counts for the capital.
  - state scope, `te_demog_town_named_<kind>` for all five: the state's hub of that kind exists in
    `map_data/state_regions/` and its loc key does (15 mining and 8 logging towns have none, and the accessor would
    print the raw key). Written as the shorter of the list and its complement.
- `gui/te_demographics_towns_generated.gui`: `te_demog_town_rows`, the ten slots the country census fills
  (`te_dg_tw_l<i>`, one state each, with `te_dg_tw<i>_c`, its town's kind, and `te_dg_tw<i>_p`, its people), three
  shown and the rest under Show All. A town isn't a scope, so a list of states can't say which of a state's towns a row
  is: each slot is its own list, and its row reads its own variables through the state's owner.

Reads `vanilla_parsed/` (buildings, building groups, localization) and the mod's `common/buildings/`,
`common/building_groups/`, `map_data/state_regions/` and `localization/english/`, so it needs no game install. Not a
post-load regenerator: run it after a vanilla patch or a change to buildings or hubs.
    python3 scripts/generators/gen_demog_towns.py [--check]
`--check` lists drifted files, writes nothing and exits 1 on drift (test_demographics_towns.py runs it).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

TRIGGERS_FILE = ROOT / "common/scripted_triggers/te_demog_town_triggers_generated.txt"
GUI_FILE = ROOT / "gui/te_demographics_towns_generated.gui"

# The five kinds of town, by the census's code (te_dg_tw_<k>, te_dg_tw<i>_c), with each one's hub key in the map data,
# its GUI accessor and its tooltip. Code 0 is a state with no named hub, one town under the state's own name.
KINDS = [
    (1, "city", "GetCityHubName"),
    (2, "port", "GetPortHubName"),
    (3, "mine", "GetMineHubName"),
    (4, "farm", "GetFarmHubName"),
    (5, "wood", "GetForestryHubName"),
]
WORK_KINDS = ["port", "mine", "farm", "wood"]
SLOTS = 10
SHOWN = 3

HEADER = "# AUTO-GENERATED by scripts/generators/gen_demog_towns.py — do not edit manually\n"


def unwrap(value):
    """Strip the parser's ('=', value) wrappers."""
    while isinstance(value, (tuple, list)) and len(value) == 2 and value[0] in ("=", "?="):
        value = value[1]
    return value


def load_buildings(root: Path = ROOT):
    """(buildings, building groups, vanilla buildings): vanilla from the committed snapshot, the mod on top."""
    from mod_state import VANILLA_COMMON_DIRS, ModState
    from vanilla_parsed import load

    kinds = ("Buildings", "Building Groups")
    snapshot = load(str(root / "vanilla_parsed"))
    state = ModState(
        {kind: "/nonexistent" for kind in kinds},
        {kind: str(root / "common" / VANILLA_COMMON_DIRS[kind]) for kind in kinds},
        vanilla_data=snapshot.data,
    )
    if state.parse_failures:
        raise ValueError(f"Cannot class buildings from an incomplete parse: {state.parse_failures}")
    return state.get_data("Buildings"), state.get_data("Building Groups"), snapshot.data["Buildings"]


def _group_chain(groups, group):
    out = []
    while group and group not in out:
        out.append(group)
        body = unwrap(groups.get(group, {}))
        group = unwrap(body.get("parent_group")) if isinstance(body, dict) else None
    return out


def _subsistence(groups, chain):
    for group in chain:
        body = unwrap(groups.get(group, {}))
        if isinstance(body, dict) and unwrap(body.get("is_subsistence")) == "yes":
            return True
    return False


def town_classes(buildings, groups, vanilla) -> dict[str, str | None]:
    """Each building's town: city, port, mine, farm, wood, or None (a subsistence building's, which counts for none)."""
    shared = {}
    for body in vanilla.values():
        body = unwrap(body)
        if not isinstance(body, dict):
            continue
        kind = unwrap(body.get("city_type"))
        if kind in (None, "none") or str(unwrap(body.get("levels_per_mesh"))) == "-1":
            continue
        for group in _group_chain(groups, unwrap(body.get("building_group"))):
            shared.setdefault(group, set()).add(kind)
    out = {}
    for key in sorted(buildings):
        body = unwrap(buildings[key])
        if not isinstance(body, dict):
            continue
        chain = _group_chain(groups, unwrap(body.get("building_group")))
        if _subsistence(groups, chain):
            out[key] = None
            continue
        kind = unwrap(body.get("city_type"))
        if kind == "city" and str(unwrap(body.get("levels_per_mesh"))) == "-1":
            for group in chain:
                kinds = shared.get(group)
                if kinds:
                    if len(kinds) == 1:
                        kind = next(iter(kinds))
                    break
        out[key] = "city" if kind in (None, "none") else kind
    return out


def state_hubs(root: Path = ROOT) -> dict[str, set[str]]:
    """Every land state region and the hub kinds it defines (the seas, 99_seas.txt, left out)."""
    states = {}
    for path in sorted((root / "map_data/state_regions").glob("*.txt")):
        if path.name.startswith("99_"):
            continue
        text = re.sub(r"#[^\n]*", "", path.read_text(encoding="utf-8-sig"))
        for m in re.finditer(r"(?m)^(STATE_[A-Z0-9_]+)\s*=\s*\{", text):
            depth, j = 1, m.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[j], 0)
                j += 1
            body = text[m.end():j]
            states[m.group(1)] = {kind for _, kind, _ in KINDS if re.search(rf"(?m)^\s*{kind}\s*=", body)}
    return states


def hub_loc_keys(root: Path = ROOT) -> set[str]:
    """The HUB_NAME_* keys vanilla's English loc and the mod's define."""
    from mod_state import split_loc_line

    with open(root / "vanilla_parsed" / "localization_english.json", encoding="utf-8") as f:
        keys = {k for k in json.load(f) if k.startswith("HUB_NAME_")}
    for path in sorted((root / "localization" / "english").rglob("*.yml")):
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            got = split_loc_line(line)
            if got and got[0].startswith("HUB_NAME_"):
                keys.add(got[0])
    return keys


def named(states: dict[str, set[str]], keys: set[str]) -> dict[str, list[str]]:
    """Per kind, the states whose hub of that kind has a name."""
    return {kind: sorted(s for s, hubs in states.items() if kind in hubs and f"HUB_NAME_{s}_{kind}" in keys)
            for _, kind, _ in KINDS}


def _or_block(lines, indent):
    pad = "\t" * indent
    return f"{pad}OR = {{\n" + "".join(f"{pad}\t{line}\n" for line in lines) + f"{pad}}}\n"


def render_triggers(classes, states, names) -> str:
    out = [HEADER,
           "# The Demographics tab's Largest Cities (te_demog_place_effects.txt, te_demog_town_walk_pop and\n"
           "# te_demog_town_walk_store). Building scope: the town a building's workers count for, from vanilla's\n"
           "# city_type (the module docstring of the generator); any other building counts for the capital.\n"]
    for kind in WORK_KINDS + [None]:
        name = f"te_demog_town_{kind}_work" if kind else "te_demog_town_subsistence_work"
        types = sorted(k for k, c in classes.items() if c == kind)
        out.append(f"{name} = {{\n" + _or_block([f"is_building_type = {t}" for t in types], 1) + "}\n")
    out.append("# State scope: the state's hub of this kind is on the map and its HUB_NAME_ key has a name, so its town\n"
               "# can be shown by name.\n")
    for _, kind, _ in KINDS:
        have = names[kind]
        lack = sorted(set(states) - set(have))
        if not lack:
            body = "\talways = yes\n"
        elif not have:
            body = "\talways = no\n"
        elif len(have) <= len(lack):
            body = _or_block([f"state_region = s:{s}" for s in have], 1)
        else:
            body = "\tNOT = {\n" + _or_block([f"state_region = s:{s}" for s in lack], 2) + "\t}\n"
        out.append(f"te_demog_town_named_{kind} = {{\n{body}}}\n")
    return "\n".join(out)


def _indent(lines, depth=1):
    """`lines` a level deeper (`depth` tabs), blank lines left blank."""
    return [("\t" * depth + line) if line else "" for line in lines]


def _lines(lines, depth):
    return "".join(line + "\n" for line in _indent(lines, depth))


def _row(slot, code, name_text, tooltip):
    """One of a slot's six rows: shown while the slot's town is of its kind."""
    kind = f"State.GetOwner.MakeScope.Var('te_dg_tw{slot}_c').GetValue"
    people = f"State.GetOwner.MakeScope.Var('te_dg_tw{slot}_p').GetValue|K"
    return [
        "te_demog_town_row = {",
        f"\tblockoverride \"town_shown\" {{ visible = \"[EqualTo_CFixedPoint( {kind}, '(CFixedPoint){code}' )]\" }}",
        f"\tblockoverride \"town_tooltip\" {{ tooltip = \"{tooltip}\" }}",
        f"\tblockoverride \"town_name\" {{ text = \"{name_text}\" }}",
        f"\tblockoverride \"town_people\" {{ text = \"[{people}]\" }}",
        "}",
    ]


def _slot(slot):
    """Slot `slot`'s list, its one state the item's context."""
    rows = [_row(slot, code, f"[State.{accessor}]", f"te_demog_town_tt_{kind}") for code, kind, accessor in KINDS]
    rows.append(_row(slot, 0, "[State.GetNameNoFormatting]", "te_demog_town_tt_state"))
    return [
        "flowcontainer = {",
        f"\tdatamodel = \"[Country.MakeScope.GetList('te_dg_tw_l{slot}')]\"",
        "\tdirection = vertical",
        "\tignoreinvisible = yes",
        "",
        "\titem = {",
        "\t\tflowcontainer = {",
        "\t\t\tdatacontext = \"[Scope.GetState]\"",
        "\t\t\tdirection = vertical",
        "\t\t\tignoreinvisible = yes",
        "",
        *_indent([line for row in rows for line in row], 3),
        "\t\t}",
        "\t}",
        "}",
    ]


def render_gui() -> str:
    shown = [line for i in range(1, SHOWN + 1) for line in _slot(i)]
    more = [line for i in range(SHOWN + 1, SLOTS + 1) for line in _slot(i)]
    body = [
        "type te_demog_town_rows = flowcontainer {",
        "\tdirection = vertical",
        "\tignoreinvisible = yes",
        "\tspacing = 2",
        "",
        *_indent(shown),
        "\tflowcontainer = {",
        "\t\tvisible = \"[GetVariableSystem.Exists('te_demog_towns_all_open')]\"",
        "\t\tdirection = vertical",
        "\t\tignoreinvisible = yes",
        "\t\tspacing = 2",
        "",
        *_indent(more, 2),
        "\t}",
        "}",
    ]
    return (
        HEADER
        + "# The Demographics tab's Largest Cities (te_demog_sec_places, gui/te_demographics_widgets.gui): the ten slots\n"
        "# the country census fills (te_demog_town_country, te_demog_place_effects.txt), largest first. Each slot is a\n"
        "# one-state list, so an empty slot draws nothing; its row is one of six, by the town's kind (te_dg_tw<i>_c: 1\n"
        "# the capital, 2 the port, 3 the mining, 4 the farming, 5 the logging town, 0 the state's own name), read\n"
        "# through the state's owner, the country shown. The first three always; the rest under Show All\n"
        "# (te_demog_towns_all_open).\n"
        "types te_demog_towns_generated\n"
        "{\n"
        + _lines(body, 1)
        + "}\n"
    )


def outputs(root: Path = ROOT) -> dict[Path, bytes]:
    buildings, groups, vanilla = load_buildings(root)
    states = state_hubs(root)
    names = named(states, hub_loc_keys(root))
    return {
        root / TRIGGERS_FILE.relative_to(ROOT): render_triggers(town_classes(buildings, groups, vanilla), states,
                                                                names).encode("utf-8-sig"),
        root / GUI_FILE.relative_to(ROOT): render_gui().encode("utf-8-sig"),
    }


def main(argv: list[str]) -> int:
    data = outputs()
    drifted = [path for path, body in data.items() if not path.is_file() or path.read_bytes() != body]
    if "--check" in argv:
        for path in drifted:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if drifted else 0
    for path, body in data.items():
        path.write_bytes(body)
    print(f"wrote {len(data)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
