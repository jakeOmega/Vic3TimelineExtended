# The ladder
# ---------------------------------------------------------------------------


def render_effects(pairs, plan) -> str:
    """``te_hcg_save_targets``: one branch per roster language, in roster order."""
    by_language: dict[str, list[cfg.Pair]] = {}
    for pair in pairs:
        by_language.setdefault(pair.language.key, []).append(pair)
    out = [
        HEADER,
        "",
        f"# {SAVE_EFFECT} (state scope): the hybrids of the host culture's language, for the hand-written pass",
        "# (te_assimilation_culture_effects.txt). It reads scope:%s, a culture the pass saves first." % HOST_SCOPE,
        "# The first roster language the host speaks whose first hybrid exists saves each of that language's",
        "# hybrids as the temporary scope %s (%s ...) and sets the local variable"
        % (TARGET_SCOPE.format("<group>"), TARGET_SCOPE.format("african")),
        "# %s to 1. A host off the roster, or a game begun before the hybrids existed, sets nothing." % HAS_TARGETS,
        "# A language has no hybrid for the one heritage group all its own cultures share, so its branch saves",
        "# no scope for that group.",
        f"{SAVE_EFFECT} = {{",
    ]
    for index, language in enumerate(cfg.languages(plan)):
        members = by_language[language.key]
        out += [
            "\t%s = {" % ("if" if index == 0 else "else_if"),
            "\t\tlimit = {",
            "\t\t\tscope:%s = { has_discrimination_trait = %s%s }" % (HOST_SCOPE, cfg.LANGUAGE_PREFIX, language.key),
            "\t\t\texists = cu:%s" % members[0].culture,
            "\t\t}",
        ]
        out += ["\t\tcu:%s = { save_temporary_scope_as = %s }" % (pair.culture, TARGET_SCOPE.format(pair.group.key))
                for pair in members]
        out += ["\t\tset_local_variable = { name = %s value = 1 }" % HAS_TARGETS, "\t}"]
    out.append("}")
    return "\n".join(out) + "\n"


