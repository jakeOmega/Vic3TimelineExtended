def hybrid_fields(pair: cfg.Pair, cultures: dict, plan) -> dict:
    """What a hybrid holds, in ``Built.fields``' shape for ``render_culture_block``."""
    entry = _merge_entry(pair.language.names_from, plan)
    names = entry.fields if entry is not None else cm_gen.culture_fields(cultures[pair.language.names_from])
    looks = cm_gen.culture_fields(cultures[pair.group.looks_from])
    names_who = f"{pair.culture}'s names_from {pair.language.names_from}"
    looks_who = f"{pair.culture}'s looks_from {pair.group.looks_from}"
    fields = {
        "religion": cm_gen.single(names, "religion", names_who),
        "heritage": pair.group.heritage,
        "language": cfg.LANGUAGE_PREFIX + pair.language.key,
        "graphics": cm_gen.single(looks, "graphics", looks_who),
        "ethnicities": cm_gen.ethnicities(looks),
        "obsessions": [],
        "taboos": [],
        "traditions": [],
    }
    if "name_format" in names:
        fields["name_format"] = cm_gen.single(names, "name_format", names_who)
    if not fields["ethnicities"]:
        raise ValueError(f"{looks_who} has no ethnicities")
    for list_name in cm_gen.NAME_LISTS:
        found = cm_gen.name_list(names, list_name)
        if found:
            fields[list_name] = found
    return fields


def render_cultures(pairs, cultures: dict, plan) -> str:
    blocks = []
    for pair in pairs:
        comment = (f"# {pair.culture}: names and religion from {pair.language.names_from}, "
                   f"looks from {pair.group.looks_from}")
        blocks.append(cm_gen.render_culture_block(pair.culture, comment, hybrid_color(pair, cultures, plan),
                                                  hybrid_fields(pair, cultures, plan)))
    return HEADER + "\n\n" + "\n".join(blocks)


def render_traits() -> str:
    blocks = [
        f"# The heritage of the {group} hybrids (hc_<language>_{group}), in vanilla's group.\n"
        f"{key} = {{\n\ttype = heritage\n\ttrait_group = {cfg.GROUP_PREFIX}{group}\n}}\n"
        for key, group in cfg.minted_heritages()
    ]
    return HEADER + "\n\n" + "\n".join(blocks)


