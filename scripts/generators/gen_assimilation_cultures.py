def culture_name(pair: cfg.Pair) -> str:
    """``<language part> <group part>``: each the roster's word, or vanilla's name spliced."""
    language = pair.language.word or f"${cfg.LANGUAGE_PREFIX}{pair.language.key}$"
    group = pair.group.word or f"${cfg.GROUP_PREFIX}{pair.group.key}$"
    return f"{language} {group}"


def loc_entries(pairs) -> dict[str, str]:
    """Loc key -> text, for every hybrid, minted heritage and static modifier."""
    entries = {pair.culture: culture_name(pair) for pair in pairs}
    for key, group in cfg.minted_heritages():
        entries[key] = f"${cfg.GROUP_PREFIX}{group}$ Diaspora"
    for key, text in cm_gen.static_modifier_loc_for([pair.culture for pair in pairs]).items():
        if key in entries:
            raise ValueError(f"{key} is defined twice")
        entries[key] = text
    return entries


def render_loc(pairs) -> str:
    entries = {}
    for key, text in loc_entries(pairs).items():
        if '"' in text:
            raise ValueError(f"{key}: a display name can't hold a quote mark")
        entries[key] = f'0 "{text}"'
    return _render_loc_file([(section_label(LOC_CATEGORY), entries)]).decode("utf-8-sig")


