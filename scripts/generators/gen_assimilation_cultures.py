"""Generate the assimilation cultures' hybrids from the roster in assimilation_cultures_config.py.

A hybrid culture (``hc_<language>_<group>``, ``hc_anglophone_african``) is what a pop becomes when it assimilates
under a host of another heritage group and the game rule keeps its heritage: the host's language, its own heritage
group (docs/superpowers/specs/2026-11-25-assimilation-cultures-design.md § The cultures). One for each roster
language and heritage group (``assimilation_cultures_config.pairs``), 584 in all. The pass that converts pops into
them is hand-written; this writes only what each culture needs and the one ladder the pass calls.

Outputs, all rewritten only when their content changes (one UTF-8 BOM):

* ``common/cultures/te_hybrid_cultures.txt``: one culture per pair, in roster order. ``language_<key>`` and the
  group's heritage trait; religion, ``name_format`` (where it has one) and every name list from the language's
  ``names_from`` (for a merge language, from the merge's built result); graphics and ethnicities from the group's
  ``looks_from``; ``traditions = { }`` and no obsessions, taboos, seal or ``assimilation_rate``. The color is the
  channel mean of the two reference cultures' colors (``hybrid_color``). Written through
  ``gen_culture_merges.render_culture_block``, so both families of generated culture keep one field order.
* ``common/discrimination_traits/te_hybrid_culture_traits.txt``: the nine heritage traits minted for the hybrids
  (``heritage_hc_<group>``, in vanilla's ``heritage_group_<group>``); the African hybrids take vanilla's
  ``heritage_african_diaspora``.
* ``common/static_modifiers/te_hybrid_culture_static_modifiers.txt`` and
  ``common/modifier_type_definitions/te_hybrid_culture_modifier_types.txt``: the six static modifiers and three
  modifier types the engine expects of every culture, through the merges' renderers
  (``render_static_modifiers_for``, ``render_modifier_types_for``). Without them the engine logs ``Missing expected
  culture static modifier`` and ``Unknown modifier type`` at load (docs/systems/mod_systems/culture_merges.md).
* ``common/scripted_effects/te_hybrid_cultures_generated_effects.txt``: ``te_hcg_save_targets`` (state scope), a
  ladder with a branch per roster language in roster order. It reads ``scope:te_hc_host``, a culture the hand-written
  pass saves. The first branch whose language trait the host has and whose first hybrid exists saves each of that
  language's hybrids as the temporary scope ``te_hc_t_<group>`` and sets the local variable ``te_hc_has_targets``
  to 1; otherwise nothing is set (a host off the roster, or a game begun before the hybrids existed).
* ``localization/english/te_hybrid_cultures_generated_l_english.yml``: each hybrid's name, spliced from vanilla's
  names for the language and the group (``$language_anglophone$ $heritage_group_african$``) or the roster's word
  where vanilla's is a linguist's (``Turkic $heritage_group_european$``); each minted heritage
  (``$heritage_group_<group>$ Diaspora``); the static modifiers' names (``static_modifier_loc_for``). Rendered
  through ``organize_loc`` (category HYBRID_CULTURES_GENERATED: keys starting ``hc_`` or ``heritage_hc_``) so that a
  run of ``organize_loc.py`` leaves it intact.

Vanilla comes from the committed ``vanilla_parsed/`` snapshot and the merges' results from
``gen_culture_merges.build_plan``, never from the live ModState, which holds the generated cultures.

Run ``python3 scripts/generators/gen_assimilation_cultures.py [--dry-run | --check]``. No game install or running
server is needed. Full server reloads call ``regenerate`` (``server/post_load.py``'s ``POST_LOAD_REGENERATORS``,
after ``gen_culture_merges`` and before ``organize_loc``).
"""

