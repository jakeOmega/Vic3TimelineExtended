HEADER = "# AUTO-GENERATED by scripts/generators/gen_assimilation_cultures.py - do not edit manually."

CULTURES_OUT = Path("common/cultures/te_hybrid_cultures.txt")
TRAITS_OUT = Path("common/discrimination_traits/te_hybrid_culture_traits.txt")
STATIC_MODIFIERS_OUT = Path("common/static_modifiers/te_hybrid_culture_static_modifiers.txt")
MODIFIER_TYPES_OUT = Path("common/modifier_type_definitions/te_hybrid_culture_modifier_types.txt")
EFFECTS_OUT = Path("common/scripted_effects/te_hybrid_cultures_generated_effects.txt")
LOC_OUT = Path("localization/english/te_hybrid_cultures_generated_l_english.yml")
LOC_CATEGORY = "HYBRID_CULTURES_GENERATED"

SAVE_EFFECT = "te_hcg_save_targets"
HOST_SCOPE = "te_hc_host"
TARGET_SCOPE = "te_hc_t_{}"
HAS_TARGETS = "te_hc_has_targets"


# ---------------------------------------------------------------------------
# Colors
# ---------------------------------------------------------------------------

_TYPED_COLOR = re.compile(r"(rgb|hsv360|hsv)\s*\{([^{}]*)\}")
_INTEGER = re.compile(r"\d+")
_FRACTION = re.compile(r"\d*\.\d+|[01]")


def color_rgb(raw) -> tuple[int, int, int]:
    """A culture color as 0 to 255 integers. ValueError for a form this reader does not know.

    The forms vanilla writes: ``rgb{ r g b }`` (0 to 255), ``hsv{ h s v }`` (0 to 1, with or without a space before
    the brace), and a bare ``{ a b c }``, which is RGB: integers 0 to 255 (40 cultures), or fractions 0 to 1
    (Romanian's ``{ 0.12 0.41 0.54 }``). Also ``hsv360{ h s v }`` (0 to 360, 0 to 100, 0 to 100).

    Two vanilla cultures write an hsv value above 1. How the engine reads one is unverified, but Japanese's
    ``hsv{ 0 0 90 }`` is a grey, which is white whether the value is clamped before the conversion or the channels
    after it, so it reads as white. Mongo's ``hsv{ 0.01 0.47 67 }`` differs by the order and is refused; no hybrid
    takes Mongo's color.
    """
    if isinstance(raw, str):
        match = _TYPED_COLOR.fullmatch(raw.strip())
        if not match:
            raise ValueError(f"a color form the reader does not know: {raw!r}")
        kind, parts = match.group(1), match.group(2).split()
    elif isinstance(raw, (list, tuple)) and all(isinstance(v, str) for v in raw):
        kind, parts = "list", list(raw)
    else:
        raise ValueError(f"a color form the reader does not know: {raw!r}")
    if len(parts) != 3:
        raise ValueError(f"a color needs three channels: {raw!r}")
    if kind == "list":
        kind = "rgb" if all(_INTEGER.fullmatch(p) for p in parts) else "rgb_fraction"
    if kind == "rgb":
        if not all(_INTEGER.fullmatch(p) and int(p) <= 255 for p in parts):
            raise ValueError(f"rgb channels are integers 0 to 255: {raw!r}")
        r, g, b = (int(p) for p in parts)
        return (r, g, b)
    try:
        values = [float(p) for p in parts]
    except ValueError:
        raise ValueError(f"a color channel is not a number: {raw!r}") from None
    if kind == "rgb_fraction":
        if not all("." in p and _FRACTION.fullmatch(p) and v <= 1 for p, v in zip(parts, values)):
            raise ValueError(f"a bare color is integers 0 to 255 or fractions 0 to 1, not a mix: {raw!r}")
        rgb = values
    elif kind == "hsv":
        h, s, v = values
        if v > 1 and s == 0 and 0 <= h <= 1:
            v = 1.0  # a grey past white (Japanese's hsv{ 0 0 90 }): white however the engine clamps
        if not all(0 <= c <= 1 for c in (h, s, v)):
            raise ValueError(f"hsv channels run 0 to 1: {raw!r}")
        rgb = colorsys.hsv_to_rgb(h, s, v)
    else:  # hsv360
        h, s, v = values
        if not (0 <= h <= 360 and 0 <= s <= 100 and 0 <= v <= 100):
            raise ValueError(f"hsv360 channels run 0 to 360, 0 to 100, 0 to 100: {raw!r}")
        rgb = colorsys.hsv_to_rgb(h / 360, s / 100, v / 100)
    r, g, b = (round(channel * 255) for channel in rgb)
    return (r, g, b)


def _merge_entry(culture: str, plan) -> cm_gen.Built | None:
    return next((entry for entry in plan if entry.merge.result == culture), None)


def reference_color(culture: str, cultures: dict, plan) -> tuple[int, int, int]:
    """A reference culture's color: a merge result's from the merge roster, a vanilla culture's from its definition."""
    entry = _merge_entry(culture, plan)
    if entry is not None:
        return tuple(entry.merge.new.color)
    return color_rgb(cm_cfg.unwrap(cm_gen.culture_fields(cultures[culture]).get("color")))


def hybrid_color(pair: cfg.Pair, cultures: dict, plan) -> tuple[int, int, int]:
    """The channel mean of the colors of the language's ``names_from`` and the group's ``looks_from``, halves up."""
    names = reference_color(pair.language.names_from, cultures, plan)
    looks = reference_color(pair.group.looks_from, cultures, plan)
    r, g, b = ((a + c + 1) // 2 for a, c in zip(names, looks))
    return (r, g, b)


