def plan_outputs(root: Path = ROOT) -> dict[Path, str]:
    """Relative output path -> its text (without the BOM)."""
    cultures = cm_gen.load_vanilla(root)
    plan = cm_gen.build_plan(cultures)
    pairs = cfg.pairs(cultures, plan)
    keys = [pair.culture for pair in pairs]
    return {
        CULTURES_OUT: render_cultures(pairs, cultures, plan),
        TRAITS_OUT: render_traits(),
        STATIC_MODIFIERS_OUT: cm_gen.render_static_modifiers_for(keys, HEADER),
        MODIFIER_TYPES_OUT: cm_gen.render_modifier_types_for(keys, HEADER, STATIC_MODIFIERS_OUT.name),
        EFFECTS_OUT: render_effects(pairs, plan),
        LOC_OUT: render_loc(pairs),
    }


def regenerate(mod_state=None, *, root: Path = ROOT, dry_run: bool = False) -> dict:
    """Post-load entry point (server/post_load.py's POST_LOAD_REGENERATORS) and CLI body.

    Reads only the vanilla snapshot and the merge roster; ``mod_state`` is unused. Writes a file only when its
    content changed, with one UTF-8 BOM.
    """
    changed = []
    for relative, text in plan_outputs(root).items():
        target = root / relative
        expected = text.encode("utf-8-sig")
        if not target.exists() or target.read_bytes() != expected:
            changed.append(str(relative))
            if not dry_run:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)
    return {"changed": bool(changed), "changed_files": changed}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    args = parser.parse_args(argv)
    result = regenerate(dry_run=args.dry_run or args.check)
    verb = "stale" if args.check else "would write" if args.dry_run else "wrote"
    for path in result["changed_files"]:
        print(f"{verb}: {path}")
    if not result["changed"]:
        print("assimilation cultures: current")
    return int(args.check and result["changed"])


if __name__ == "__main__":
    sys.exit(main())
