#!/usr/bin/env python3
"""Write te_math_generated.txt: math functions script values lack.

A script value has no `sqrt`, `pow` or `log` operator
(docs/guides/scripting_best_practices.md, "Script values have no square root or
power"), so each function here is a piecewise-linear table: straight segments
between knots a factor of sqrt(2) apart, exact at every knot, picked by a binary
tree of `if`/`else` on the input so a read costs about seven comparisons.

`te_sqrt` reads its input from `var:te_math_in` on the current scope: set it,
read the value, remove it (te_set_sqrt in common/scripted_effects/te_math_effects.txt
does all three). Concave, so the chords run under the curve: within 0.5% of the
square root from 0.001 to KNOT_TOP, within 2% below that, where the knots crowd
onto the engine's 0.00001 grid. Past KNOT_TOP the last segment carries on.

Needs nothing but the repo. Re-run after changing a table; test_math_curves.py
fails CI when the committed file is stale:

    python3 scripts/generators/gen_math_curves.py [--check]
"""
import argparse
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "common", "script_values", "te_math_generated.txt")

INPUT = "var:te_math_in"
# The engine keeps five decimals (scripting_best_practices.md, "Values are
# stored in units of 1e-5"), so no knot can sit below this, and its largest
# value is about 9.2e13: the top knot is the last power of 2 under it.
KNOT_FLOOR = 0.00001
KNOT_TOP = 2 ** 46


def _round_knot(x):
    """Five significant figures, on the engine's five-decimal grid."""
    digits = 4 - math.floor(math.log10(x))
    return round(x, min(5, digits))


def knots():
    """0, then the powers of sqrt(2) from KNOT_FLOOR to KNOT_TOP, rounded and deduplicated."""
    out = [0.0]
    j = math.floor(2 * math.log2(KNOT_FLOOR))
    while 2 ** (j / 2) <= KNOT_TOP:
        k = _round_knot(2 ** (j / 2))
        if k >= KNOT_FLOOR and k > out[-1]:
            out.append(k)
        j += 1
    return out


def _num(x):
    """A literal as the engine reads it: five decimals, no trailing zeros."""
    s = f"{x:.5f}".rstrip("0").rstrip(".")
    return s if s else "0"


def segments(fn=math.sqrt):
    """(start, end, fn(start), slope's divisor) per segment; the last runs past its end."""
    ks = knots()
    out = []
    for a, b in zip(ks, ks[1:]):
        fa, fb = fn(a), fn(b)
        out.append((a, b, fa, (b - a) / (fb - fa)))
    return out


def _leaf(seg):
    a, _b, fa, div = seg
    ops = [f"value = {INPUT}"]
    if a:
        ops.append(f"subtract = {_num(a)}")
    ops.append(f"divide = {_num(div)}")
    if a:
        ops.append(f"add = {_num(fa)}")
    return " ".join(ops)


def _tree(segs, lo, hi, depth):
    tab = "\t" * depth
    if hi - lo == 1:
        return [tab + _leaf(segs[lo])]
    mid = (lo + hi) // 2
    lines = [tab + "if = {", tab + f"\tlimit = {{ {INPUT} < {_num(segs[mid][0])} }}"]
    lines += _tree(segs, lo, mid, depth + 1)
    lines.append(tab + "}")
    lines.append(tab + "else = {")
    lines += _tree(segs, mid, hi, depth + 1)
    lines.append(tab + "}")
    return lines


def render():
    segs = segments()
    lines = [
        "# AUTO-GENERATED by scripts/generators/gen_math_curves.py — do not edit manually.",
        "# Math functions script values lack, as piecewise-linear tables: straight segments between knots a",
        "# factor of sqrt(2) apart, exact at each knot, picked by a binary tree on the input (about seven",
        "# comparisons a read). Re-run the generator after changing a table; test_math_curves.py fails when",
        "# this file is stale.",
        "",
        "# The square root of var:te_math_in on this scope, 0 for 0 or less. Set the input, read this, remove",
        "# the input: te_set_sqrt (common/scripted_effects/te_math_effects.txt) does all three. Within 0.5% from",
        f"# 0.001 to {segs[-1][1]:,.0f} ({len(segs)} segments) and within 2% below 0.001, a little under the",
        "# root; past the top knot the last segment carries on. Store the result where a modifier's multiplier",
        "# reads it: the engine evaluates a multiplier again later, when var:te_math_in is gone.",
        "te_sqrt = {",
        "\tvalue = 0",
        "\tif = {",
        f"\t\tlimit = {{ {INPUT} > 0 }}",
    ]
    lines += _tree(segs, 0, len(segs), 2)
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale; write nothing")
    args = parser.parse_args()
    text = render()
    rel = os.path.relpath(OUT, REPO)
    if args.check:
        try:
            with open(OUT, encoding="utf-8-sig") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f"{rel} is stale: run scripts/generators/gen_math_curves.py")
            return 1
        print(f"{rel} is current")
        return 0
    with open(OUT, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print(f"wrote te_sqrt ({len(segments())} segments) to {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
