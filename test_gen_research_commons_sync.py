import re
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "scripts" / "generators"))
import gen_research_commons_sync as gen  # noqa: E402


class CatalogTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.state = gen.load_state(ROOT)
        cls.catalog = gen.tech_catalog(cls.state)
        cls.by_key = {tech.key: tech for tech in cls.catalog}

    def test_all_three_categories(self):
        # The covert generator leaves society out only because no operation steals it.
        self.assertEqual({tech.category for tech in self.catalog}, {"production", "military", "society"})
        self.assertIn("mass_media", self.by_key)
        self.assertIn("nuclear_weapons", self.by_key)   # weapons included in v1 (design § 6.7)
        self.assertIn("intergovernmental_organizations", self.by_key)

    def test_leaves_out_unresearchable(self):
        self.assertNotIn("sericulture", self.by_key)    # can_research = no

    def test_exclusion_list_is_empty_in_v1_and_works(self):
        self.assertEqual(gen.EXCLUDED_TECHNOLOGIES, ())
        catalog = gen.tech_catalog(self.state, excluded=("nuclear_weapons",))
        self.assertNotIn("nuclear_weapons", {tech.key for tech in catalog})
        self.assertEqual(len(catalog), len(self.catalog) - 1)

    def test_prerequisite_order(self):
        order = gen.prerequisite_order(self.catalog)
        self.assertEqual(sorted(t.key for t in order), sorted(self.by_key))
        position = {tech.key: i for i, tech in enumerate(order)}
        for tech in order:
            for prereq in tech.prereqs:
                if prereq in position:
                    with self.subTest(tech=tech.key, prereq=prereq):
                        self.assertLess(position[prereq], position[tech.key])

    def test_a_cycle_is_an_error(self):
        a = gen.Tech("a", "society", 1, ("b",))
        b = gen.Tech("b", "society", 1, ("a",))
        with self.assertRaises(ValueError):
            gen.prerequisite_order([a, b])

    def test_ties_by_era_then_key(self):
        techs = [gen.Tech("zeta", "society", 1), gen.Tech("alpha", "society", 2), gen.Tech("beta", "society", 1)]
        self.assertEqual([t.key for t in gen.prerequisite_order(techs)], ["beta", "zeta", "alpha"])


class RenderTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.state = gen.load_state(ROOT)
        cls.order = gen.prerequisite_order(gen.tech_catalog(cls.state))
        cls.text = gen.render_sync(cls.order)

    def test_one_branch_a_technology(self):
        n = len(self.order)
        body = self.text[self.text.index("te_rc_sync_all = {"):]
        self.assertEqual(body.count("any_power_bloc_member = { has_technology_researched = "), n)
        self.assertEqual(body.count("any_power_bloc_member = { NOT = { has_technology_researched = "), n)
        self.assertEqual(body.count("every_power_bloc_member = {"), n)
        self.assertEqual(body.count("te_rc_grant = { TECH = "), n)

    def test_grant_only_where_lacking(self):
        for tech in self.order[:5]:
            with self.subTest(tech=tech.key):
                self.assertIn(
                    f"\t\tevery_power_bloc_member = {{\n"
                    f"\t\t\tlimit = {{ NOT = {{ has_technology_researched = {tech.key} }} }}\n"
                    f"\t\t\tte_rc_grant = {{ TECH = {tech.key} }}\n",
                    self.text,
                )

    def test_cost_line_states_the_count(self):
        n = len(self.order)
        self.assertIn(f"Cost per pass: {n} technologies, {2 * n} any_power_bloc_member checks", self.text)

    def test_order_matches_rendered(self):
        keys = re.findall(r"te_rc_grant = \{ TECH = (\S+) \}", self.text)
        self.assertEqual(keys, [t.key for t in self.order])


class OutputTest(unittest.TestCase):
    def test_committed_output_is_current(self):
        result = gen.regenerate(root=ROOT, dry_run=True)
        self.assertFalse(result["changed"], f"stale; run scripts/generators/gen_research_commons_sync.py: {result}")

    def test_one_bom_and_header(self):
        raw = (ROOT / gen.OUT).read_bytes()
        self.assertTrue(raw.startswith(b"\xef\xbb\xbf"))
        self.assertFalse(raw[3:].startswith(b"\xef\xbb\xbf"))
        self.assertIn(b"AUTO-GENERATED by scripts/generators/gen_research_commons_sync.py", raw[:200])

    def test_helper_exists(self):
        effects = (ROOT / "common/scripted_effects/te_research_commons_effects.txt").read_text(encoding="utf-8-sig")
        self.assertRegex(effects, r"(?m)^te_rc_grant = \{")
        self.assertIn("add_technology_researched = $TECH$", effects)


if __name__ == "__main__":
    unittest.main()
