"""The overlay mod: the harness's own script, written into a small mod folder that `launch` adds to the playset.

    mod/te_qa_overlay/.metadata/metadata.json                 carries MARKER, which is what lets `remove` delete the folder
    mod/te_qa_overlay/events/te_qa_events.txt                 hidden country events: the read event, the pad event, one per setup
    mod/te_qa_overlay/common/scripted_effects/te_qa_effects.txt   te_qa_pad, te_qa_loaded, te_qa_setup_<name>
                                                              and the spare te_qa_slot_<n> effects
    mod/te_qa_overlay/tools/scripted_tests/te_qa_fixture.txt  the scripted test that makes a fresh save (game_qa.fixture)

Nothing here touches anything but that one folder, by its exact path, and a sibling temp folder
made for one build. `build` writes the new overlay beside the old one and swaps it in, so a failed
build leaves no half overlay; one cut short by a kill can leave its temp folder, which `remove_build`
deletes under the same checks as `remove` (`python3 -m game_qa remove-overlay` runs both). The shapes
follow the probe files that ran against the real game on 2026-11-10 (docs/testing/game_qa_probe/overlay/).
The `.txt` files start with one UTF-8 BOM and are indented with tabs; `metadata.json` has no BOM, as the
mod's own has none.

A setup added to a running game (`add_setup`, #1600) goes into a spare slot. The game reloads a scripted-effect
file that changes while it runs (`-debug_mode`; spec § 3.3: verified, about 40 seconds with this mod), but an
effect file added mid-game did not run until the reload after, and nothing says an event added to a loaded file
would. So the events are all there from the start: SLOT_COUNT hidden events, each calling its own
`te_qa_slot_<n>` effect, empty until `add_setup` rewrites `te_qa_effects.txt` with a body in one. That file
carries a revision, logged by `te_qa_loaded` through LOADED_EVENT, which is how the session tells that the
game has taken the rewrite.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path

OVERLAY_NAME = "te_qa_overlay"
MARKER = "te_qa_overlay generated by game_qa"
NAMESPACE = "te_qa"
READ_EVENT = "te_qa.1"
PAD_EVENT = "te_qa.2"
FIXTURE_TEST = "te_qa_fixture"
LOADED_EVENT = "te_qa.3"
FIRST_SETUP_EVENT = 10  # setup events are te_qa.10, te_qa.11, ... in the sorted order of the setup names
FIRST_SLOT_EVENT = 100  # the spare events are te_qa.100 ... te_qa.129, slot 0 first
SLOT_COUNT = 30
MAX_START_SETUPS = FIRST_SLOT_EVENT - FIRST_SETUP_EVENT
LOADED_PREFIX = "TE_QA overlay rev "    # then the revision of te_qa_effects.txt the game has loaded
_BUILD_TEMP = re.compile(r"\.%s\.tmp-[A-Za-z0-9_]+" % OVERLAY_NAME)  # the temp folders `build` makes (mkdtemp)

EVENTS_FILE = "events/te_qa_events.txt"
EFFECTS_FILE = "common/scripted_effects/te_qa_effects.txt"
SCRIPTED_TEST_FILE = f"tools/scripted_tests/{FIXTURE_TEST}.txt"
METADATA_FILE = ".metadata/metadata.json"

PAD_LINES = 60  # about 9 KB of log: enough to flush the game's block-buffered debug.log (4 KB at a time)
PAD_TEXT = "TE_QA PAD " + "0123456789" * 7
READ_LOG_LINE = (
    'debug_log = "TE_QA read country=[THIS.GetCountry.GetTagName] date=[TimeKeeper.GetCurrentDate.GetString]"'
)

_SETUP_NAME = re.compile(r"[a-z][a-z0-9_]{0,40}")
_DATE = re.compile(r"\bdate=([A-Za-z]+) (\d{1,2}), (\d{4})")
_MONTHS = {
    name: number
    for number, name in enumerate(
        (
            "January", "February", "March", "April", "May", "June",
            "July", "August", "September", "October", "November", "December",
        ),
        start=1,
    )
}


class OverlayError(Exception):
    """A setup, a name or a folder the overlay refuses; nothing has been written or removed."""


@dataclass
class Overlay:
    dir: Path
    events_file: Path
    read_line: int  # 1-based line of te_qa.1's debug_log in events_file: the debugger's breakpoint
    setup_events: dict[str, str]  # setup name -> event id ("te_qa.10", ...; "te_qa.100", ... for an added one)
    effects_file: Path | None = None
    bodies: dict[str, str] = field(default_factory=dict)    # the setups given at start, cleaned
    added: dict[str, tuple[int, str]] = field(default_factory=dict)     # an added setup -> (its slot, its body)
    revision: int = 0   # of effects_file: 0 as built, one more for each add_setup


def build(dest: Path, setups: Mapping[str, str], game_version: str) -> Overlay:
    """Write the overlay into `dest` (a folder named OVERLAY_NAME), replacing an earlier one of ours.

    `setups` maps a setup name to the Paradox script of its body, which becomes the scripted effect
    `te_qa_setup_<name>` and is run by its own hidden event. Raises OverlayError, before anything is
    written or removed, for a name or body it refuses, a `game_version` that is not text, a `dest`
    that is not named OVERLAY_NAME, a `dest` whose parent folder is not there (no ancestor is ever created,
    since `remove` could not undo it), and a `dest` that exists and is not an overlay of ours."""
    dest = Path(dest)
    if dest.name != OVERLAY_NAME:
        raise OverlayError(f"the overlay folder must be named {OVERLAY_NAME}, not {dest.name!r}")
    if not isinstance(game_version, str) or not game_version.strip():
        raise OverlayError("the game version must be text, such as '1.15.0'")
    bodies = {name: _clean_body(name, body) for name, body in setups.items()}
    if len(bodies) > MAX_START_SETUPS:
        raise OverlayError(f"{len(bodies)} setups: at most {MAX_START_SETUPS} can be given at start")
    if not dest.parent.is_dir():
        raise OverlayError(f"{dest.parent} is not a folder: the overlay goes into an existing mod folder")
    if os.path.lexists(dest) and not _is_overlay(dest):
        raise OverlayError(f"{dest} exists and is not an overlay made by game_qa, so it is left alone")

    events_text, read_line, setup_events = _events_text(sorted(bodies))
    temp = Path(tempfile.mkdtemp(prefix=f".{OVERLAY_NAME}.tmp-", dir=dest.parent))
    try:
        os.chmod(temp, 0o755)
        _write(temp / METADATA_FILE, _metadata_text(game_version).encode("utf-8"))
        _write(temp / EVENTS_FILE, _txt(events_text))
        _write(temp / EFFECTS_FILE, _txt(_effects_text(bodies, {}, 0)))
        _write(temp / SCRIPTED_TEST_FILE, _txt(_scripted_test_text()))
        remove(dest)
        os.rename(temp, dest)
    except BaseException:
        shutil.rmtree(temp, ignore_errors=True)
        raise
    return Overlay(dest, dest / EVENTS_FILE, read_line, setup_events, dest / EFFECTS_FILE, bodies)


def slot_event(slot: int) -> str:
    return f"{NAMESPACE}.{FIRST_SLOT_EVENT + slot}"


def add_setup(ov: Overlay, name: str, body: str) -> tuple[str, int]:
    """Put a new setup into the next spare slot of a built overlay by rewriting its `te_qa_effects.txt`, and
    return (the slot's event id, the file's new revision). The game runs the setup only once it has reloaded the
    file: LOADED_EVENT then logs that revision.

    Raises OverlayError, with nothing written, for a name or body `build` would refuse, a name already used (a
    setup's name is used once: its markers in the log are how its lines are found), no spare slot left, and an
    overlay folder that is no longer one of ours. The file is rewritten in place, as an editor saves it, which
    is the write the reload was verified with; if the write fails the overlay's record is left as it was."""
    body = _clean_body(name, body)
    if name in ov.setup_events:
        raise OverlayError(f"setup {name} is there already (event {ov.setup_events[name]}): a setup's name is "
                           "used once, so give the changed one a new name")
    if len(ov.added) >= SLOT_COUNT:
        raise OverlayError(f"all {SLOT_COUNT} spare slots are used: a new session starts with them empty")
    if ov.effects_file is None or not _is_overlay(ov.dir) or not ov.effects_file.is_file():
        raise OverlayError(f"{ov.dir} is not this session's overlay any more, so nothing was written")
    slot = len(ov.added)
    added = {**ov.added, name: (slot, body)}
    revision = ov.revision + 1
    text = _effects_text(ov.bodies, added, revision)
    try:
        ov.effects_file.write_bytes(_txt(text))
    except OSError as error:
        raise OverlayError(f"{ov.effects_file} could not be rewritten ({error}); the setup was not added") from error
    ov.added, ov.revision = added, revision
    ov.setup_events[name] = slot_event(slot)
    return ov.setup_events[name], revision


def loaded_revision(line_text: str) -> int | None:
    """The revision a LOADED_EVENT log line names, or None for any other line."""
    _, found, rest = line_text.partition(LOADED_PREFIX)
    rest = rest.strip()
    return int(rest) if found and rest.isdigit() else None


def check_setups(setups: Mapping[str, str]) -> None:
    """Raise OverlayError for a setup name or body `build` would refuse; nothing is read or written."""
    for name, body in setups.items():
        _clean_body(name, body)


def remove(dest: Path) -> bool:
    """Delete the overlay at `dest`. Only a real folder named OVERLAY_NAME whose metadata.json carries
    MARKER is deleted; anything else (missing, a symlink, someone else's folder) is left as it is
    and the answer is False."""
    dest = Path(dest)
    if not _is_overlay(dest):
        return False
    _delete(dest)
    return True


def leftover_builds(mod_dir: Path) -> list[Path]:
    """The folders in `mod_dir` named as `build` names its temp folders, marked or not: what a build cut short
    (killed between its mkdtemp and its rename) left. Only `remove_build` deletes one, and only a marked one."""
    try:
        names = os.listdir(mod_dir)
    except (FileNotFoundError, NotADirectoryError):
        return []
    return sorted(Path(mod_dir) / name for name in names if _BUILD_TEMP.fullmatch(name))


def remove_build(temp: Path) -> bool:
    """Delete a temp folder a cut-short `build` left, under `remove`'s checks: only a real folder named as
    `build` names them whose metadata.json carries MARKER (`build` writes it first). Anything else, an unmarked
    one included (killed before its first write: nothing proves it is the harness's), is left, and the answer
    is False."""
    temp = Path(temp)
    if _BUILD_TEMP.fullmatch(temp.name) is None or not _is_marked(temp):
        return False
    _delete(temp)
    return True


def _delete(dest: Path) -> None:
    """Delete a folder `_is_marked` vouched for, never following a symlink inside it."""
    # The marker goes last: if a delete fails midway (a file the game still holds), the folder still reads as
    # ours and the next `remove` finishes the job, where a folder with no marker would be refused for good.
    marker = dest / METADATA_FILE
    for where, folders, files in os.walk(dest, topdown=False):
        where = Path(where)
        for name in files:
            if where / name != marker:
                (where / name).unlink()
        for name in folders:
            path = where / name
            if path.is_symlink():  # os.walk lists a symlink to a folder here, and does not enter it
                path.unlink()
            elif path != marker.parent:
                path.rmdir()
    marker.unlink()
    marker.parent.rmdir()
    dest.rmdir()


def parse_date(line_text: str) -> tuple[int, int, int] | None:
    """The (year, month, day) of a log line holding `date=January 11, 1836`, or None."""
    found = _DATE.search(line_text)
    if found is None:
        return None
    month = _MONTHS.get(found.group(1))
    day = int(found.group(2))
    if month is None or not 1 <= day <= 31:
        return None
    return int(found.group(3)), month, day


def _is_overlay(folder: Path) -> bool:
    """A real folder (not a symlink) named OVERLAY_NAME whose metadata.json says MARKER."""
    return folder.name == OVERLAY_NAME and _is_marked(folder)


def _is_marked(folder: Path) -> bool:
    """A real folder (not a symlink) whose metadata.json says MARKER, read through no symlink: the marker is
    what lets a delete begin, so it must be the folder's own."""
    marker = folder / METADATA_FILE
    if any(path.is_symlink() for path in (folder, marker.parent, marker)) or not folder.is_dir():
        return False
    try:
        meta = json.loads((folder / METADATA_FILE).read_bytes().decode("utf-8-sig"))
    except (OSError, ValueError):
        return False
    if not isinstance(meta, dict):
        return False
    description = meta.get("short_description")
    return isinstance(description, str) and MARKER in description


def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _txt(text: str) -> bytes:
    return ("\ufeff" + text).encode("utf-8")


def _clean_body(name: str, body: str) -> str:
    """The body with newlines normalized, or OverlayError. The name is checked first."""
    if not isinstance(name, str) or _SETUP_NAME.fullmatch(name) is None:
        raise OverlayError(f"a setup name is a-z, 0-9 and _, starting with a letter, 41 characters at most: {name!r}")
    if not isinstance(body, str):
        raise OverlayError(f"setup {name}: the body must be text")
    body = body.replace("\r\n", "\n").replace("\r", "\n")
    if not body.strip():
        raise OverlayError(f"setup {name}: the body is empty")
    problem = _brace_problem(body)
    if problem:
        raise OverlayError(f"setup {name}: {problem}")
    return body


def _brace_problem(body: str) -> str | None:
    """What is wrong with the braces of a body, or None. A brace inside a "quoted string" or after
    a # (a comment runs to the end of its line) does not count; a # inside a string starts nothing
    and a quote inside a comment opens nothing. Strings may run over lines, as the mod's parser reads them."""
    depth = 0
    in_string = False
    in_comment = False
    for char in body:
        if in_comment:
            in_comment = char != "\n"
        elif in_string:
            in_string = char != '"'
        elif char == '"':
            in_string = True
        elif char == "#":
            in_comment = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth < 0:
                return "a '}' closes a block that was never opened, so it would end the effect early"
    if in_string:
        return "a quoted string is never closed and would swallow the closing brace of the effect"
    if depth:
        return f"{depth} '{{' never closed"
    return None


def _metadata_text(game_version: str) -> str:
    meta = {
        "name": "TE QA overlay",
        "id": "",
        "version": "0.0.1",
        "supported_game_version": game_version,
        "short_description": f"{MARKER}. Timeline Extended in-game QA script. Never published.",
        "tags": [],
        "relationships": [],
        "game_custom_data": {"multiplayer_synchronized": True},
    }
    return json.dumps(meta, indent="\t") + "\n"


def _events_text(names: list[str]) -> tuple[str, int, dict[str, str]]:
    """The events file, the line of the read event's debug_log, and the event id of each setup."""
    lines = [
        f"namespace = {NAMESPACE}",
        "",
        "# The session puts its breakpoint on the debug_log line below, then reads values at the stop.",
    ]
    lines += _event(READ_EVENT, [READ_LOG_LINE, "te_qa_pad = yes"])
    read_line = lines.index(f"\t\t{READ_LOG_LINE}") + 1
    lines += ["", "# Pads the log so the game flushes it."]
    lines += _event(PAD_EVENT, ["te_qa_pad = yes"])
    lines += ["", "# Says which revision of te_qa_effects.txt the game has loaded (add-setup rewrites that file)."]
    lines += _event(LOADED_EVENT, ["te_qa_loaded = yes", "te_qa_pad = yes"])
    setup_events: dict[str, str] = {}
    for number, name in enumerate(names, start=FIRST_SETUP_EVENT):
        event = f"{NAMESPACE}.{number}"
        setup_events[name] = event
        lines += ["", f"# Runs the session's setup {name}."]
        lines += _event(
            event,
            [
                f'debug_log = "TE_QA setup {name} start"',
                f"te_qa_setup_{name} = yes",
                f'debug_log = "TE_QA setup {name} done"',
                "te_qa_pad = yes",
            ],
        )
    lines += ["", "# Spare events for setups added to a running session: each slot's effect is empty until then,",
              "# and logs the setup's own start and done markers once it is filled."]
    for slot in range(SLOT_COUNT):
        lines += _event(slot_event(slot), [f"te_qa_slot_{slot} = yes", "te_qa_pad = yes"])
    return "\n".join(lines) + "\n", read_line, setup_events


def _event(event_id: str, immediate: list[str]) -> list[str]:
    lines = [f"{event_id} = {{", "\ttype = country_event", "\thidden = yes", "", "\timmediate = {"]
    lines += [f"\t\t{line}" for line in immediate]
    return lines + ["\t}", "}"]


def _effects_text(bodies: Mapping[str, str], added: Mapping[str, tuple[int, str]], revision: int) -> str:
    """`te_qa_effects.txt`: the pad, the revision line, the setups given at start, and every slot, the ones in
    `added` (name -> (slot, body)) with their body between the setup's markers."""
    lines = [
        "# Writes sixty log lines, so the game flushes its block-buffered debug.log.",
        "te_qa_pad = {",
        "\twhile = {",
        f"\t\tcount = {PAD_LINES}",
        f'\t\tdebug_log = "{PAD_TEXT}"',
        "\t}",
        "}",
        "",
        "# The revision of this file, one more for each setup added while the game runs.",
        "te_qa_loaded = {",
        f'\tdebug_log = "{LOADED_PREFIX}{revision}"',
        "}",
    ]
    for name in sorted(bodies):
        lines += ["", f"te_qa_setup_{name} = {{"]
        lines += _body_lines(bodies[name])
        lines.append("}")
    by_slot = {slot: (name, body) for name, (slot, body) in added.items()}
    for slot in range(SLOT_COUNT):
        lines += ["", f"te_qa_slot_{slot} = {{"]
        if slot in by_slot:
            name, body = by_slot[slot]
            lines.append(f'\tdebug_log = "TE_QA setup {name} start"')
            lines += _body_lines(body)
            lines.append(f'\tdebug_log = "TE_QA setup {name} done"')
        else:
            lines.append(f'\tdebug_log = "TE_QA slot {slot} is empty"')
        lines.append("}")
    return "\n".join(lines) + "\n"


def _body_lines(body: str) -> list[str]:
    text = body.rstrip().lstrip("\n")
    return [f"\t{line.rstrip()}" if line.strip() else "" for line in text.split("\n")]


def _scripted_test_text() -> str:
    return "\n".join(
        [
            "# Run with: -debug_mode -handsoff -scripted_tests -run_until=1836.1.4",
            f"# {FIXTURE_TEST} fails on day 2, so the engine writes",
            f'# "save games/TEST_FAIL_{FIXTURE_TEST}_2 January, 1836.v3": a fresh game with no clicks.',
            'last_date = "1836.1.3"',
            "",
            "tests = {",
            f"\t{FIXTURE_TEST} = {{",
            "\t\tsuccess = { always = no }",
            '\t\tfail = { game_date > "1836.1.1" }',
            "\t}",
            "\tte_qa_pass = {",
            '\t\tsuccess = { game_date > "1836.1.1" }',
            "\t\tfail = { always = no }",
            "\t}",
            "}",
        ]
    ) + "\n"
